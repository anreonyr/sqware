//! System Protocol — **服务编排**：整个系统中由哪些 Service 构成，以及它们如何被组织、
//! 依赖、启动、停止、替换与监督。
//!
//! 它不创造 Task。Service 的**执行载体**是 `Task`（一个域 = `Team`），载体由内核的
//! Unit ABI 产生；本协议把那些载体**组织成系统**。故两层要彻底分开：
//!
//! ```text
//!   内核 ABI（机制）     Unit                 Task 怎么创建、运行、结束
//!        │
//!   本协议（编排）       Service              系统由哪些 Service 组成、怎么运行
//!        │                                     （判定与账在本文这一侧）
//!   实现方               programs/src/system/ 起一条、看/判、放下、收场
//! ```
//!
//! # 本份有两半：编排 + 运行期命名
//!
//! ```text
//!   编排（core / desk / grant）  起停 / 判就绪 / 放下 / 配给（静态那一步：grant）
//!   运行期命名（board）          "这个名字此刻指向哪个入口"（运行期那一步：板）
//! ```
//!
//! **两半为什么同住一份**：板线程**就住在编排域里**（`root` 那张单上没有板那一格，
//! 起板的只有 `system`），而它干的正是编排的另一半——`grant` 是装配期把名字对上入口，
//! `board` 是运行期那一步。板那一台与它的装配侧住
//! `programs/src/system/board/`。
//!
//! **Unit 的生命周期不在这条正文里**——六个动词、五道门、血缘、两阶段扑杀那份叙述
//! 整体降级为本文末的附录《Unit 生命周期（内核 ABI 的叙述）》：它是本协议的**载体**
//! 说明，不是本协议。载体哪天换掉（比如容器、远程执行体），服务编排的语义一个字不用改。
//!
//! # 与 Principal 是两条正交的轴
//!
//! ```text
//!   System Protocol      "系统里运行什么、怎么运行"   → Service
//!   Principal Protocol   "这个请求代表谁"            → Policy ID
//! ```
//!
//! 一个 Service 可以承载多个策略主体，一个主体也可以横跨多个 Service——两者**没有
//! 所有权关系**。System 也不知道 Policy ID 是什么；它只知道"这个 Service 的状态"。
//!
//! **System 与 Principal 都不是 Service 类型**：它们是横跨整个服务世界的两条系统协议。
//! 具体协议（驱动、操作者……）才各自是一种 Service，各自暴露自己那一片东西。
//!
//! # 一、Service 是什么
//!
//! ```text
//!   Service
//!   ├── identity      名字（清单名，≤ 31 字节）
//!   ├── instance      这一次运行的载体：域（Team）+ 代表线程（Task）
//!   ├── state         Starting / Ready / Stopping / Dead
//!   ├── dependency    我起之前必须已经就绪的那些 Service
//!   ├── supervisor    谁负责在我死后处理我（= 起我的那一方）
//!   └── lifecycle     起 → 就绪 → 停 → 死
//! ```
//!
//! 六个动作：**start**（起）/ **stop**（停）/ **restart**（再起一个）/
//! **supervise**（盯着）/ **dependency**（依赖）/ **replace**（换掉在跑的那一个）。
//!
//! ## 这六样没有一样在内核里
//!
//! | Service 概念 | 内核里有对应物吗 |
//! |---|---|
//! | 名字 | **没有**——内核不记名字（`Build` 也不收它）；本协议的名字住在装配账里 |
//! | 实例 | 有 `TeamId` + `TaskId`——可 `TeamId` 在动作面上只够得到"我生的那一格"（见 §七） |
//! | 状态 | **没有**。内核只有任务自己的存活与是否收尾完毕，没有"服务就绪"这回事 |
//! | 依赖 | **没有**。内核的父子链只记血缘，不记"谁等谁" |
//! | 监督者 | **没有**。父子链是唯一的责任边，而它只意味着"能杀" |
//! | 生命周期 | 内核只有 Unit 的（产 → 跑 → 停 → 回收），Service 的由本协议定义 |
//!
//! 这一格一格都空着，正是本协议存在的理由：**Service 的世界是凭空造出来的一层**，
//! 由编排者（Server）自己记账维持，内核既不知道也不需要知道。
//!
//! # 二、编排者：Server 是谁、跑在哪
//!
//! **System Server 是一个独立域**（`prog-system`，由引导域 `root` 起）——引导域只做
//! **固件那一层**的事：读 boot 的两块账、把字节与门闩按单子交出去、退出即停机。
//!
//! **照实记（这段曾经写反）**：原注说"Server 就是 root 域"，理由是"建域那道门是 S 态，
//! 另立一个域就有两个能建域的顶层域"。这一条**两头都不成立**了：
//!
//! - 建域那道 S 态门**已经删了**（`env::fid::UnitCall::Build` 的门那一段照实记着：判据
//!   分家，"能不能"归内核、"该不该"归本协议），故"另立一个域"不需要 S 态；
//! - 就算那道门还在，"另立一个域"也只是多一个**子域**——子域不是顶层域，"内核只引入
//!   一个顶层域"这条根本不涉及它。
//!
//! 于是编排者可以是一个普通域（今天它就是）：`root` 起它、把"清单 + 全部镜像那一块字节"
//! 与"按单子发货"那条路交给它。内核依旧只引入一个顶层域。
//!
//! Server 的账（服务表）是**它的私有状态**，不在内核里：
//!
//! ```text
//!   服务名 ──▶ { 域 TeamId, 代表线程 TaskId, 状态, 依赖 }
//! ```
//!
//! 这张表丢了 = 编排没了（Service 还活着但没人管）。故它是**单点**，这一点照实写在
//! §八。服务名是清单名（装配侧决定，≤ 31 字节），Server 在起它那一刻读进表里。
//!
//! # 三、起一个 Service
//!
//! 四步，顺序是契约：
//!
//! ```text
//!   1. 建域        按镜像与名字建出域（空壳，无线程）
//!   2. 产代表线程   产它的主线程，此刻它一步都还没跑
//!   3. 塞门闩       把它要的门闩一件件塞进它手里（它还是没跑）
//!   4. 放行         它开跑
//! ```
//!
//! **第 3 步之所以能成立，全靠"未放行"这个窗口**——线程产出后不会先于放行运行，
//! 所以父方可以从容授权。这是载体提供的能力里最不可替代的一条：先给权，再让它跑，
//! 于是 Service 启动时手里已经是齐的，不必"先跑起来再求权限"。
//!
//! ## 就绪由 Service 自己宣布
//!
//! 内核**不知道"就绪"是什么意思**——装好门闩算就绪？还是发出第一句回答才算？
//! 这是 Service 的语义，只有它自己知道。故约定是：**Service 装好后，回手交给 Server
//! 一枚通道**（"我好了，有事从这里找我"）；Server 扫到它就认为它就绪。
//!
//! Server 侧的等待必须**同时**看着两件事，因为 Service 可能死在半路：
//!
//! ```text
//!   循环 {
//!       扫到那枚通道            → 就绪
//!       查出代表线程已回收      → 它没了 ⇒ 启动失败（按 Server 自己的策略处理）
//!       否则：让出处理器或短等
//!   }
//! ```
//!
//! 第二格不能省：**一个卡在初始化里死掉的 Service，不会给 Server 任何消息**
//! （它退场时那句话是打给调试控制台的，不是打给 Server 的）。不给第二格，Server
//! 就会一直等一个永远不来的通道。
//!
//! ## 依赖是策略，顺序由 Server 排
//!
//! ```text
//!   驱动就绪 ──▶ 文件系统起 ──▶ 终端起
//! ```
//!
//! 这张"谁等谁"的图**完全在 Server 的账上**，与内核的父子链无关。内核能表达的关系只有
//! 一种：父子（谁生的）。依赖图不是父子图的投射——B 依赖 A 而 A 不是 B 的父亲，
//! 是常态。
//!
//! # 四、停一个 Service
//!
//! **停 = 编排者主动收掉它**（自杀是 Service 自己的事，不属于"停"）。语义是**域粒度**：
//! 停一个 Service 就是收掉它那个域连同它的全部后代线程——不会剩半个 Service 在跑。
//! 这是载体白送的一条：他杀与级联收的是整棵子树。
//!
//! **不等它收完**：下令即回，"停了"这件事由 Server 之后自己看（见 §五）。要等有等待面，
//! 但"停"这个动作本身不等。
//!
//! # 五、监督
//!
//! Service 死了，**内核不会通知任何人**——载体的世界里没有事件出口，只有"等/探一个
//! 具体的线程"。故监督在第一版里只有两种形状：
//!
//! - **一个 Service 配一条等待线程**（阻塞等它回收）；
//! - **Server 定期轮询**每个在跑的 Service。
//!
//! 两条都是"Server 主动问"，没有"内核推给 Server"。这条限制决定本协议能承诺什么：
//! **监督的及时性由观察面决定，不由内核决定**。
//!
//! 今天跑着的那一套把这件拆成"看"与"判"两半（见 `programs/src/system/server.rs`，
//! 板线程与等待线程都住在编排域里）：
//!
//! - **看**：不是"一条服务配一条等待线程"（`Join` 的门只认"同域 或 在我 `heir` 里"，
//!   中间人两条都不占），而是由**板**这类中介盯着"客人开的那扇门还在不在"——门封印即
//!   投信，编排者挂在一只组上等任一道响，**零轮询**；
//! - **判**：`service::until`，形状是**问 → 等 → 问**。判决只认那两次非阻塞问
//!   （`Join{task, 0}` 答"收尾完了没有"，唯一置位路径是退场链上那一步）；挂起过的那一问
//!   读回的是**预置值**，不含信息——把它当判决就是曾记过的"他杀偶发不生效"那笔错账。
//!
//! 内核依旧只回答"这一枚线程收尾了没有"；"谁死了、要不要重起"全在 Server。
//!
//! 服务死了之后怎么处理（重起、放弃、告警）是 Server 的策略；本协议只规定"Server
//! 必须能发现它死了"，不规定发现之后干什么。
//!
//! # 六、replace / restart（**两半都落了**：载体那一格 + 重发那一半，见下）
//!
//! "换掉在跑的那一个"要分两步：让旧实例退场，再起新实例。
//!
//! **第一步今天做得干净了**：父方有了"放下子域"的动作（`UnitCall::Oust`）——它摘掉父方
//! `heir` 里那一格、放掉那份强引用，前提是**那域里没有还没收尾的线程**（否则答 `Busy`）。
//! 于是"每重启一次留一个死域的壳"这条不再成立。表这一侧也备好了：`Slot` 是**最近一次
//! 实例的坐标**，死亡记账**不清它**（见 §一）⇒ 重启时"上一个实例是谁"读得出来。
//!
//! **重发那一半已经走通**（照实记：`harness/src/again.rs` 在**同一张表的同一行**
//! 上起了三次，`restarts=2 failures=0`）。序列是 **stop → watch → Oust → spawn → start**，
//! 其中有两处暗礁，都是这台子第一次跑出来的：
//!
//! - **`until` 不落地状态**：`stop` 只把 `State` 推到 `Stopping`，把 `Dead` 写进表的是
//!   `watch`（`until` 答 `Unsettled` 时"一个字都不写"）。少了这一步，`admit_start` 就按
//!   `Stopping` 把重发拒掉——实测第一版正是 `r=2 step=spawn REFUSED`。
//! - **不许再 `register`**：行是**复用**的（`register` 遇重名即 `Unknown`）；`admit_start`
//!   本来就允许 `NeverStarted | Dead`，身子由 `Table::attach` 换，`Slot` 记住的旧坐标
//!   正好给 `Oust` 用。
//!
//! ## 预算与放弃（**已裁：协议不给，Server 自己数**）
//!
//! 两格都留着不动，理由是它们都属于**策略**，而 `State` 只描述**实例的生命阶段**：
//!
//! - **有界预算**（试几次算放弃）：**Server 侧记账**。协议为它加一格就等于把"试几次"
//!   写进 ABI，且每个 Service 的合理次数并不一样（通道服务与回显服务不是一回事）。
//! - **放弃之后算什么**：**复用 `State::Dead`**。放弃了仍然是"起过、现在死了"——
//!   真实且可读；"不再重发"是 Server 的决定，不该在表里另立一格（立了还要决定
//!   `admit_start` 是否拒绝它，那又把策略拽回协议）。
//!
//! Server 侧配方（可抄；`again` 台子跑的就是它）：
//!
//! ```text
//!   let mut tries = 0;
//!   loop {
//!       if watch(&mut table, name, MS)? {          // 死了 ⇒ 先把 Dead 落地
//!           if tries >= BUDGET { break }           // 放弃：不再重发（表里就是 Dead）
//!           if let Some(Slot::Live { team, .. }) = slot { oust(team)? }   // 放下旧域
//!           spawn(&mut table, name, elf, kind)?;   // 同一行重发
//!           start(...)?;
//!           tries += 1;
//!       }
//!       sleep_until(next)?;                        // 绝对到点，不漂（见 Chrono 那门）
//!   }
//! ```
//!
//! 判据：放弃之后**表仍答 `Dead` 且 `Slot` 还留着旧坐标**（`Dead` 与坐标并存是合法的），
//! 所以"它是什么"随时读得出来；而"要不要再试"只有 Server 知道。
//!
//! ## 空位：disown（**未定，先搁置**）
//!
//! "把这个 Service 的责任转给别人"（`disown`）今天**没有**，而且不只是一个参数问题——
//! 它要动三处：父方那张表要能**摘**（今天只有入、没有出）、新父亲那张表要接、子方
//! "我从哪来"那格要改（今天构造期定型、不可改）；且**空域不能转**（它唯一的持有者
//! 就是父亲，一摘就没了，故必须在产出线程之后才能转）。
//!
//! 最难的一格是权限判据跟着谁走：登记信息仍记"当初谁生的"，而权力要不要跟着走——
//! 跟着走则"生的"这个事实丢掉，不跟着走则 disown 等于没做。**这一格没定，故整个动作
//! 搁置**；§九 的收域那一枚与 §二 的"父亲 = 调用者"都因此保持今天的形状。
//!
//! **同一族里已经删掉的一格**（交接那一族收口那一刀）：台账上那个 `desk::hand_over`
//! （"记下它交回的通道"）**一处调用都没有**，它唯一写的那一格 `Service::root` 全仓没有读者，
//! 而它服务的 `Announce::Channel` 也没有任何清单在用（`Ready::Pending` 走不到）⇒ 那一手删了。
//! `root` / `Channel` / `Pending` 三块**没有一起删**：它们与 `disown` 是同一个问题的两面
//! （谁宣布、谁接手），归这一节。
//!
//! # 七、服务名与"代表线程"
//!
//! **名字不是身份。** 名字由装配侧决定、内核不解释、也不保证跨父唯一；能不能按名字
//! 找到 Service，取决于 Server 那张表，而不是内核。**要找服务得先有目录**——今天那本
//! 目录就是 [`board`]（公示板：运行期把名字对上入口；与装配期的 `grant` 是同一个问题的
//! 两半）。本协议这一节只说"Server 的表里，名字唯一"。
//!
//! **代表线程是约定，不是内核字段。** "哪一枚 Task 代表这个域"完全是 Server 记账的
//! 结果（约定 = "建域之后第一枚被放行的线程"）；内核里**没有这个字段**。后果是：
//!
//! - Server 必须**自己记住**每枚代表线程的 id（起它时拿到的那个返回值）；
//! - **`TeamId` 只够得到"我生的那一格"**：`Spawn { team }` 与 `Oust { team }` 都在调用者
//!   自己的 `heir` 里查 ⇒ 想"等 / 放行 / 杀"别人家那个域，手上必须有一枚它的 `TaskId`：
//!   枚举出来的域（`Heir { index }`）在**这三条**动作面上仍是死端。
//!
//! 故本协议把这条约定写死：**代表线程 = 该域建好后第一枚被放行的线程**。将来若内核
//! 愿意给域一个"代表"字段，这条就搬家，正文其余部分不动。
//!
//! # 八、已知边界（照实写，不是待办）
//!
//! - **Server 是单点**：编排状态只在编排域那一张表里 ⇒ 它死了，全部 Service 随级联
//!   一起收场（它的父是引导域，级联一路收到底）。这说明系统的一生 = 引导域的一生，
//!   但也意味着**编排状态没有第二份**。
//! - **没有全量替换**：只能停一个起一个，没有"停机窗口内整体切过去"这种东西。
//! - **没有持久化、没有重启**：系统退完即停机，一次会话就是系统的一生。跨会话的
//!   服务身份没有对象可引用。
//! - **没有服务发现**：Service 拿到的门闩是启动前塞进去的（§三 第 3 步），
//!   第一版不定义"运行期我怎么找一个服务"。
//! - **没有依赖图校验**：环、缺依赖、起不来——都由 Server 自己发现，内核不参与。
//! - **零个 Service 是合法初态**：机器可以一个域都没有而正常停机（见附录 §起点）。
//! - **就绪的定义在 Service 手里**：Server 只能等它宣布，不能替它判断。
//! - **没有护栏**：收一个域不需要任何凭证，也不需要血缘（§九）⇒ 任何域都能拆掉
//!   任何域。这是"内核不裁决"的直接代价，收窄要在编排侧做。
//! - **Mint 能起什么，由清单决定**：申请者只能给名字，给不了程序（§九）⇒ 装机时没打进去
//!   的程序，运行期谁都起不出来——包括 Server。
//!
//! # 九、一枚专有动词：Mint（收域那一枚直接用内核的 `doom`）
//!
//! 载体的动词是**内核的通用机制**（收字节、执行、按域判活）。本协议在这之上只有**一枚
//! 自己的动词**——它不是通用机制，是编排这套东西用的：
//!
//! ```text
//!   Mint(名字)         造一个 Service：按名字建域 + 产它的代表线程（恒产未放行）
//!   收域               `room::doom`（**内核的词**，本协议不为它另起名）
//! ```
//!
//! **照实记（收域那一枚原先叫 `Ruin`，用户裁定去掉）**：`Ruin` 那个名字**没有多出任何意思**
//! ——它的落地 `call::ruin` 通体只有一行 `room::doom`（连错误都是吞掉的，因为"目标已经不在世"
//! 视作收到），而这里原写的那句"两枚都**不住在内核的通用动词里**"对它本来就不成立。故
//! **撤名对齐**：内核叫 `doom`，本侧也叫 `doom`。
//!
//! 两枚**共用内核的执行面**：`programs::system::server` 的 `build` 就是 `unit::build`、
//! `doom` 就是 `room::doom`——**同一枚动词**，内核并没有为它们各加一条入口（加了就有两个执行
//! 面，判据会被抄成两份）。判据因此全在本协议这一侧，内核只答"能不能"。
//!
//! **照实记（那一格原先住 `programs/src/system/call.rs`）**：那七手（建域 / 产线程 / 塞门闩 /
//! 放行 / 收域 / 判收尾）原先是独立一份 `call.rs`，而它们的**唯一读者就是 `server.rs`** ⇒
//! 已收进那个文件（`system::server` 的头注记着这一刀）。
//!
//! ## Mint：把"传字节"换成"传名字"
//!
//! | | 载体的建域（`UnitCall::Build`） | Mint（本协议） |
//! |---|---|---|
//! | 谁能用 | **任何 Task**（S 态门已删，见 §"五道门"） | **任何 Task** |
//! | 传什么 | 镜像字节（≤ 8 MiB） | 申请者给**名字**（≤ 31 字节）；查清单的是 **Server** |
//! | 镜像从哪 | 调用方内存（**不可信**） | Server 手里那份**内核打包清单**（**可信**） |
//! | 特权级 | 清单编码，调用方转交 | 同一个清单编码，Server 转交 |
//!
//! 所以 Mint **不是**"放开了建域"，而是**换了一种更紧的建域**：申请者只交出名字，
//! 交不出字节；能建出什么，仍然完全由装配期那张清单决定。**"任何 Task 都能建"不构成
//! 提权**——提权的两条路（自封特权级、塞任意镜像）都还堵着。
//!
//! **今天实现的是 Mint-lite**：申请者 → Server 那一段是名字，Server → 内核那一段**仍是
//! 字节**（`service::mint(table, name, entry.elf, kind)` 的 `entry.elf` 取自清单）。内核
//! **不按名字查**（见本文件前面"名字"那一条）；查的是拿着清单的 Server。把这一段收进内核
//! （内核按名字取镜像、调用方连字节都见不到）是**下一版**的事——今天"更紧"靠的是 Server
//! 只肯交清单里的那一份，不是靠内核拒收字节。内核侧 `UnitCall::Build` 的注里那个
//! "Mint-lite 口径"，指的就是这一段。
//!
//! 父亲 = **调用者自己**（今天唯一的选择，见 §六 disown 的空位）。故产出的那个域在
//! 血缘上归调用者；调用者死了，它也随级联一起走。
//!
//! 产出的线程**恒为未放行**（与载体的建域一致）：调用者先塞门闩，再放行。
//!
//! ## 收域那一枚：`doom`，不靠血缘也能收
//!
//! 载体原来的"他杀"判据是血缘（目标域得在我后代链里），**那道门已删**（见 §"五道门"
//! 那张表的原形状说明）。故 `doom` 不必再造一道：任何 Task 都能收任何域。内核在这条路上
//! **不做判断**——它只执行，不裁决。
//!
//! 为什么要有这么一条：**一旦有域不归任何人管，"没人有资格收它"就是个洞**（§六 的
//! disown 一落地就会造出这种域）。`doom` 是给系统留的那个"收掉没人管的东西"的手段。
//!
//! **代价照实说**：没有任何 Task 站在特权的裁决位上 ⇒ **服务之间没有护栏**（任何域
//! 都能拆掉任何域）。这一版接受它：内核不裁决，规矩由本协议与 Policy 各管一段
//! （§十）。要收窄，只有在编排侧加"谁能申请收谁"的规矩——**那不是内核该长的东西**。
//!
//! 收不掉的两种情形（判活，不是判决）：目标从未入册 / 已经不在世。
//!
//! ## 与老动词的关系
//!
//! **不是两条路，是同一枚动词的两个调用者**：Server 走 ABI 的 `UnitCall::Build` /
//! `RoomCall::Doom`；引导期的内核**不经 ABI**，直接调 `work::unit::build` 造 root 域
//! （`boot.rs`，`Doom` 那条今天只有运行期用）。判据分家之后内核**两个都不审**（"能不能"
//! 恒答"能"），该不该起 / 该不该收全在调用者那一侧：引导期由内核的引导代码决定（它手里就
//! 有镜像），运行期由 Server 按服务表决定。于是"护栏"这件事在两端都落在**调用者**身上
//! ——见 §八 的"没有护栏"。
//!
//! # 十、本协议不负责的
//!
//! - **请求代表谁** → Principal Protocol。
//! - **门闩怎么传、消息怎么走** → 通信与权柄那两份（载体面）。
//! - **Service 内部能做什么** → 各具体协议（驱动暴露硬件、操作者提供高层语义……）。
//! - **该不该起、给多大权** → 装配策略；Server 执行它，但本协议不定义它从哪来。
//!
//! ---
//!
//! # 附录：Unit 生命周期（内核 ABI 的叙述）
//!
//! 以下是**载体**的说明：Unit = `Task | Team`。本协议用它们承载 Service，但不定义
//! 它们。实施面全在内核 ABI 上（`env::fid` 的 `UnitCall` 整类 + `RoomCall` 的
//! `Reap` / `Doom`；判别号与载荷见那边，此处不重复）。
//!
//! **上面那两枚建立在这份机制之上**（§九）：Mint 用"建域 + 产线程 + 放行"，收域用
//! "他杀 + 级联"；它们替掉的是**判据**，不是机制。
//!
//! ## 词汇（两处撞名在这里说清）
//!
//! - **Unit = `Task | Team` 的合称**。代码里**没有 `Unit` 这个类型**，此处用它指代
//!   两者。
//! - `runtime::core::unit` 是**另一件事**：域内产线程跑闭包、把结果取回来。撞的是词
//!   不是事，**不改名**，此处声明区分。
//! - **`Spawn` 只有"产 Held"一个意思**：内核侧曾有一枚同名别名（`TaskBuilder::spawn`
//!   = `hold` + 放行），已删——放行是单独一步（ABI 的 `Hatch`，内核的 `Task::release`）。
//!
//! **六个动词**：`Build` / `Spawn` / `Hatch` / `Join`（class 1）+ `Doom` / `Reap`
//! （class 0）。另有四个只读观察面：`SelfId` / `Sire` / `HeirCount` / `Heir`。
//!
//! **class 0 里还有四枚，都不是本协议的动词**，但**不是同一条理由**：`Starve` / `Park`
//! 的"身份"只是调度器认识的那一个（键由调度侧命名，域侧无从命名）；`Wait` / `Wake`
//! 的键来自**调用方自己的空间**——跨域无意义。它们是 class 0 的第二类操作。ABI 枚举
//! （`RoomCall`）归内核的**归属轴**，协议的分界划在**操作**上，不划在枚举上。
//!
//! ## 五道门，一道都不走 Pie（**这张表记的是原形状**）
//!
//! 建域与他杀那两道的判据**已经搬到编排侧**（本协议的两枚专有动词，§九）：机制本身
//! 不再设门——内核只回答"能不能"，"该不该"归本协议。表里其余三道（产线程 / 放行 /
//! 等结束）仍在载体这一侧，未动。
//!
//! | 操作 | 门 |
//! |---|---|
//! | `Build` | 调用方是 S 态域——**特权级**；能力面不为建域背书 |
//! | `Spawn` | 目标 team ∈ 我 `heir`，或本域（`TeamId(0)`） |
//! | `Hatch` | 同域，或在我 `heir` 里 |
//! | `Doom` | 目标域是我沿 `sire` 链可达的**严格后代**（**传递**，按**域**判） |
//! | `Join` | 同域，或在我 `heir` 里（目标已消失时不核） |
//!
//! `Reap` 没有门：它只能对自己——"我不再续跑，来收我"的自退声明，不带目标参数。
//!
//! `Doom` 的负码只有一枚（那是**判活**，不是判据）：
//!
//! - `-2 Dead`：目标从未入册（名册升不起），或它所属的域已经不在世（域里已没有还没收尾的
//!   线程）——两条都是"它已经死了"，故与"入土之后名册升不起"同一条口径。
//! - **没有 `-1 Denied`**：血缘门删掉之后 `Doom` 没有任何"不让你收"的判据（任何域都能收
//!   任何域，见 §八 的"没有护栏"）。曾经那一支答的是"不在血缘里"，今天**不可达**。
//!
//! `-2` 的本义是"资源已封印"（码的单一真相在**属主域的词表**——`PieFail::Dead` 的判别值
//! 就是那一格的值）；用在这里是
//! **借号**——"目标不在世"与"资源不能用了"恰好同码。这是现状的账，不是设计。
//!
//! ## 边界动词与边界内动词
//!
//! 六个动词里只有两个动**血缘这张表本身**，其余四个在既有边界内动作：
//!
//! | 动词 | 目标的存活与归属 | 动没动边界 |
//! |---|---|---|
//! | `Build` | 造出新域，`sire` 非空 ⇒ 立即入 `sire.heir` | **动**：边界 +1 个成员 |
//! | `Doom` | 目标域是我沿 `sire` 的严格后代，连子树一起收 | **动**：边界内实体整体消失 |
//! | `Spawn` / `Hatch` / `Join` | 只作用于我 `heir` 里的、或本域 | 不动：边界内 +1 线程 / 放行 / 观察 |
//! | `Reap` | 只能对自己 | 不动（作用于自己） |
//!
//! 这条分界横切 ABI 的 class（`Build` 在 class 1、`Doom` 在 class 0）——再次说明
//! 协议的分界不跟着枚举走。
//!
//! ## 血缘
//!
//! `Build` 时 `sire` 非空 ⇒ 立即入 `sire.heir`（构造期闭合，只有一个写点）。父方强
//! `heir`、子方弱 `sire`，是防环唯一边。`heir` **只增不减**——它记的是"生过多少个子域"，
//! 不是"有几个活着"。
//!
//! 只增不减不是顺手：**它就是 `Spawn` 授权凭证一直在的原因**（"我生过 ⇒ 我永远是
//! sire"）。代价是那张表随子域数量长——它撑命（无线程的空域靠它活），也占位
//! （永不回收，见本协议 §六）。
//!
//! ## 终止与回收分两段
//!
//! `Doomed` = 已停摆（退出钩子未跑）；`Reaped` = 收尾已完成（唯一置位路径是退场链上
//! 的收尾那一步 ⇒ "等结束"的判据不含竞态）。回收（栈 / trap 帧 / 空间）留到埋掉那一步。
//! 父被回收时，退出钩子沿 `heir` 两阶段扑杀整棵子树：先让全部受害者停摆，再逐个跑
//! 钩子——阶段边界即安全边界。
//!
//! ## 起点：内核只引入一枚
//!
//! 顶层 Unit（今天只有 root）由内核直接引入、`sire` 为空 ⇒ `Doom` 的判据恒假 ⇒
//! **没有任何调用者能对它 `Doom`，包括它自己的域**。它的收场只有一条路：**自己 `Reap`
//! 自己**（自退触发级联，把剩下的 `heir` 一起收掉）。唯一的例外是内核的紧急路径——
//! 它不以血缘为门，故不受这条保护。
//!
//! 引入这一枚的动作**不经门、也不由任何域发起**（那一刻还没有域）：内核自己装配它。
//! 故"第一个域是谁"这个问题在协议里没有答案，答案在内核。**零个域也是合法初态**——
//! 机器可以一个域都没有而正常停机（内核的停机判据承认"还没有任何任务"这一态）。
//!
//! ## 已知边界
//!
//! - **`TeamId` 不是存在性坐标**：它只增不减、又被父的 `heir` 强持有 ⇒ 在父**放下**它
//!   之前读出来永远"在"（放下之后 `Heir` 不再报它，见 `UnitCall::Oust`）。故 `Doom` /
//!   `Join` 只认 `TaskId`；`Build` 之后没 `Spawn` 的空域没有单独终止的手段，它随父收场。
//! - **`Doom` 的判活是域粒度**：目标那枚线程还在册就够；随后按"该域里还有没有没收尾的
//!   线程"判——没有了答 `Dead`（不再"答成功却什么都没做"）。
//! - **观察一层**：观察面只有 `Sire`（一层）与 `Heir*`（直接子域）⇒ 调用方无法预知
//!   "谁能杀谁"；`Doom` 已无血缘门（见 §九）。
//! - **终止有四个来源，只有两个走 ABI**：六个动词之外，还有两条**内核自己**的路，
//!   都不经任何 ABI 动词——① **紧急路径**（如不可解析的缺页）直接置故障码后退出，
//!   血缘、门、调用者意愿一概不问；② **级联**（父被回收 ⇒ 沿 `heir` 两阶段扑杀整棵
//!   子树）。三条内核原因码与域自己的编号共用同一字段，值域不重叠（域从 1 起，
//!   内核占高位段）。
//! - **名字会撞，且两个名字不是一回事**：**清单名**（装配单里那一段）与 `@unit-address`
//!   （设备树/清单里**节点的 basename**）。清单侧保证"同父下不撞、跨父不保证"；**内核里
//!   根本没有名字这一格**——两处名字都在用户态，内核不看名字做任何判断。
//!
//! 策略（该不该杀、该给什么身份）不在这里：**内核只回答"能不能"**。

