//! Coalition Protocol — **策略结盟**：一组身份共同参与一件事。
//!
//! 它是身份之间的**横向**关系（[`system::principal`](super::principal) 那一条是**纵向**的：从谁而来）。
//! 它不定义权限、不产生 PrincipalId、不发 Pie、不解释成员资格的含义，也不负责**发现**——
//! 它只回答一个问题：**这一组身份里有没有它。**
//!
//! # 一条关系、两个方向、三格写三格读
//!
//! ```text
//!   盟籍   PrincipalId ──→ CoalitionId      这条身份在哪些盟里      bloc(p)   核心 + 上线
//!          CoalitionId ──→ PrincipalId      这枚盟里有谁            band(c)   核心 + 上线
//!   号     0 .. next                     铸过就一直在（没有墓碑、没有 id 表）
//! ```
//!
//! **只有一张表**：反着念就是第二个方向。principal 要三个轴名（名册 / 谱系 / 转换），是因
//! 为它真有三张表；这里不起多余的轴名。
//!
//! **号**（`CoalitionId`）是服务发的一枚裸号，铸过就一直在："这枚盟存在"= 号落在那枚计数器
//! 之下。故**空盟合法**：铸一枚空盟什么也不产生，也没有"散掉"这回事。
//!
//! # 六条原语
//!
//! | 原语 | 字 | 干什么 | 钥匙 | 上线 |
//! |---|---|---|---|---|
//! | [`Coalition::found`] | 立 | 铸一枚新号（空盟） | 发送者**已绑定**（适配层） | 是 |
//! | [`Coalition::enter`] | 入 | 把**发送者此刻代表的那条身份**放进 `c` | 发送者那一格 | 是 |
//! | [`Coalition::leave`] | 出 | 把它从 `c` 拿出来（撞空也成） | 发送者那一格 | 是 |
//! | [`Coalition::amid`] | 在 | `p` 在不在 `c` 里 | 无（读是公开的） | 是 |
//! | [`Coalition::band`] | 员 | `c` 的成员（**一趟取窗**：号序 + 阈值游标） | 无 | 是 |
//! | [`Coalition::bloc`] | 籍 | `p` 的盟籍（同上） | 无 | 是 |
//!
//! **写只有三条，读全是公开的**：答案不是秘密，本协议不授予任何东西——故读那三条里
//! **没有"对端说了不"这一档**，唯一会答的失败是"这枚号没铸过"（[`Fail::Unknown`]）；
//! [`Coalition::bloc`] 连这一格都没有（`p` 不在任何盟里就是空串，一个诚实的答案）。
//!
//! **`found` 没有失败域**：它只动一枚计数器（不分配、不校验）⇒ 全族唯一一条**不可失败**的原语
//! ——说的是**核心那一条**（[`Coalition::found`] 收不到任何失败理由）；**线上那一格 `FOUND` 还要
//! 先过 `who` 闸**（发送者没绑过就答 `UNKNOWN`，见下面那张表里那一行）。[`Fail::Full`] 只被
//! [`Coalition::enter`] 用。
//!
//! # 裁决（连同被否项一起记）
//!
//! ## K1 键 = **身份**（`PrincipalId`）
//!
//! 盟籍是**身份**的属性，不是任务的属性。回报是一条免费的定理：表里存的从来是号，故
//! **`adopt` / `waive` 自动改变这个任务问到的东西**——领了 `q` 之后问到的是 `q` 的盟籍，
//! 弃了又问回起点的；一行都没搬，零迁移代码。（`p` 自己那一行也原样在：出的是"这一对"，
//! 不是"这个人"。）
//!
//! **被否**：键 = TID。那样两条轴从此不相交（结盟退化成"任务之间的标签"），而你给这条轴
//! 的定位是"一组**身份**共同参与一件事"。
//!
//! ## K2 **无主**
//!
//! 盟没有主人那一格：`dissolve`（散盟）/ `expel`（逐）/ `admit`（代他人报名）三条**因为
//! 没有可判的钥匙**一律否——"谁有权散盟""谁有权除名"两句都答不出来。这在结构上的落点是
//! **一格不存在的字段**（对照 `Principal` 的 `assembler`），在失败域上的落点是**没有 `Denied`**。
//!
//! **被否**：记一格 `founder`。它会给那三条一把**可查**的钥匙（`resolve(发送者) == founder`，
//! 同 `derive` 那款判据），代价是记了一格没人读，且横向轴一旦有主，就与纵向的"父"形状重复
//! ——两条轴的分野就糊了。
//!
//! ## K3 号由**服务**铸
//!
//! [`Coalition::found`] 无参 ⇒ 服务发号（同 principal P5 的"号只能由 Server 发"）。
//!
//! **被否**：号由客人选（`found(c)` 占号）。发现虽然免费，但号就成了"约定的名字"（与 P5 形状
//! 冲突），还得另定重号怎么办。**代价照实记**：把号送到别人手里**不是这份协议的事**——
//! 见下面"发现不是本协议的事"。
//!
//! ## K4 空盟**一直存在**
//!
//! 铸了就一直在（同 principal 的"节点永不删"）：空盟合法，[`Fail::Unknown`] 恒等于"这枚号
//! 从来没铸出来过"，不需要墓碑。
//!
//! **被否**：最后一个成员走掉即消亡——省号空间，但要答"从前有没有过"就得立墓碑，
//! 两件事混进同一格。
//!
//! ## K5 **幂等**
//!
//! `enter` 两遍、`leave` 两遍都答 `OK`：集合没有"第二次"这件事。
//!
//! **照实记**：这一格与 `Principal::unbind` 的撞空**不同**——那边答 `Unknown`，因为名册是
//! **账**（"这一格本来就没有"值得如实回答，撤一格是记账动作）；这里是**集合**，进与出都是
//! 集合运算。
//!
//! ## K6 `amid` **带 `p`**（问"这一位在不在"，不是"我在不在"）
//!
//! 同 P3 的翻案：服务想问的正是"**这位客人代表的那条号**在不在我的盟里"，而那个 `p` 是它
//! 自己 `Resolve` 来的。做成无参的"我在不在"，读这一侧也得过名册——把唯一那条公开读变成
//! 有依赖的读。
//!
//! ## K7 结盟服务是**身份服务的客人**
//!
//! 依赖方向单一：它起手在树上 `FIND "/sys/principal"` 拿一份 `Face`，每条
//! **写**原语嵌一次 `Resolve(发送者)`；**读**那一条不问名册。
//!
//! **照实记两件事**：① 这里**有先例**（编排域自己就是身份服务的客人），**"在伺候一位客人的
//! 半路上再去问另一位"也不是第一次**——树的门禁早就是这样（它回答一位客人时去问名册 / 盟册，
//! 见 `operator/server.rs` 的 `judge`）。本域与它同形，差别在**位置**：门禁是"这一格要不要判"
//! 才走，本域是**每一条写**都要先过名册；
//! ② 嵌套问答期间**本域的门是没人的**（单线程、门牌单槽）：代价是延迟，不是正确性。
//!
//! **被否**：① 两张表同域（载体做得到——孔按"任务 + 记号"建，一台域能解封第二枚；否它的
//! 不是机制，是分层：那样"结盟依赖身份"就从协议的依赖降成装配时的巧合，正文的意义取决于
//! 汇编者把两台服务放进了哪个域）；② 帧里带"我是谁"（自报标签，与 P6"报文里没有'我是谁'
//! 那一格"直接冲突）。
//!
//! # 命名（向 principal 看齐）
//!
//! **4 字母单数访问器**（`sire` / `clan` / `heir` 那一族），**字 = 英文词义**：
//!
//! | 原语 | 字 | 英文 | 字母 | 形态 |
//! |---|---|---|---|---|
//! | [`Coalition::found`] | 立 | `found` | 5 | 动词 |
//! | [`Coalition::enter`] | 入 | `enter` | 5 | 动词（主语 = 发送者） |
//! | [`Coalition::leave`] | 出 | `leave` | 5 | 动词（同上） |
//! | [`Coalition::amid`] | 在 | `amid` | 4 | 谓词（两格，同 `heir`） |
//! | [`Coalition::band`] | 员 | `band` | 4 | 访问器（单数集合） |
//! | [`Coalition::bloc`] | 籍 | `bloc` | 4 | 访问器（单数集合） |
//!
//! **被否的名字**（连同理由）：`create`（计算机语——principal 里没有一条叫 create/delete/
//! get/set 的）；`mint` / `seal`（**载体词**：铸一枚孔 / `PieCall::Seal`）；`convene` /
//! `charter`（声称有一位召集人／一纸章程，那是 K2 里没有的一格）；`join`（本仓的
//! `unit::join` 已经是"等它收尾完"）；`exit`（`room::exit` 是退出/死）；`member`（本仓的
//! `Tole` 里"组里的一枚"就叫它，另加 6 字母破族）；`part`（operator 的**分**）/ `peer`
//! （session 的**对端**）/ `link`（本仓的**链**）/ `hold`（本仓的**持有**）都有主；
//! `ally`（一个词两个词性 ⇒ 会被读成一次写；且它声称"结盟的忠诚"，而盟只是一张无主无义的
//! 集合）；`among`（可读，5 字母破族）；`roster`（principal 名册那一格已用这个字段名）；
//! `seat`（泊位那个词归 `Quay::seat`）。
//!
//! **三处近形照实记**（不靠自律）：`enter` 与载体那个词 `entry`（本仓 275 处——名词/动词
//! 一对，各在各自的层）；`bloc` 与 `block`（本仓 144 处，**全在分配器那一层**，协议层 0 处）；
//! `found` 与 operator 那条 `find`（同形——那 25 处全是 `find` 实现里的**局部变量**，
//! 不是任何 API 的名字）。
//!
//! # 帧与码（一处上界各一格）
//!
//! ```text
//!   Ask    [0] op   [1..9] a   [9..17] b          一问：动作码 + 两个 8 字节的号
//!   Reply  [0] status  [1] flag  [2..10] a        一答：状态 + 有没有 + 一个号
//!          [0] status  [1] 未完  [2] 条数  [3..] 号   一窗：状态 + 未完 + 条数 + 一串号
//!
//!   动作码  FOUND=1 ENTER=2 LEAVE=3 AMID=4 BAND=5 BLOC=6
//!   答话    OK=0 UNKNOWN=1 FULL=2    BAD=3        （BAD 在表外）
//! ```
//!
//! **码的数字不照抄 principal**：同一个概念 `UNKNOWN`，operator 那一面是 1、principal 那一面
//! 是 2——三家各按**自己失败域的顺序**排、`BAD` 收尾。照抄别家只会让自己表里空出一个号。
//!
//! **答话的三种编法**（六条一起看，一眼查得完）：
//!
//! ```text
//!   OK                     enter / leave          只答状态
//!   OK + 值（a 那一格）     found                  答那枚新号（零号也是合法答案，故不用 flag）
//!   OK + flag              amid                   是 / 不是
//!   OK + 未完 + 一串号      band / bloc            一窗号（`more` = 窗外还有）
//!   UNKNOWN                found / enter / leave / amid / band   盟不存在，或发送者没绑
//!   FULL                   enter（只有它）         备不下那一行
//!   表外 BAD               读不懂这一问
//! ```
//!
//! `bloc` 不在任何一行里——**它没有失败域**。
//!
//! **报文里没有"我是谁"这一格**：发送者由内核在 `Push` 那一刻盖章，Server 拿去名册问。
//! 于是客侧的 `enter` / `leave` **不带身份参数**：这一格的诚实性是**签名给的**。
//!
//! # 地址与载体
//!
//! Server 的门牌落在树上 **`/sys/coalition`**（自己分 `/sys`、落自己那一枚、再查回来验一遍，
//! 同 `router` / `rtc` / `principal` 那一趟）。客侧一问一答**建在门牌上**：替这一趟铸一枚
//! 回信孔借过去（记号 `call::BACK`），把帧推上门牌，答话从那枚孔回来——一份报文里没有
//! "往哪回"这一格。
//!
//! **起手两颗锚**：`Sire`（只为上板与上树两条会话，**之后不落任何字段**——盟无主，核心不需
//! 要它；对照 `Principal` 拿它当名册钥匙）、以及树上那面身份服务的门牌（**带重试**：门牌是
//! principal 自己跑完那一段落下的，本服务可能比它先起来；撞 `UNKNOWN` 就睡 `RETRY_MS`
//! 再来，总预算 `MS`）。找不到身份那一份门牌就**起不来**（本域死在起手那一步，出口那一行是
//! `coalition: no identity plate`——旧文写的 `E_FACE` 是落地前的 `const` 名，那一族已收进
//! `Fail`）——没有名册就没有"是谁"，这台服务什么也做不了。
//!
//! # 与左右两边的关系
//!
//! - **与 [`system::principal`](super::principal)**：纵向（从谁而来）与横向（谁和谁一起）两条轴，
//!   互不推出，只在**一处**相会：键是身份 ⇒ 转换（`adopt` / `waive`）会移动"这个任务问到的
//!   盟籍"。**谁是谁**归 principal，**成员关系的真值**归本协议；两者都不解释含义。
//! - **与 [`system::operator`](super::operator)**：树是**地址**（名字 → 一枚 Pie）——本协议的门牌走它，
//!   但盟的**号**不上树（树上的条目存不了号）。
//! - **与 [`system`](crate::system) / [`system::board`](crate::system::board)**：零交集。
//!   System 管存在与生命周期、板管生死，两者都在"一个 TID 此刻是什么"上说话，与本协议
//!   回答的两个问题都不同。
//! - **与 Pie**：零交集。`System = 存在与生命周期`、`Principal = 策略身份`、
//!   `Coalition = 横向归属`、`Pie = 实际持有的 authority`、`具体协议 = authority 的语义`。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **"self" 不在核心，在适配层**：核心的 `enter(who, c)` **收得下**"代他人报名"的形状
//!   （它收的就是一条身份），分开它们的只有服务那一句 `who = resolve(发送者)`。⇒ 谁写第二个
//!   适配层，谁就得自己扛这条义务（核心挡不住）。这也是"没有 `admit` 这条原语"的**确切**含义。
//!
//!   **被否（这一格是选出来的，不是漏掉的）**：核心改收 `TaskId`、由它自己去问名册——那会把
//!   "身份服务"从**适配层的依赖**升成**核心的依赖**，而这一族的核心今天连 `TaskId` 都不认识
//!   （见 `core.rs` 头注）："喂两个假号就能把六条规矩推理干净"正是从那儿来的。
//! - **无主的推论（K2 那一格的另一半，照实写下来）**：成员只能**自己退**（`leave` 的钥匙是
//!   发送者那一格），而"无主"意味着没有 `expel` / `dissolve`（K2）；身份又永不消亡 ⇒
//!   **表与计数器都只增**：没有一条原语能清掉一行、也没有一条能清掉一枚盟。今天唯一的"清"
//!   是**会话级**的——编排域退 ⇒ 本服务随级联收掉 ⇒ 整本盟册消失（见下面那条边界）。
//! - **第二处同名不同事**：principal 那条约未落的 `admit`（纳：把一个没绑过的 TID 收进自己
//!   那一支）与本协议说的"代他人报名"**不是一回事**，两处都停在"验不了对方的同意／血缘"上。
//! - **发现不是本协议的事**：号由服务铸 ⇒ 要有第二方进同一枚盟，得先有人把号交到它手里。
//!   本仓今天的三条路都要新东西（树上的条目是"名字 → 一枚 Pie"，**存不了号**；报文里带一格
//!   需要两位客人之间先有一条会话；装配单的 args 没接）。故真机读数是**一位客人 + 它派生出
//!   来的第二条身份**（`harness/src/member.rs`）。
//! - **没有任务事件面**：盟**不知道**谁死了；盟籍是**身份**的属性，而身份不随任务消亡
//!   （principal 的节点永不删）⇒ 死者的行留着，且必须留着。
//! - **不验身份**：表里的 `who` 只有一个来路（`Resolve(发送者)`），而它只答树里的号或"没绑"
//!   ——**不变量比检查硬**。故本册不去问"这条身份还在不在"：`bloc` 对一条假号答空串，
//!   `amid` 对一条假号答 `false`，都不是失败。
//! - **没有语义**：`amid` 为真**不蕴含任何权限**；`band` / `bloc` 答**号序升序**（不是登记序）。
//! - **取窗的游标是阈值**：取的是"号 > 游标"的那些，游标 = 上一趟的**末一枚**。故没有"过期
//!   游标"这回事（`cookieverf` 那一格不需要）；**代价照实记**：两次取窗之间册变了 ⇒ 跨页
//!   **只会漏，不会重**。`b` 那一格写成"游标 + 1"（`0` = 没有游标）——零号是真格子
//!   （`PrincipalId::ROOT` 是 0、`CoalitionId(0)` 是一枚普通的盟），拿 0 当"没有"会漏掉它。
//! - **没有配额**：条数是策略、容器要有界 ⇒ 落点在分配那一格（[`Coalition::enter`] 的
//!   [`Fail::Full`]）；另两条写与两条读**不分配**。号空间只受 `usize` 宽度约束（`found`
//!   到不了 `Full`），到 `usize::MAX` 那一步在本仓不可达（铸一枚要一趟问答）——不造机制。
//! - **身份空间是会话级的**（同 principal P4）：编排域退 ⇒ 本服务随级联收掉 ⇒ 整本盟册消失。
//! - **内核侧零存储**：Task 没有盟籍字段——权威状态只在 Server。
//! - **两个号空间不同型**：`CoalitionId` 与 `PrincipalId` 同形不同源，互相拿错是**编译错误**；
//!   `CoalitionId(0)` 是一枚**普通的盟**，`PrincipalId(0)` 是**根**。


