//! Session Protocol — **会话建立**：两个陌生实体怎么建起一条会话。
//!
//! 它不定义消息格式、不定义负码表、不管收发——那些归各具体协议。它只回答一件事：
//! **两个手里都没有对方门闩的 Task，怎么把会话的两端凑到各自手里。**
//!
//! # 陌生在哪：身份是免费的，地址不是
//!
//! ```text
//!   知道对方是谁        ← 内核免费给：`sire`（谁生了我）、每枚门闩上的"谁授的"
//!   手里有对方的门闩    ← 谁都不给：建起之前，双方都没有
//! ```
//!
//! 所以会话不是"交换地址"，是**一侧先铸一枚交给对方**。两个动作一合就成：
//!
//! ```text
//!   我这一侧                            对方那一侧
//!   Quay::open(对端)                    （它知道我是谁：内核告诉它"生你的是谁"）
//!   seat(名字) ── 一枚孔（刻着这个名字）──▶ 落到它的表里（盖上"我授的"）
//!                                       claim(我, 这个名字, 期限)  扫表认领、归位
//!                                                │
//!                                                ▼
//!                                       seat(名字) 也交一枚回来（刻着同一个名字）
//!   ◀─────────────── 它的孔 ─────────────┘
//!   ⇒ 两侧各持两枚孔 ⇒ 数据面 = `Port`（本协议不管收发）
//! ```
//!
//! **认领的判据是两格正判据**：这扇门**谁开的**（`owner`）+ 孔上**刻的记号**（`mark`）。
//! 两格都是内核在开门那一刻盖/刻上去的戳（"谁授的"是另一个戳子，见事实 3），副本共享同一
//! 事实、转手不变；而名字、位置、内容、号码那四样都能被伪造或乱序。
//! **记号 = 铸者那张表里这条路的名字**（`seat` 铸孔那一刻刻上去的，随副本过线）——
//! 有它，**同一位开的多枚孔**才分得开（只有 `owner` 一格时办不到）。
//! 这是本协议**不发明名字系统**的原因：按名字寻址是目录的事，不在这一层——记号只回答
//! "这是哪条路上的那一枚"，不回答"谁在哪儿"。


