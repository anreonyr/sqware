//! Driver Protocol — **设备轴**：一台设备从"交到某个域手里"到"它的线有人领"这一整段。
//!
//! 它**不是**一份驱动框架：没有 `Device` trait、没有驱动注册表、没有设备类模板。它是**跨域
//! 约定**的集合——谁对谁说什么；设备语义（读哪个寄存器、FIFO 怎么排、行怎么编）各驱动自带
//! （`programs/src/driver/<域>/` 里那一片设备模块）。
//!
//! ```text
//!   driver
//!   ├── supply   物料到手（引导域 → 域）：一张单子换一段记录        【已落】
//!   └── line     线：权威 / 属主 / 登记 / 投递 / 排空 / 收线      【已落：四格都有调用者】
//! ```
//!
//! **轴 ≠ 容纳**（与 [`system`](crate::system) 分清）：那一份**自己是一份协议**——它有判定
//! （`core`）与账（`desk`），下面那四份是**它的子协议**；本层**自己没有判定也没有账**（`driver`
//! 这一级没有 `core.rs` / `desk.rs`），下面那两半是**并列的两份协议**——物料与线是两件不同的事，
//! 谁也不在谁之下。
//!
//! # 两个角色
//!
//! | 角色 | 手里有什么 | 干什么 |
//! |---|---|---|
//! | **设备驱动** | 那台设备的门闩 | 写寄存器、排空设备、开自己的闸门（`IER`） |
//! | **线路由者** | 中断控制器 | 接线、`claim` / `complete`、把线投给登记过的驱动、收线 |
//!
//! 今天 `prog-router` 一台兼着"控制器驱动"与"线路由者"，`prog-uart` 是第一台纯设备驱动。
//! 两个角色分开写，是因为第二台控制器 / 第二台设备驱动出现时这一层不必重写。
//!
//! # 这一层管什么、不管什么
//!
//! 每个驱动都要做的那几件事里，**只有一件别处没有**——线；其余各有各的家，本层**只引用、
//! 不复述**（"两处各写一遍"正是旧树 `docs/driver.md` 那份清算里第 1 条的病）：
//!
//! | 每个驱动都要做 | 家 | 本层的动作 |
//! |---|---|---|
//! | 递单 / 发货（物料） | [`supply`] | **就是本层** |
//! | 收物料的**字节形状** | `system::grant`（`Pair` 解）+ [`session`](crate::session) | 引用 |
//! | 被按名找到（挂牌） | [`system::board`](crate::system::board) / [`system::operator`](crate::system::operator) 的客侧几手 | 引用 |
//! | 就绪宣布 | [`system`](crate::system) 的 `Announce` | 引用 |
//! | 开设备（门闩 → 视图） | `runtime::core::dock` | 引用 |
//! | **线的权威 / 登记 / 投递 / 排空 / 收线** | [`line`] | **已落** |
//! | 服务面（读写设备） | 各驱动自己的具体协议 | **不放**——旧 `uart` 协议的死因就是这里。今天两个实例（`uart` 那枚读行孔、`rtc` 那面报时服务），都住各自驱动目录 |
//! | 装配样板（会话 + 收配给 + 上板 + 常驻） | `programs/src/driver/`（`assemble` 等） | **不放**：那是程序骨架，不是两个任务之间的约定 |
//!
//! # 物料到手（[`supply`]）
//!
//! 一份正文、两台机器：**收方自己开单**（`programs/src/driver/<域>/needs.rs` 那张常量表就是
//! 单子上的形状：**写的是类**，坐标由编排域读树定），**装配者代递**，引导域按坐标发货。
//! 三条规矩属本层：
//!
//! - **`ONLY` 是资源事实**：一台设备的寄存器页同一时刻只该有一个持有者——故"谁持有它"与
//!   "谁动它的寄存器"是同一个答案；
//! - **`VEST` 一路被剔**：驱动拿到的门闩不再授出（今天没有需要再授出的用家）；
//! - **驱动不直接对固件说话**：子方只认得生我者，故单子由编排域代递（见 [`supply`]）。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **线那一半已落**：`occupy` / `deliver` / `exhaust` / `vacate` 四个原语 + 一张按线号索引的
//!   账（[`line`]），**接到机器上**了（`router` 一枚线程守"铃 + 门 + 排空"三个事件，`uart`
//!   登记自己那条线）；**`exhaust` 今天有真内容**——读口搬到设备持有者之后，客户是真的读走了
//!   设备里的字节才说那句话；**`vacate` 也有调用者了**——路由者每次醒来探活（`alive` 答不出的
//!   那几条拆线 + 空出格子），时机就是主人那一枚孔封印敲到组键的那一次醒来。
//! - **门牌已落（三台驱动）**：驱动的门牌挂 [`system::operator`](crate::system::operator) 的 **`/device`**
//!   （`DIR`）——名字用服务名、那块 Pane 由第一个上树的驱动建、按名找服务走树、板只管生死
//!   （见 `programs/src/driver/mod.rs`）。`uart` 的门牌 `/device/uart` 上挂的是**读行那枚孔**
//!   （服务面），客人 `echo` 从它读；`rtc` 的 `/device/rtc` 上挂的是**报时服务的入口**，客人
//!   `sleeper` 照同一条路找上门（问时间、定闹钟、等到那一声）。
//! - **驱动的特权级已裁（量出来的）**：两台都是 **U 态**——清单 改 `User` 之后两道门
//!   照旧全过（banner 里 UART 与 PLIC 的 PMP 都是 S/U (R,W)，旧树也裁过"驱动是 U 态域"）。
//! - **坐标是区，名字不是坐标**：配对块按 `reg` 段基址分条（实测 `flash@20000000` 两段 ⇒ 两条
//!   记录，各是各的坐标，"同名"这件事不再存在）；**单子上仍然没有"第几段"这一格**——按类认领
//!   认到的是**首段**，要更细得先立那一格（与"第几台"同一类）。
//! - **重活不做**：DMA、共享内存、热插拔、驱动运行期替换、一条设备多条线、中断共享。


