//! supply — **物料到手**：引导域向上层露的那一面（**按坐标发货**）。
//!
//! 它是 [`crate::driver`] 的**供给侧**：这一层记的是"引导域交给域的一切"。**不全是设备**——
//! 今天五笔货分两类：
//!
//! ```text
//!   设备侧（驱动领）    那几台设备的 `reg` 段（Pole，按**区**取）
//!                      irq（Nole，空载荷的中断门铃，按"哪一件"取）
//!   纯物料（谁用谁领）  devicetree（自描述区，router 领，按"哪一件"取）
//!                      initrd（载荷区，编排域领，按**区**取）
//! ```
//!
//! 后两笔**借这条路**，不因此变成设备（"这张账记的是交出了哪些门闩，不是有哪些设备"）。
//! 把它们放在这一份里的**代价照实记**：编排域为了自己那一笔也要 `use` 驱动这一层。
//!
//! **从前还有第六笔 `operator-tip`**（持树者的提示之路：引导域先认下来、编排域来要时才发）：
//! 树改由**编排域自己起**之后，那一笔当场消失——它的装配者就是编排域，提示之路直接落在
//! 编排域手里，不必从引导域转一圈。
//!
//! 引导域（`root`）是内核引入的**唯一顶层域**：boot 把清单与配对块只读借映进它，设备门闩
//! 种进它那张表。它自己**不做策略**——不认识服务名、不排顺序、不记账。这一份正文定义它与
//! 上层（编排域 `system`）之间那一面：**一张单子换一段记录**。
//!
//! # 谁在用它
//!
//! - **服务端**（发货循环）在引导域：`programs/src/root/supply/server.rs`；
//! - **客户端**（递单取记录）是**编排域**：`client::draw`，今天唯一一个客户；
//! - **收方**是各驱动：`call::Need` 的常量形态就在它们自己那张需求单里
//!   （`programs/src/driver/{router,uart,rtc}/needs.rs` 与 `harness/src/lodger/needs.rs`）
//!   ——单子由编排域**代递**（子方只认得生我者，**驱动对固件说不上话**），递之前它把单子上
//!   那几格"类"翻成设备树里那一段区（`call::Need::settle`）。
//!
//! ```text
//!   编排域（client）                          引导域（server）
//!   递一张单子：要哪几样、给谁、多大权 ▶ 收下单子
//!                                      按坐标从 boot 账里取原件（或取它自己认来的那一枚）
//!                                      授进"给谁"那张表（Accord 直授，不经本域）
//!   收下回单：一段记录（坐标 + 种在你表里的号） ◀ 回一张回单
//! ```
//!
//! # 为什么是"按坐标发货"而不是"把账交出去"
//!
//! 两块账里**只有一块是纯字节**（清单 + 全部镜像那一区），它整块交出去一次就够（零拷贝）。
//! 另一块是**门闩**——`PieToken` 是"哪张表里的第几个"，**过线的字节在对面没有意义**，故
//! 门闩只能一枚一枚 `Accord` 到要它的那张表里。本协议发的是后者：**坐标进、号回**。
//!
//! # 固件不发"再授出的权"
//!
//! 每一条要什么，都带着"多少权"与"什么形态"；**唯独 `VEST` 一位，固件一律剔掉**
//! （`policy & !Policy::VEST`）。理由不是权宜：这一版里**每一份授出都不需要再授出**——
//! 客人只收发、编排域只转投与接树、连持树者的提示之路也只是"推一个号"。于是"向固件要
//! 再授出的权"这条提权路当场堵死，而原件与 `VEST` 一直留在引导域手里。
//!
//! 形态里的 `ONLY` **不动**：它是**资源事实**（`Accord` 校验它与源枚一致），不是调用方的
//! 选择——独占资源的授出必须是移交。
//!
//! # 一问一答，且只有一个客户
//!
//! 泊位上**不并发**：一单一答，回单与单子一一对应（今天只有编排域一个客户）。回单里那一段
//! 记录是 `Pair` 数组（坐标 + 号），与"装配者转交配给"那一条路**同一种字节**——两条路记的
//! 是同一件事："这东西种在你表里的那个号"。
//!
//! # 读不出 ≠ 对面没了
//!
//! **照实记**：本域读的那一枚孔**命随本端**（对端退出时内核的寿命边封的是**对端开的那几枚**）
//! ⇒ 读超时不能当作"客户没了"。故 `server::serve` 有界地等，超时只**探一次活**（那一步由
//! 调用方给，判据与协议无关）。要"读不出即 Dead"，得用一枚**对端开的**孔——那是另一份形状。
//!
//! # 本协议不负责的
//!
//! - **该起谁、该给谁什么权** → 编排域的策略（单子就是它的策略，本域只照办）；
//! - **要哪几样** → **收方**自己那张需求单，就是本协议 `call::Need` 的常量形态
//!   （今天那四张在 `programs/src/driver/{router,uart,rtc}/needs.rs` 与
//!   `harness/src/lodger/needs.rs`）；本协议只定义怎么把单子递过去、回单怎么读回来；
//! - **谁代表谁** → Principal Protocol；
//! - **清单怎么解析** → `plan::manifest`（线格式）与域侧那几张表；
//! - **装载与建域** → 内核 Unit ABI（本协议的"授出门闩"只是权柄那一步）。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **一个客户**：今天只有编排域会递单子；多客户要各一条泊位（本正文不定义"谁来排队"）。
//! - **没有撤销**：授出去的门闩归对端；要收回得走 `Revoke`，本协议不带这一格。
//! - **没有账号**：固件不记账，"谁领过什么"它不知道也不留底。
//! - **上限是本侧选择**：孔不预设上限（见 `env::fid::PieCall::UnsealHole`），
//!   `ORDER_CAP`/`REPLY_CAP` 是"一帧一单、不流式"这个选择的尺寸，不是线格式的约束。


