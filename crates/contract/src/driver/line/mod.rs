//! line — **线**：一条中断线从"归了某个域"到"这一条处理完了"这一整段。
//!
//! 它是 [`crate::driver`] 的另一半（那一半是 [`super::supply`]：物料到手）。线上两个角色：
//! **设备驱动**（持有那台设备的寄存器页——只有它能排空）与**线路由者**（持有中断控制器——
//! 只有它 `claim` 得动，那是 per-context 的）。
//!
//! ```text
//!   occupy   占住这一格 + 接线   设备驱动 → 线路由者：「这台设备的线归我」
//!   deliver  推一帧   + 置忙     线路由者 → 设备驱动：「哪一条响了」
//!   exhaust  排空     + 置闲     设备驱动 → 线路由者：「哪一条我处理完了」
//!   vacate   空出这一格 + 拆线   （主人没了——探活看出来的）
//! ```
//!
//! 两对：`occupy` / `vacate`（占住 / 空出）、`deliver` / `exhaust`（投递 / 排空）。
//!
//! # 账
//!
//! ```text
//!   格 = 空（这条线没主） | 有主 { 泊位, 忙 }
//!   线号 = 下标（容量按 device_count 校验 ⇒ 越界不可表达）
//! ```
//!
//! "忙"只可能是"有主"里的一个字段（"没人要的线正在等排空"写不出来）。**客户手里没有"线"**：
//! 它那条泊位就是坐标，故"线"这个类型只活在路由者那一侧——线泊位上那两句话（投递 / 排空）
//! 因此都不带线号（见 `call`）。
//!
//! # 权威与属主
//!
//! **线 = 区的函数**：线号只有一个来源——设备树里那个节点的 `interrupts` 第一格；客户永远不说
//! 线号，只报它持有那件东西的**那一段区**。解树只发生一处（线路由者，它手里有设备树）。
//!
//! **属主验不动**：内核交完设备就零设备账，句柄号又不跨表 ⇒ 抢线如实记为代价；真护栏在装配期
//! （谁拿到那台设备的 `ONLY` 门闩）。
//!
//! # 两层
//!
//! ```text
//!   core.rs    账 + 四个原语 + 失败域   —— 不碰内核（不出现 runtime::）
//!   call.rs    帧形与记号
//!   client.rs  客侧几手（占线 / 收投递 / 说排空）
//!   （服务面 = 设备持有者自己的具体协议，**不进本 crate**：`driver/uart` 那枚门牌孔、
//!   `driver/rtc` 那面报时服务）
//!   （不在协议里）接线 / 静音 / 拆线 / claim / complete —— programs/src/driver/router/plic.rs
//! ```
//!
//! 核心只记账：**"登记了就接线、放回了就接着、空了就拆"**那三手紧随其后，由适配层做
//! （它要动硬件）。门牌：驱动挂在 [`crate::system::operator`] 的 **`/device`**（`super::DIR`）之下，
//! 名字用服务名。
//!
//! # 静音还是压着不结（**已裁：静音**）
//!
//! `deliver` 之后到排空之前，那条线怎么处置。两条路都防得住"同一格再报一次"，差别在
//! **结账那一步**：
//!
//! ```text
//!   静音（今天）  deliver ⇒ priority = 0 ⇒ complete ⇒ …客户排空… ⇒ enable（优先级写回）
//!   压着不结      deliver ⇒              （不 complete）…客户排空… ⇒ complete
//! ```
//!
//! 两条都是**探针量过**的（临时改掉那一手、跑一程、再改回来）：
//!
//! - **不静音、`complete` 照旧立刻做** ⇒ 每次投递与排空之间白叫醒客户（实测：短跑里多出两次
//!   `uart: rang n=0`——设备那一格已经空了，客户被叫起来排到 0 字节）。
//! - **压着不结** ⇒ 白叫醒也没有了，但它把 `complete` 当成流量阀，而**结是那一格的再武装**：
//!   QEMU 那份实现（`hw/intc/sifive_plic.c`）领走时置 `claimed`，仲裁只看
//!   `pending & ~claimed & enable` ⇒ 结没写回去，那条线就**再也不前送**；而 `claimed` 在那里
//!   是**整台控制器一份**（不是 per-context）⇒ 一笔没付出去的结把这条线钉死到重启。
//!   实测：故意不结 line 10 ⇒ 只投递一次，之后第二次输入再也进不来（回显与停机都没了）。
//!
//! 故裁**静音**：`claim` / `complete` 成对、**当场结清**；"这一条现在有没有人接"归
//! **优先级**那一格（`priority = 0` 是可逆静音，写回即复原，见
//! `programs/src/driver/router/plic.rs` 的 `disable`）。拿控制器的完成协议兼职流量阀，代价是
//! "客户中途死"那条路上的一条永久死线——而"客户没了"正是这一层反复处理的那件事
//! （`vacate` / `sweep`），不该在那条路上埋一颗。
//!
//! # 未决（照实写）
//!
//! - **投递不出去时的那一格**：客户的口封了 ⇒ 投不出去就不静音，而线还挂着电平 ⇒ 会空转。
//!   探活那一格已经落了（路由者每次醒来 `sweep`），故它同一次或下一次醒来就被 `vacate` 收掉。
//!   **照实记**：`router: deliver failed line=` 那一行因此**近乎不可达**——探活排在每次醒来的
//!   `claim` 之前，客人一死就先被收掉，只剩"sweep 跑完、claim 跑完之间那位死掉"那个竞态窗口；
//!   它是一格**防御**读数（与 `platform/devices.rs::IRQ` 同款），不为它造台子。
//!
//! **已落**：
//!
//! - `exhaust` **有真内容**了——读口搬到设备持有者（`driver/uart`）之后，客户是真的读走了
//!   设备里的字节才说这句话（见 `programs/src/driver/uart/main.rs`）。两个方向的堵法不对称
//!   也是实测定下来的：投递阻塞、排空**不阻塞**（`client::Line::exhaust`）。
//! - **探活**：`vacate` 有调用者了——路由者每次醒来扫一遍有主的那些条，`alive` 答不出的
//!   就**拆线 + 空出格子**（`sweep`，见 `programs/src/driver/router/main.rs`）。时机是
//!   "组那一次等待回来"，理由：主人一没，它铸的那一枚孔就封印，而那一格正挂在路由者这只组
//!   上（`wipe` 敲组键）——**醒来本身就是通知**，不必跟着板、也不必拿一拍去探。
//!   **读数**：`prog-lodger`（房客）每次冷启动都占住 1 号线、一句话不说就走 ⇒
//!   `router: line 1 = virtio_mmio@10001000` 与 `router: vacate line=1`（`crates/gate/src/soak.rs`（已删）的固定
//!   读数）——"死会叫醒"由此从读代码变成量出来的。


