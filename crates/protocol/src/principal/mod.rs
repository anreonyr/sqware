//! Principal Protocol — **策略身份**：这个 Task 在策略上代表谁。
//!
//! 它不定义权限（Policy ID 的含义由各具体协议自己解释），不定义 User（User 是它之上的一种
//! 解释），也不定义任何领域语义。它只回答一个问题：**这个请求代表哪个策略主体。**
//!
//! # 实现面在哪里（本模块目前没有代码）
//!
//! 与 [`system`](super::system) 不同，这一份**要走会话**：调用方得去问 Principal Server。
//! 今天树里还没有那个 Server（`programs/` 下只有 root / plic / echo），故本模块只有正文。
//! 但它已经站在实地上——内核给了两条**不可伪造**的身份凭证：
//!
//! - `MailCall::Pull` 回的 `(len, TaskId)`：发送者由**内核在 Push 时盖章**（hole 的单槽记
//!   `from`，"syscall 上下文不可伪造"），收方不必从报文里猜"谁在说话"；
//! - `PieCall::Reserve { token }` 回的 `(vestor, owner)`：`vestor` 是**门闩**的来历（转手即
//!   改写），`owner` 是**资源**的来历（任意副本共享同一事实，转发不丢）。
//!
//! 两条合起来给出这条分界：**"你是谁"内核免费背书，"别人是谁"不免费**——D3 的形状就是从这
//! 条分界直接落下来的。
//!
//! # 四条裁决
//!
//! ## D1 键 = TID；装配绑"域的代表线程"
//!
//! 身份挂在 **Task** 上，不引入域（Team）粒度。理由不是偏好，是内核的形状：身份的管道只产出
//! TID——Push 盖章的是 task id、`Reserve` 给的是两个 TaskId、`Sire` 给的是 TaskId；而
//! **`TeamId` 连"我自己是多少"都问不出来**（`UnitCall` 里没有 `SelfTeam`，TeamId 只由
//! `Build` / `Heir` 产出）。键在域上，Server 拿不到键。
//!
//! 粒度问题在**策略层**解决，不进结构：一个域的若干线程**可以**共享一个 Policy ID（多个
//! Task 同一个主体是常态）；装配只给**每个域的代表线程**（今天就是各 bin 的 `main`）绑一次，
//! 域内自产的线程默认 `Unbound`——要独立身份就自己去 `Bind`。新线程的能力表本来就起步为空
//! （`Spawn` 的既有语义），身份同款不自动继承，没有额外代价。
//!
//! ## D2 只由装配写；信任锚走启动参数
//!
//! `Bind` / `Unbind` 第一版**只有装配者（root）能写**，Server 只认那一个 TID。
//!
//! 锚怎么给：root 用 `UnitCall::SelfId` 取自己的 TID，hatch Server 时把它当**启动参数**写进
//! 对方栈顶（`Spawn` 的 args）——启动参数由**装配者**写入，第三方改不了。今天零内核改动就能
//! 落地。
//!
//! 为什么不是另外两条路：
//!
//! - **血缘门**（只有直接 sire 能给子绑）：与 `Spawn`/`Hatch`/`Doom` 同族，但 Server **验不了
//!   血缘**（域侧没有按 TID 查任务的动词），验不了的门就是装饰——那正是 `2bc7c55` 删掉的那
//!   一种门；要它成立得先让内核代验（新增动词）。
//! - **注册即绑定**（`Build`/`Spawn` 载荷里带身份）：最省，但把身份塞回 Task 的核内字段，与
//!   "Task 不持有 Policy ID"直接冲突。
//!
//! ## D3 `Resolve` 无参
//!
//! `Resolve()` 只解析**调用者自己**：TID 由内核盖章，答 `Bound(PolicyId)` 或 `Unbound`。内核
//! 能免费背书"你是谁"，不能背书"别人是谁"；带 TID 的 Resolve 是代人查询，缺一条授权规则
//! （谁能问、能问到什么、死人怎么算），第一版不开。
//!
//! 附带的好处：v1 里那三个态（未绑定 / 已死 / 从未存在）在无参形态下**塌成两个**——说话的人
//! 必然活着，后两个**不可达**。于是"死过的 TID 与从未分配的 TID 在核内同形"这条退化被
//! **消掉**，而不是被回答。
//!
//! `Unbound` 是**一个诚实的答案**，不是错误码：Server 不替上层做血缘推断（它没有血缘事实，
//! 也不该有）；未绑定的请求怎么对待，由收到它的那个协议自己定。
//!
//! ## D4 身份空间是**会话级**
//!
//! Principal Server 做 root 的子域，随会话一起收场（root 退 ⇒ 退出钩子沿 `heir` 级联）。本仓
//! 没有持久化、没有重启（**退出即关机**），一次会话就是系统的一生——跨会话的身份没有对象可
//! 引用。要一个比 root 长寿的宿主，就得让内核认识"principal server"这个角色（今天只有内核能
//! 引入顶级域），那是把具体协议写进内核，与"内核零上层概念"直接冲突。
//!
//! 将来要跨会话身份，需要的是**持久化**这个能力（另一个协议），不是更长寿的 Server。
//!
//! # 接口（第一版）
//!
//! ```text
//! Resolve()            → Bound(PolicyId) | Unbound   ← 唯一必须被别的协议依赖的
//! Bind(TID, PolicyId)  → ()                          ← 只有装配能写
//! Unbind(TID)          → ()                          ← 只有装配能写
//! ```
//!
//! **帧形、负码表、上界不在这里定**——那是这一层的第一关（结构 / 原语 / 签名），且本 crate
//! 头注已经把那三条列进"不要重犯的六条"的头三条：一份帧形、一张负码表、一处上界。
//!
//! # 与左右两边的关系
//!
//! - **与 [`system`](super::system)**：System 回答"系统里运行着哪些 Service、怎么起停监督"，
//!   Principal 回答"这个请求代表谁"。两者都落在 TID 上，但**不存在所有权关系**：Service 的
//!   生命周期归 System，策略身份归 Principal。两条差别要记牢：
//!   ① **TID 的存在性判据只有内核有**（见下面的已知边界）；
//!   ② System 那份正文里也有一个词叫 *supervisor*（"谁负责在我死后处理我"），
//!   那指的是**编排责任**（谁起的谁负责），与策略主体无关——撞词不撞事，两者都读作
//!   "谁"但回答的是不同的问题。
//! - **与 Pie**：零交集。`System = 存在与生命周期`、`Principal = 策略身份`、
//!   `Pie = 实际持有的 authority`、`具体协议 = authority 的语义`。Principal 不持有、不授予、
//!   也不解释任何 Pie。
//!
//! v1 草稿里有一句"Permission 可以定义为**一个 Task 是否能够获得另一个 Task 的 Pie**"——这句
//! 今天**没有动词支撑**：跨域取得 Pie 的唯一路径是**持者主动 `ship`**（另有 `Unseal*` 自铸、
//! `Reserve` 查来历），没有"向对端索取"这个调用。故本版不把它写进职责：Pie 的获得与传播归
//! Pie 那条路，Principal 只回答身份。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **没有按 TID 查任务的只读动词**：`muster` 在核内；域侧只有 `Join`/`Hatch`/`Doom`（都要
//!   授权）与 `SelfId`/`Sire`/`Heir*`（只看自己与直接子域）。⇒ Server **无法验证**一个 TID
//!   是否存在、是谁建的；它的表只能建立在"被告知"上。
//! - **没有任务事件面**：产生 / 退出 / 被杀 / 级联都不通知任何域 ⇒ 死掉的 TID 不会自动解绑，
//!   **陈旧绑定是合法状态**（Principal 比 Task 长寿），但也意味着表只增不减（第一版接受；
//!   真要回收，得先有事件出口）。
//! - **内核自己分不清"死过的 TID"与"从未分配的 TID"**：名册在 `bury` 时 `prune_dead` 摘掉死
//!   条目，此后 `muster` 对两者都答 `None`。**TID 永不复用**，故身份不会张冠李戴，但"这个 TID
//!   存在过吗"只在死后、prune 之前答得准。
//! - **身份空间随会话消亡**（D4）：root 退 ⇒ Server 随级联收掉 ⇒ 全部绑定消失。
//! - **内核侧零存储**：Task 没有 Policy ID 字段（本协议的权威状态**只在 Server**）——这一条在
//!   D2 选了"只由装配写"之后仍然成立，而且正是它排除了"注册即绑定"。
