//! Principal Protocol — **策略身份**：这个 Task 此刻代表谁，以及这条身份从谁而来。
//!
//! 它不定义权限（PrincipalId 的含义由各具体协议自己解释），不定义 User（User 是它之上的一种
//! 解释），也不定义任何领域语义。它只回答一个问题：**这个请求代表哪个策略主体。**
//!
//! # 三条轴：名册、谱系、转换
//!
//! ```text
//!   名册   TID ──→ 当前 PrincipalId        这个 Task 此刻代表谁        ← 内核盖章的那条管道
//!   谱系   PrincipalId ──父──→ PrincipalId     这条身份从谁而来           ← 只增不改的一棵树
//!   转换   名册那一格上的两句话          领（往下走）／弃（回起点）  ← 主体改自己，不碰树
//! ```
//!
//! **名册**是这份协议与内核之间的那一条边：内核在 `Push` 那一刻给报文盖章，收方拿到的是
//! **TaskId**；名册把它翻成一条策略身份。**谱系**是身份之间的关系：一棵单根的树，`derive`
//! 长出新枝，父不可改、节点不删。**转换**是主体对自己那一格的两种写法，钥匙全在"发送者是谁"
//! 上——故报文里没有"我是谁"这一格。
//!
//! 三条轴都**不定义**权限：收到"这个请求代表 P"的服务自己解释 P 意味着什么、要不要给它 Pie。
//! Principal 不持有、不授予、不解释任何 Pie（与 [`system`](super::system)、`operator` 的边界
//! 不重叠）。
//!
//! # 九条原语
//!
//! | 原语 | 干什么 | 钥匙 | 上线 |
//! |---|---|---|---|
//! | [`Principal::bind`] | 名册：把一条 TID 定到一条已存在的号上（换绑 = 重定起点） | 装配者 | 是 |
//! | [`Principal::unbind`] | 名册：撤一格 | 装配者 | **否**（核心有，同 `board::unregister`） |
//! | [`Principal::resolve`] | 名册：这条 TID **此刻**代表谁 | 无（读是公开的） | 是 |
//! | [`Principal::derive`] | 谱系：由一条身份派生一枚新节点 | 装配者，**或当前正好代表它的那一枚** | 是 |
//! | [`Principal::sire`] | 谱系：直接父（三态：有父 / 根 / 树外） | 无 | 是 |
//! | [`Principal::heir`] | 谱系：`a ≼ b`（`b` 在 `a` 那一支里） | 无 | 是 |
//! | [`Principal::clan`] | 谱系：最近公共祖先 | 无 | **否**（核心有，同 `operator::list`） |
//! | [`Principal::adopt`] | 转换 **领**：自己当前的号 ← 自己那一支里的某一格 | 发送者那一格 + `heir` | 是 |
//! | [`Principal::waive`] | 转换 **弃**：自己当前的号 ← **装配给我的那一条** | 发送者那一格 | 是 |
//!
//! **层**：这一族的 `sire` / `heir` 说的是**谱系**（谁代表谁）——与门闩层那个 `Pie.heir`
//! （这一枚被交给谁了，核里那个锚）**同字不同层**；两处名字都照旧，靠这一句分。
//!
//! **写只有五条，读全是公开的**：答案不是秘密，Principal 不授予任何东西——故读那四条里
//! **没有"对端说了不"这一档**，唯一会答的是"这条号不在树里"（`Unknown`）；`resolve` 连这一格
//! 都没有（`None` = 没绑，一个诚实的答案）。
//!
//! # 裁决（这一版重新裁过的几条，连同被否项一起记）
//!
//! ## P1 键 = TID；装配绑"域的代表线程"；**运行期身份不可自增**
//!
//! 键落在 Task 上，不引入域（Team）粒度：内核的身份管道只产出 TID——`Push` 盖章的是 task id、
//! `Reserve` 给的是两个 `TaskId`、`Sire` 给的是 TaskId；而 **`TeamId` 连"我自己是多少"都问
//! 不出来**（`UnitCall` 里没有 `SelfTeam`）。粒度问题在策略层解决：一个域的若干线程可以共享
//! 一条身份（多条 TID 指向同一个号是常态）。
//!
//! **被否项（前一版正文里的一句话）**："域内自产的线程默认 `Unbound`，**要独立身份就自己去
//! `Bind`**"——它与"只由装配写"直接冲突，且真放开就是让一个任务自报标签。**删**：运行期
//! 拿不到新身份，只有装配期那一次（以及下面 P5 那条"在自己那一支里向下派生"）。
//!
//! ## P2 只由装配写；信任锚 = **`Sire`**
//!
//! `Bind` / `Unbind` 只认装配者那一枚。锚不是启动参数，是**内核已经免费给的同一个事实**：
//! Server 的域由装配者建（`Sire` 回"建我那个域的那一枚"），故 Server 起手读一次自己的
//! `Sire` 就够了——**零接线**，而且比 args 更硬（args 是装配者写的，`Sire` 是内核盖的）。
//! 附带一条：`Sire` 是**弱引用**，装配者一退它就答 0 ⇒ 锚随会话一起失效，正是 P4 要的形状。
//!
//! 前一版选的是"启动参数 + root"，两处都要改：**装配者是编排域那一枚**（今天唯一起服务的地方），
//! 而 args 那条路在装配机器里根本没接（`system::call::bear` 写死空参数）。
//!
//! ## P3 `Resolve` **带参**（前一版是无参，翻案）
//!
//! `Resolve(tid)` 答 `Some(p)` 或 `None`。翻案的理由不是偏好：**另三处协议把"谁"这一格挂空
//! 在那儿等它**——`operator` 收到一条 `land`，内核盖的印章是**客人**的 TID，它要判 owner
//! 就得问"这位客人是谁"；无参的 `Resolve` 只会答 operator 自己，一点用没有。
//!
//! 带参版没有多出授权问题：**PrincipalId 是公开标签，不是凭证**（拿到它什么也做不了）。三问当场
//! 答得出来——谁能问：谁都能问；能问到什么：只有一条号或 `None`；死人怎么算：**Principal 从
//! 来不知道谁死了**（没有任务事件面），它答那条陈旧绑定，而那正是接收方要的。
//!
//! ## P4 身份空间是**会话级**
//!
//! Server 做编排域的子域，随会话一起收场（编排域退 ⇒ 退出钩子沿 `heir` 级联）。本仓没有
//! 持久化、没有重启（退出即关机），一次会话就是系统的一生；跨会话的身份没有对象可引用。
//! （前一版写的是"root 的子域"——今天唯一起服务的是编排域，root 只做固件那一层。）
//!
//! ## P5 谱系：只增不改、单根、钥匙是"正好代表它"
//!
//! `PrincipalId` 一旦产生，**父不可改**（树只 `push` ⇒ 无环、恰好一个根写不出来第二枚）；
//! 节点**永不删**（陈旧绑定必须合法：对方死了，收到它那句话的服务仍要问得出"刚才是谁"）。
//! 根是 Server 的**初始状态**（零号节点），不是一条动作。
//!
//! `derive(p)` 的钥匙：装配者，**或当前正好代表 `p` 的那一枚**（`Resolve(发送者) == Some(p)`）。
//! 后半把是内核印章与名册免费给的判据——"只能沿自己的 lineage 向下"因此不是纪律，是可查的
//! 事实。
//!
//! **`PrincipalId` 不是名字**：`derive` 不收名字，故号只能由 Server 发（裸号 + 树外答 `Unknown`）。
//! 可读的名字若将来要，是另挂的一格标签，不是身份；命名归 [`operator`](super::operator) 那棵树。
//!
//! ## P6 转换：**领**（`adopt`）与**弃**（`waive`）
//!
//! `adopt(q)` 把**自己**当前的号换成 `q`，只许在自己那一支里向下；`waive()` 把它写回
//! **装配给我的那一条**（名册那一格多留一格 `origin`）。于是这一族压成一句不变量：
//!
//! > **`origin ≼ current` 恒成立**——身份只会沿自己那一支往下走，或者回到起点。
//!
//! 三条边界：
//!
//! - **向上不是"没授权"，是判据**：`adopt(sire(p))` 在 `heir(p, ·)` 之外 ⇒ `Denied`，一句话
//!   就查得出来（§4 那句"lineage 是结构事实、向上涨权不是结构给的"因此不必靠自律）；
//! - **`waive` 不是单向门**：它不删格（身份还在，只是回到起点），故弃完还能再领；
//! - **钥匙全在发送者身上**：报文里没有"我是谁"那一格，两条转换都只认内核盖的那枚印章。
//!
//! **被否项**：① 把 `derive` + `adopt` 合成一条（"派生并换过去"）——那会把两个事实藏成一条，
//! 而两步各自能独立读懂；② **"父替子绑"**（§11 那种进程谱系）——Server 问不到"这个 TID 是不是
//! 你生的"（域侧没有按 TID 查任务的动词），做出来只能是一句没人能验的声称。故本刀**只做自我
//! 转换**；真要它落地，那一格的名字已经定好叫 `admit`（纳，5 个字母），与 [`Principal::adopt`]
//! 的区别写在下一条已知边界里。
//!
//! ## P7 **结盟**是另一条轴（已落地，见 [`coalition`](super::coalition)）
//!
//! 身份之间有两条互不推出的关系：**纵向的谱系**（本协议，这份正文）与**横向的结盟**
//! （`Coalition`：一组身份共同参与一件事，`found` / `enter` / `leave` / `amid`）。
//! 后者已经有自己的正文与服务。今天只记两处**交界**：结盟不产生 PrincipalId（它是关系，不是
//! 身份）；**它的键是本协议发的号**，故 `adopt` / `waive` 会移动"这个任务问到的盟籍"
//! ——那是两条轴唯一相会的地方。
//!
//! # 帧与码（一处上界各一格）
//!
//! ```text
//!   Ask    [0] op   [1..9] a   [9..17] b          一问：动作码 + 两个 8 字节的号
//!   Reply  [0] status  [1] flag  [2..10] a        一答：状态 + 有没有 + 一个号
//!
//!   动作码  BIND=1 RESOLVE=2 DERIVE=3 SIRE=4 HEIR=5 ADOPT=6 WAIVE=7
//! ```
//!
//! **答案不进失败表**：`resolve` 的"没绑"与 `sire` 的"它是根"走 `OK` + `flag = 0`（`flag`
//! 那一格省不得——`PrincipalId(0)` 是根，不是"没有"）；"这条号树外"走 `UNKNOWN`。三件事三个
//! 落点，故那张双射的负码表只装真正的失败（`Denied` / `Unknown` / `NoRoom`），`BAD` 在表外。
//! 转换那两条只答状态那一格（成功 = `OK`）。
//!
//! **加两条操作，帧形一个字不改**——这正是"一处上界"那条纪律在第二刀上的回报。
//!
//! # 地址与载体
//!
//! Server 的门牌落在树上 **`/sys/principal`**（自己分 `/sys`、落自己那一枚、再查回来验一遍，
//! 同 `router` / `rtc` 那一趟）。客侧一问一答**建在门牌上**：替这一趟铸一枚回信孔借过去
//! （记号 [`call::BACK`]），把帧推上门牌，答话从那枚孔回来——一份报文里没有"往哪回"这一格
//! （号只在持有它的那张表里念得动）。
//!
//! **装配者那一份不经树**：Server 起手把门牌那一枚**也交给它的生我者**——装配者认得自己起的
//! 那一枚，故装配期不必先上树查自己。装配期给每条服务一次 `derive(root)` + `bind(rep, p)`：
//! **从第三条起都在放行之前**做完（服务一起来，`resolve(self)` 就答得出）。**头两条**（树与
//! 身份服务本身）是照实记的例外——它们起来时身份服务还没在，故由装配者在它放行之后**补绑**。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **没有按 TID 查任务的动词**：域侧只有 `Join`/`Hatch`/`Doom`（都要授权）与
//!   `SelfId`/`Sire`/`Heir*`。⇒ Server **验不了**一个 TID 是否存在、是谁建的；它的名册只
//!   建立在"被告知"上（`bind` 因此只信装配者那一枚）。
//! - **`admit`（纳）未落地**：名字已定（5 个字母），语义是"有身份的一方把一个
//!   **没绑过**的 TID 收进自己那一支"。它今天落不了地的理由在第 1 条：Server 验不了血缘，
//!   故它**实际声称的只是"归属"，不是"父与子"**——唯一的护栏是"目标必须没绑过"（抢不走
//!   已绑的那一格）。要落它，得先把"它到底声称什么"在正文里钉死。
//! - **照实记：与内核那条私有的 `Task::adopt` 撞词**。"把一个子域收进我的 heir 表"（内核，
//!   `pub(crate)`、不在 ABI 词表里）与"主体自己往下领一格"（本协议 `adopt`）方向相反；
//!   本协议还没落的 `admit`（纳）反倒与内核那一条同向。
//! - **没有任务事件面**：产生 / 退出 / 被杀都不通知 ⇒ 名册**只增不减地留着死者的绑定**，
//!   而且**必须留着**（见 P5）；`unbind` 只有装配者会用。
//! - **`Sire` 的弱引用**：装配者退场之后 `Sire` 答 0 ⇒ 那之后没有人能写名册（也不该有）。
//! - **身份空间随会话消亡**（P4）：编排域退 ⇒ Server 随级联收掉 ⇒ 全部绑定与整棵树消失。
//! - **内核侧零存储**：Task 没有 PrincipalId 字段——权威状态只在 Server（这一条排除了
//!   "建域即绑定"那条路）。
//! - **无配额**：树与名册都按需增长，备不下如实报 `NoRoom`（不 panic）。"条数是策略、
//!   容器要有界"在这里的落点是分配那一格，不是架构里的一个常数。两条转换原语**不分配**
//!   （故它们到不了 `NoRoom`；这一格今天只被 `bind` / `derive` 用）。
//!
//! # 与左右两边的关系
//!
//! - **与 [`system`](super::system)**：System 回答"系统里运行着哪些 Service、怎么起停监督"，
//!   Principal 回答"这个请求代表谁"。两者都落在 TID 上，但**不存在所有权关系**：Service 的
//!   生命周期归 System，策略身份归 Principal。
//! - **与 [`system::board`](super::system::board)**：板管生死与牌子，Principal 管身份；
//!   两者都在"一个 TID 此刻是什么"上说话，但**答的是两个问题**（活着没有 / 代表谁）。
//! - **与 [`operator`](super::operator)**：树是**命名**（名字 → Pie），Principal 是**身份**
//!   （TID → 号）。树的条目没有 owner 字段——**"谁能动这一格"不在树上，在持树者那本账上**
//!   （`Ledger` 的 `Owner` + `claimable`）：**用**那一轴问的是身份（`Rule`，本协议答），
//!   **改**那一轴比的是落牌那一枚任务（账里那两格 `who` + `pie` 都是任务级的；为什么记命
//!   不记身份，见 `operator::ledger` 的 `Owner`）。**照实记**：这一句原来写的是"那一条的判据今天还没接上
//!   （真接上就是另一刀：条目得先有 owner 那一格）"——账就是那一格，它落在持树者手里，
//!   不在树上（"树不知道规矩"是刻意的）。
//! - **与 Pie**：零交集。`System = 存在与生命周期`、`Principal = 策略身份`、
//!   `Pie = 实际持有的 authority`、`具体协议 = authority 的语义`。

