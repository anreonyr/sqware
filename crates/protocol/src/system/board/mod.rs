//! Board Protocol — **命名寻址**：一个名字，此刻指向哪个入口。
//!
//! ```text
//!   调用方知道       它想要的东西叫什么（"console"、"irq"）
//!   调用方不知道     它现在在谁手里、该往哪儿说话
//! ```
//!
//! **它住在 [`system`](super) 之下**：这是同一份正文的**运行期那一半**——[`grant`](super::grant)
//! 管装配期"名字对上入口"，板管运行期那一步。板线程**就住在编排域里**
//! （`programs/src/supervisor/system/server.rs` 就是它那台监督机），故它不另立一个域、
//! 也不另立一份正文。
//!
//! 内核**不参与**这件事：它没有"按名字查"的动词（`Collect` 只报句柄、权限、授与人，
//! **不报名字**）。所以名字必须跟着门闩走，而这个协议就是那块**公示板**。
//!
//! # 一块板，一枚牌子
//!
//! ```text
//!        板（Board）           牌子（Sign）
//!   ┌──────────────────┐   ┌───────────────┐
//!   │  叫什么 │ 在哪   │   │  Name         │  ← 双方的坐标
//!   │ ────────┼─────── │ = │  Option<入口> │  ← None = 没实例
//!   │  console│  ■     │   │  Option<谁挂> │  ← 无实例时它无意义
//!   │  irq    │  □     │   └───────────────┘
//!   └──────────────────┘
//! ```
//!
//! # 三个动作
//!
//! | 动作 | 谁 | 落在一枚牌子上 | 失败 |
//! |---|---|---|---|
//! | [`Board::register`] | provider | 挂上 / 改写自己的牌子 | `Denied` / `Taken` / `Full` |
//! | [`Board::unregister`] | provider | 摘下自己的牌子（**牌子留着**） | `Unknown` / `Denied` |
//! | [`Board::lookup`] | client | 照牌子上的字说出"在哪" | `Unknown` |
//!
//! 线上的形状是 **`Query` → `Reply`**：一问一答，一次往返。三个动作是**模型**里的动作，
//! `Query` 是它们在线上那一侧的名字——两者不是重名，是同一件事的两层（`session` 里
//! `open` 既是动作也是那一步的说法）。
//!
//! 线上还有第四个码 [`call::DISMISS`]（**一字节短帧，空载荷**），它**不落在牌子上**：那
//! 一句落在板侧那本客人账上（[`Desk`]，一位客人一格）——一位客人退场 = 撤它那一格 +
//! 摘掉它挂在板上的全部牌子。
//!
//! # 一问一答的载体
//!
//! 往返**建在会话上**，不另铸一条路——两侧都用同一对动作
//! （[`seat`](crate::session::Quay::seat) + [`claim`](crate::session::Quay::claim)，
//! 靠**孔上的记号**对位，见 [`call::mark_of`]）：
//!
//! ```text
//!   客侧（问）                              板侧（答）
//!   open(生我者) + seat(名字) + claim        seat(名字) + claim(客人)
//!     ├ 交出一枚孔（本端读，刻着名字）──────▶ 落到**生我者**表里（不是板手里）
//!     └ 等板那一枚（本端写） ◀────────────── 板交出一枚孔（板读，刻着同一个名字）
//!                                            装配者：把那枚孔 Ship 给板线程
//!   post([op][名字][入口号]) ──────────────▶ pull ⇒ 交给板
//!   pull → [status]          ◀────────────── post([status])
//! ```
//!
//! **中间那一格（装配者转授）是必须的**：客人只认得它的生我者（[`session`](crate::session)
//! 事实 1），故客人交出来的那一枚先落在装配者表里，板线程拿不到——由装配者转授过去。
//! 转授的是**客人开的那扇门**：副本共享 `owner` **与记号**，故板那一侧照样认得出它。
//!
//! **入口不从这条路上来**：它由会话进对方的表（注册时客人把入口 `Accord` 给板，
//! 查到后板把板上那一份 `Accord` 回客人），故**答案那一侧没有存放"编号"的那一格**——
//! 塞一个号只会多出一份两边都得认的约定。帧形见 [`call::ASK`]：一问一答各一条，
//! **上限就是它**。
//!
//! # 唯一的判据：那枚入口是你亲手交给我的
//!
//! ```text
//!   register 收下 (name, entry, who)   ⇒  probe(entry) == Some(who)
//!                                      且 entry 上的记号 == "entry" 才写板
//! ```
//!
//! `who` 由**内核在 Push 那一刻盖章**（`MailCall::Pull` 连发送者一起交回），报文里
//! **没有"来源"字段**；`probe` 是 `PieCall::Reserve`，答"这枚谁授的"；**记号**是同一
//! 原语的第三格，答"这是哪条路上的那一枚"——客人交来的问话孔与入口**都是它铸、它交的**，
//! 只有记号分得开（那一格读 [`call::mark_of`]）。
//! 于是"抢注"与"把名字绑到别人的入口"是同一道门挡住的两件事。
//!
//! **不存预约表**：谁能用哪个名字是装配期的事（谁拿到那枚入口），不是板上的判定。
//! 代价照实说——拿到持板者入口的任何服务，都能挂**任意未被占用的名字**，
//! "已占用"是唯一的护栏。
//!
//! # 两条不变量
//!
//! - **一个名字一枚牌子**：`find` 按名字定位，`register` 遇到别人的实例答 `Taken`，
//!   自己的实例覆盖（重登 / 换绑），故同一名字在板上只有一条路。
//! - **板上不留死实例**：那一枚入口**答不出**（`Probe` 答 `None`——**不在我表里**，**或**
//!   它那扇门**已经封印**）即**当场扫空**（`sweep_at`）。
//!   "从未登记 / 已注销 / 已死"因此是**同一个状态**（无实例），`Unknown` 只有一种语义，
//!   服务重启也能重登——不需要回收路径，也不需要存活通知。
//!
//! # 谁给持板者那枚入口
//!
//! 与 [`session`](crate::session) 同一条路：**由父域经 `Accord` 下发**
//! （`env/src/fid.rs` 里那句旧注记说的就是这件事）。板是一枚普通入口，不是内核机制；
//! 自举不需要"目录入口"这一格启动参数——`boot` 写 args 的时候还没有任何服务。
//!
//! # 两层
//!
//! ```text
//!   core.rs  板 / 牌子 / 失败域 / 三个动作 + 扫牌      —— 不碰内核（判据可机械检查）
//!   desk.rs  板侧那本账：一位客人一格（谁 / 问 / 答）   —— 同上，探活靠注入
//!   call.rs  盖章 / 探活 / 授出 / 放下 / 一问一答  —— 一处裁决都没有（见该文件头）
//! ```
//!
//! # 谁用它
//!
//! [`system`](super) 起服务时靠它把名字对上入口：`grant` 是**静态**的那一步（装配期把门闩
//! 按名字交进子域），板是**运行期**那一步——同一个问题的两种时候。
//!
//! **三侧分家住**：**客侧**（`client`：`open` / `ask` / `take`，从外面找上板的那些手）
//! 在本文这一侧；**板那一台**（`server`，就一枚线程招待所有客人）、它那本客人账（`desk`）
//! 与**装配侧**（`bridge`：谁给谁转授、什么时候起板线程）住
//! `programs/src/supervisor/system/board/`。今天有四位客人：
//!
//! ```text
//!   router  线路由者（S 态）：**不挂牌子**——只装板路 + 交问话孔，让板看得见它的死
//!   guest   最小特权域（U 态）：自己挂牌 + 说一句"我走了"；**找 router 走树**（`/device/router`）
//!   passer  过客：起来、挂个名字、直接死（不说再见）
//!   echo    调试回显（U 态）：也挂一个名字——那一挂只为让板**看得见它的死**（编排域的监督事件源）
//! ```
//!
//! **照实记**：按名找服务改走树（`operator` 的 `/device`）之后，板上 [`Board::lookup`]
//! **没有真客人**了——`router` 与 `guest` 都从树上问。这一格今天"有机制、没读数"，去留另裁。
//!
//! # 板为什么就一枚线程
//!
//! 牌子上的入口是**一枚只在对端表里有意义的句柄**（`PieToken` = "我这张表里的第几个"）。
//! "查到了要把入口授出去"必须由**持有那一枚的那张表**来做——故所有牌子只能住同一张表，
//! 也就是同一枚线程。"每位客人一枚待客线程"那种形状栽在这里：甲的入口在甲的板线程表里，
//! 乙来查时乙的板线程手里没有它 ⇒ `probe` 判它"已死"（牌子当场被扫空）、`give` 也交不
//! 出去——**症状是"刚挂上的名字，别人一查就是 `Unknown`"**。
//!
//! 一枚线程招待多位客人：**一位客人的孔就是组里的一格**——板线程用一枚组同时等"提示孔 +
//! 每位客人的问话孔"（`Tole::await_`，一次 `Await` 等任意一格）。只有"还有客人没挂齐"的
//! 那几轮才退化成节拍轮询（一位 `1ms`）；挂齐了就是 `usize::MAX`，**真挂起、不空转**。
//!
//! **照实记**：这一格原先写的是"门铃与孔各有各的唤醒键，今天没有'同时等 N 个源'，这是
//! 那一格在板这一侧的代价"——组（`Tole`）落地之后那句已经不成立，而**板线程自己就是它的
//! 第一个用户**。
//!
//! **板只管把入口交到手上，不管拿到之后说什么**：那两位之间那一句是 32 字节的名字
//! （`programs/src/user/guest.rs` 的头注）——那是**服务自己的事**，不是本协议的一格。
//! 真要做"调用"，帧形得另开一轮裁决。
//!
//! # 授进来的那一枚怎么认出来
//!
//! `Reply` 里**没有号**（见上：入口从会话里来），故客人只能自己在表里认出它：
//!
//! ```text
//!   vestor == 板           ← 这一份是板交给我的（唯一的"来源"格）
//!   不是本端这条板路那两枚  ← 那两枚里有一枚的 vestor 也是板（板铸的读端）
//!   取最后登记的那一枚      ← 一次一问一答只授一枚
//! ```
//!
//! **`owner` 在这里没用**：那扇门是**对端**开的，客人不是它的开者。按 `owner` 找只在
//! "挂的是自己铸的那一枚"时碰巧成立（自重登、自问自答的那一趟）；换一位真客人就找不到
//! ——这一格是接了 `guest` 才露出来的。
//!
//! **v1 里还没有客人用的那一格**：[`Board::unregister`] 线上有码、核心有动作，但客人退场
//! 走的是 [`call::DISMISS`]（**整位**退场：撤格 + 摘牌一次做完），故没有谁急着发那一条
//! **逐名**的右半。
//!
//! **退场是客人说的，死亡仍是板看见的**：客人走之前说一句 `DISMISS` ⇒ 板当场撤掉它那一格、
//! 摘掉它挂在板上的全部牌子、把它的问话孔从组里摘掉（名字的位置留着）；**没说就走**的那种
//! 仍由**惰性剔除**扫掉（那一枚入口答不出即当场扫空：`Probe` 答 `None`——**不在我表里**，
//! **或**它那扇门**已经封印**，见 [`core::Probe`]），而板那一侧留着的那一枚孔仍在——封印动的是
//! **资源**，板那份句柄还在表里，`Probe` 对它答 `None`：判据正是落在这一格上。

// ── 载体：三侧分别住在哪 ───────────────────────────────────
//
// **使用侧** [`client`]（客侧三手）住这里——那是"别的任务怎么找上板"。**实现侧**（板那一台）
// 与**装配侧**（把板接上客人）住 `programs/src/supervisor/system/board/{server,bridge}.rs`：起那枚线程、转授、
// 递格都是那一枚域在干活。下面这段是那一台的图与次序——它讲的是"怎么跑"。
//
//!  ```text
//!    装配者（编排域 system）                    客人（服务域）            板线程（一枚）
//!    quay.seat(板路) + quay.claim(客人, 板路) ▶ open: seat(板路) + claim(生我者, 板路)
//!    转授：把客人那一枚 Ship 给板线程 ─────────────────────────────────▶  按"谁转授的 + 记号"认答话写端
//!    板路上先递一格：板线程的号 ────────────▶  open 收下 ⇒ 此后叫得出板
//!    提示：往提示之路推一个客人号 ────────────────────────────────────▶  收一位客人（admit）
//!                                             铸问话孔(ask)、Ship 给板 ─▶  按"谁开的 + 记号"认出 ⇒ arm + attach
//!                                             推(Query) ────────────────▶  组唤醒 ⇒ pull ⇒ 交给板
//!                                             读(Reply) ◀───────────────  推(Reply)
//!  ```
//!
//!  **两条路各一枚孔，两枚都落进板的表里**：答话那条的**写端**由装配者转授（板路那条会话），
//!  问话那条由**客人自己铸**再交给板。板按 `(谁, 记号)` 认领：答话写端认**记号 `board`**
//!  （交者是装配者），问话孔认**记号 `ask`**（开者是客人）——客人是**唯一"每位客人各不同"
//!  的身份**，故板只能按它分人；板自己铸则八位客人的孔同形，反倒认不出是哪位的。
//!
//!  **两枚孔都要客人先叫得出板**：孔是"铸的人那张表里的第几个"，换一张表就念不出来。客人
//!  只认得生我者（装配者），故装配者在**板路上先递一格 8 字节：答话的是谁**——与提示孔那
//!  一格对偶（告板"客人是谁"，也告客人"答话的是谁"）。缺这一格，客人交出来的孔就落进装配
//!  者表里，而装配者不代转：板永远收不到问话（实测症状：板每轮都是 `settling`，客人超时）。
//!
//!  板把**所有**问话孔挂进**一个组**，于是"等 N 位客人说话"是一件事，不是一个轮询圈。
//!
//!  **为什么中间要装配者过一手**：客人只认得它的生我者（孔是交给"生我者"的），板线程不是
//!  它的生我者 ⇒ 客人交出来的那一枚落在装配者表里。装配者把它**转授**给板线程——装配者本来
//!  就是设备门闩的第一个持有者与转授者，这里走的是同一条路。转授的是**客人开的那扇门**：
//!  副本共享 `owner` **与记号**（`session` 事实 3），故板那一侧照样念得出"这是哪位的孔、
//!  走的哪条路"。
//!
//! # 一问一答的次序
//!
//! ```text
//!   1  装配者在本域与客人那座码头上加一条板泊位（本端交出自己那一枚 —— 答话从它走）
//!   2  认领：**这位客人**交出来的那一枚落进本域表里（客人只认得生我者，故先落这里）
//!   3  板线程（只起一枚）→ 把客人那一枚转授给它 → 板路上递一格「答话的是谁」 → 提示来客人了
//! ```
//!
//! 三步都在 [`bridge::attach`] 里，**次序即契约**。

