//! Board Protocol — **死信号传感器**：哪些客人还活着（编排域的监督从这里读）。
//!
//! ```text
//!   板看见       哪一位客人没了（它开的那扇门封印了，或它自己说了"我走了"）
//!   板推进       那一位的**死亡道**（一位一条）——监督从组上醒来据此记账
//! ```
//!
//! **照实记（"公示板"那一半已退场）**：本协议原先还有另一半——**公示板**（一个名字，此刻指向
//! 哪个入口：`REGISTER` / `UNREGISTER` / `LOOKUP`）。**按名找服务归树**是用户裁定（记在
//! `harness/src/guest.rs`：驱动挂 `/svc/drv`），故 `LOOKUP` 此后**没有真客人**；本笔按新裁定
//! 「board 只保留**死信号**一件」把"名字 → 入口"那条语义整支退场：`Board::lookup` /
//! `lookup_after` 两具读手删了（读路径那一格惰性剔死改由**表侧**按 `join(POLL)` 与死信号
//! 落地），线上 `LOOKUP` 那一码只剩帧形（`frame.rs` 一个字不动），板上不再有动作。
//! 板今天只干一件事：**待客账**（谁还活着——编排域的监督从这里读）。
//!
//! **它住在 [`system`](super) 之下**（用户裁定：`system` **容纳**它）：它是**编排域自己的一个
//! 机构**——板线程由本域起、住本域里（`programs/src/system/board/` 就是它那台），
//! 而它那本客人账正是监督的输入。
//!
//! **照实记（这一句原先举错了另一半）**：原写"这是同一份正文的**运行期那一半**——
//! [`grant`](super::grant) 管装配期'名字对上入口'"。而 `grant` 管的是**配给记录的解码**
//! （固件回的那段"坐标 + 号"），**与名字无关**；装配期那一步在**装配机器**手里（单子上的
//! `name` ＋ 起手时交出去的入口）。故这一格的依据换成上面那条：**它是编排域自己的机构**。
//!
//! 内核**不参与**这件事：它没有"通知谁死了"的动词，只答"这一枚句柄此刻还答不答得出"
//! （`PieCall::Reserve`）。故"某位客人没了"只能由**替他看着那扇门**的人看出来，而这个协议
//! 就是那块**死信号面**。
//!
//! # 一块板，一枚牌子
//!
//! ```text
//!        板（Board）           牌子（Sign）
//!   ┌──────────────────┐   ┌───────────────┐
//!   │  叫什么 │ 在哪   │   │  Name         │  ← 双方的坐标
//!   │ ────────┼─────── │ = │  Option<入口> │  ← None = 没实例
//!   │  console│  ■     │   │  Option<谁挂> │  ← 无实例时它无意义
//!   │  irq    │  □     │   └───────────────┘
//!   └──────────────────┘
//! ```
//!
//! # 三个动作（**没有"查"**）
//!
//! | 动作 | 谁 | 落在一枚牌子上 | 失败 |
//! |---|---|---|---|
//! | [`Board::register`] | provider | **报到**：写下自己那一格 | `Denied` / `Taken` / `Full` |
//! | [`Board::unregister`] | provider | 摘下自己那一格（**牌子留着**） | `Unknown` / `Denied` |
//! | `Evict` | client | 整位退场（**按主人**，不按名字） | `Unknown` |
//!
//! 线上留下的码还有第四个（`LOOKUP`）——**它已退场**（见文件头照实记）：帧形还在（`frame.rs`
//! 不动），板上答 `Unknown`（"这一码我不认"）。模型里的"名字 → 入口"那一问（`Board::lookup`）
//! 连同一具读手一起删了。
//!
//! 线上的形状是 **`Req` → `Union`**：一问一答，一次往返。三个动作是**模型**里的动作
//! （`register` / `unregister` / `evict` 那一张表），线上那一侧的名字是 `Req`——两者不是
//! 重名，是同一件事的两层（[`communication::establish`] 里 `endpoint` 既是动作也是那一步的说法）；收进来的一问
//! 另叫 `Wire`（它多一格：表外的动作码）。
//!
//! 线上还有第四条动作 `frame::Req::Evict`（**一字节短帧，空载荷**），它**不落在牌子上**：那
//! 一句落在板侧那本客人账上（`Desk`，一位客人一格）——一位客人退场 = 撤它那一格 +
//! 摘掉它挂在板上的全部牌子。
//!
//! # 一问一答的载体
//!
//! 往返**建在会话上**，不另铸一条路——两侧都用同一手（[`endpoint`](crate::communication::establish::endpoint)，
//! 铸本端那一枚 ＋ 认下对端那一枚），靠**孔上的记号**对位，见
//! [`marked_as`](crate::communication::establish::marked_as)）：
//!
//! ```text
//!   客侧（问）                              板侧（答）
//!   endpoint(生我者, 名字)                  endpoint(客人, 名字)
//!     ├ 交出一枚孔（本端读，刻着名字）──────▶ 落到**生我者**表里（不是板手里）
//!     └ 等板那一枚（本端写） ◀────────────── 板交出一枚孔（板读，刻着同一个名字）
//!                                            装配者：把那枚孔 Ship 给板线程
//!   post([op][名字][入口号]) ──────────────▶ pull ⇒ 交给板
//!   pull → [status]          ◀────────────── post([status])
//! ```
//!
//! **中间那一格（装配者转授）是必须的**：客人只认得它的生我者（[`communication`](crate::communication)
//! 事实 1），故客人交出来的那一枚先落在装配者表里，板线程拿不到——由装配者转授过去。
//! 转授的是**客人开的那扇门**：副本共享 `owner` **与记号**，故板那一侧照样认得出它。
//!
//! **入口不从这条路上来**：它由会话进对方的表（注册时客人把入口 `Accord` 给板，
//! 查到后板把板上那一份 `Accord` 回客人），故**答案那一侧没有存放"编号"的那一格**——
//! 塞一个号只会多出一份两边都得认的约定。帧形见 `frame::Req`（问那一侧的长度上限是
//! `frame::REQ_LEN`）：一问一答各一条，**答只有一格**（`frame::Status::LEN`）。
//!
//! # 唯一的判据：那枚入口是你亲手交给我的
//!
//! ```text
//!   register 收下 (name, entry, who)   ⇒  probe(entry) == Some(who)
//!                                      且 entry 上的记号 == "entry" 才写板
//! ```
//!
//! `who` 由**内核在 Push 那一刻盖章**（`MailCall::Pull` 连发送者一起交回），报文里
//! **没有"来源"字段**；`probe` 是 `PieCall::Reserve`，答"这枚谁授的"；**记号**是同一
//! 原语的第三格，答"这是哪条路上的那一枚"——客人交来的问话孔与入口**都是它铸、它交的**，
//! 只有记号分得开（那一格读 `call::marked_as`）。
//! 于是"抢注"与"把名字绑到别人的入口"是同一道门挡住的两件事。
//!
//! **不存预约表**：谁能用哪个名字是装配期的事（谁拿到那枚入口），不是板上的判定。
//! 代价照实说——拿到持板者入口的任何服务，都能挂**任意未被占用的名字**，
//! "已占用"是唯一的护栏。
//!
//! # 两条不变量
//!
//! - **一个名字一枚牌子**：`find` 按名字定位，`register` 遇到别人的实例答 `Taken`，
//!   自己的实例覆盖（重登 / 换绑），故同一名字在板上只有一条路。
//! - **板上不留死实例**：那一枚入口**答不出**（`VestedBy` 答 `None`——**不在我表里**，**或**
//!   它那扇门**已经封印**）即**当场扫空**（`sweep_at`）。
//!   "从未登记 / 已注销 / 已死"因此是**同一个状态**（无实例），`Unknown` 只有一种语义，
//!   服务重启也能重登——不需要回收路径，也不需要存活通知。
//!
//! # 谁给持板者那枚入口
//!
//! 与 [`communication`](crate::communication) 同一条路：**由父域经 `Accord` 下发**
//! （`env/src/fid.rs` 里那句旧注记说的就是这件事）。板是一枚普通入口，不是内核机制；
//! 自举不需要"目录入口"这一格启动参数——`boot` 写 args 的时候还没有任何服务。
//!
//! # 两层
//!
//! ```text
//!   core.rs  板 / 牌子 / 失败域 / 三个动作 + 扫牌      —— 不碰内核（判据可机械检查）
//!   （客人账不在这一层了：两本并成一本，住 `programs/src/system/desk.rs`）
//!   `protocol` 的 system/board/mod.rs  盖章 / 探活 / 授出 / 放下 / 一问一答  —— 一处裁决都没有（见那一段）
//! ```
//!
//! # 谁用它
//!
//! [`system`](super) 起服务时靠它把名字对上入口：`grant` 是**静态**的那一步（装配期把门闩
//! 按名字交进子域），板是**运行期**那一步——同一个问题的两种时候。
//!
//! **三侧分家住**：**客侧**（`programs::system::board::client`：`BERTH` / `enroll` /
//! `register` / `evict`，从外面找上板的那些手）与**板那一台**（`server`，就一枚线程招待所有
//! 客人）、它那本客人账（客人在 `programs::system::desk`，两本并一本）与**装配侧**
//! （`bridge`：谁给谁转授、什么时候起板线程）**全住 `programs/src/system/board/`**——本文这一侧
//! 只留形与记号。今天有七位客人（`lodger` 不上板：它喂的是线那本账）：
//!
//! ```text
//!   router  线路由者（U 态）：**不挂牌子**——只装板路 + 交问话孔，让板看得见它的死
//!   uart    串口驱动（U 态）：同上（不挂牌子）
//!   rtc     实时钟驱动（U 态）：同上（不挂牌子）
//!   guest   最小特权域（U 态）：自己挂牌 + 说一句"我走了"；**找 router 走树**（`/svc/drv/router`）
//!   passer  过客：起来、挂个名字、直接死（不说再见）
//!   sleeper 客人（U 态）：挂一个名字（同 `canonical` 的理由）+ 从树上找 `/svc/drv/rtc`
//!   canonical 控制台那一台（U 态）：也挂一个名字——那一挂只为让板**看得见它的死**（编排域的监督事件源）
//! ```
//!
//! **照实记（"留着"那一格后来退了）**：按名找服务改走树（`operator` 的 `/svc/drv`）之后，
//! 板上 `Board::lookup` 就没有真客人了——**命名归树，板只管生死**。当初按用户裁定**留着**它
//! （它是核心的读出口，且读路径顺带做惰性剔除）；本笔按新裁定「board 只保留**死信号**一件」
//! 把它连同 `lookup_after` 一起退场：命名本来就有去处（树），读路径那一格惰性剔死改由**表侧**
//! 按 `join(POLL)` 与死信号落地（见 `programs/src/system/board/core.rs` 的照实记）。
//! 谁要按名找服务，走树。
//!
//! # 板为什么就一枚线程
//!
//! 牌子上的入口是**一枚只在对端表里有意义的句柄**（`PieToken` = "我这张表里的第几个"）。
//! "查到了要把入口授出去"必须由**持有那一枚的那张表**来做——故所有牌子只能住同一张表，
//! 也就是同一枚线程。"每位客人一枚待客线程"那种形状栽在这里：甲的入口在甲的板线程表里，
//! 乙来查时乙的板线程手里没有它 ⇒ `probe` 判它"已死"（牌子当场被扫空）、`ship` 也交不
//! 出去——**症状是"刚挂上的名字，别人一查就是 `Unknown`"**。
//!
//! 一枚线程招待多位客人：**一位客人的孔就是组里的一格**——板线程用一枚组同时等"提示孔 +
//! 每位客人的问话孔"（`Pile::await_`，一次 `Await` 等任意一格）。只有"还有客人没挂齐"的
//! 那几轮才退化成节拍轮询（一位 `1ms`）；挂齐了就是 `Wait::Forever`，**真挂起、不空转**。
//!
//! **照实记**：这一格原先写的是"门铃与孔各有各的唤醒键，今天没有'同时等 N 个源'，这是
//! 那一格在板这一侧的代价"——组（`Pile`）落地之后那句已经不成立，而**板线程自己就是它的
//! 第一个用户**。
//!
//! **板只管把入口交到手上，不管拿到之后说什么**：那两位之间那一句是 32 字节的名字
//! （`harness/src/guest.rs` 的头注）——那是**服务自己的事**，不是本协议的一格。
//! 真要做"调用"，帧形得另开一轮裁决。
//!
//! # 授进来的那一枚怎么认出来
//!
//! `Union` 里**没有号**（见上：入口从会话里来），故客人只能自己在表里认出它：
//!
//! ```text
//!   vestor == 板           ← 这一份是板交给我的（唯一的"来源"格）
//!   不是本端这条板路那两枚  ← 那两枚里有一枚的 vestor 也是板（板铸的读端）
//!   取最后登记的那一枚      ← 一次一问一答只授一枚
//! ```
//!
//! **`owner` 在这里没用**：那扇门是**对端**开的，客人不是它的开者。按 `owner` 找只在
//! "挂的是自己铸的那一枚"时碰巧成立（自重登、自问自答的那一趟）；换一位真客人就找不到
//! ——这一格是接了 `guest` 才露出来的。
//!
//! **v1 里还没有客人用的那一格**：[`Board::unregister`] 线上有码、核心有动作，但客人退场
//! 走的是 `frame::Req::Evict`（**整位**退场：撤格 + 摘牌一次做完），故没有谁急着发那一条
//! **逐名**的右半。
//!
//! **退场是客人说的，死亡仍是板看见的**：客人走之前说一句 `Evict` ⇒ 板当场撤掉它那一格、
//! 摘掉它挂在板上的全部牌子、把它的问话孔从组里摘掉（名字的位置留着）；**没说就走**的那种
//! 仍由**惰性剔除**扫掉（那一枚入口答不出即当场扫空：`VestedBy` 答 `None`——**不在我表里**，
//! **或**它那扇门**已经封印**，见 [`core::VestedBy`]），而板那一侧留着的那一枚孔仍在——封印动的是
//! **资源**，板那份句柄还在表里，`VestedBy` 对它答 `None`：判据正是落在这一格上。

// ── 载体：三侧分别住在哪 ───────────────────────────────────
//
// **使用侧**（客侧那几手）与**实现侧**（板那一台）**都在实现树那一边**（`programs/src/system/
// board/{client,server}.rs`）——本文这一侧只留形与记号。**装配侧**（把板接上客人）同住那一处
// （`bridge.rs`：起那枚线程、转授、递格都是那一枚域在干活）。下面这段是那一台的图与次序
// ——它讲的是"怎么跑"。
//
//!  ```text
//!    装配者（编排域 system）                    客人（服务域）            板线程（一枚）
//!    endpoint(客人, 板路)               ▶   open: endpoint(生我者, 板路)
//!    转授：把客人那一枚 Ship 给板线程 ─────────────────────────────────▶  按"谁转授的 + 记号"认答话写端
//!    板路上先递一格：板线程的号 ────────────▶  open 收下 ⇒ 此后叫得出板
//!    提示：往提示之路推一个客人号 ────────────────────────────────────▶  收一位客人（admit）
//!                                             铸问话孔(ask)、Ship 给板 ─▶  按"谁开的 + 记号"认出 ⇒ arm + attach
//!                                             推(Req) ──────────────────▶  组唤醒 ⇒ pull ⇒ 交给板
//!                                             读(Union) ◀─────────────────  推(Union)
//!  ```
//!
//!  **两条路各一枚孔，两枚都落进板的表里**：答话那条的**写端**由装配者转授（板路那条会话），
//!  问话那条由**客人自己铸**再交给板。板按 `(谁, 记号)` 认领：答话写端认**记号 `board`**
//!  （交者是装配者），问话孔认**记号 `ask`**（开者是客人）——客人是**唯一"每位客人各不同"
//!  的身份**，故板只能按它分人；板自己铸则八位客人的孔同形，反倒认不出是哪位的。
//!
//!  **两枚孔都要客人先叫得出板**：孔是"铸的人那张表里的第几个"，换一张表就念不出来。客人
//!  只认得生我者（装配者），故装配者在**板路上先递一格 8 字节：答话的是谁**——与提示孔那
//!  一格对偶（告板"客人是谁"，也告客人"答话的是谁"）。缺这一格，客人交出来的孔就落进装配
//!  者表里，而装配者不代转：板永远收不到问话（实测症状：板每轮都是 `settling`，客人超时）。
//!
//!  板把**所有**问话孔挂进**一个组**，于是"等 N 位客人说话"是一件事，不是一个轮询圈。
//!
//!  **为什么中间要装配者过一手**：客人只认得它的生我者（孔是交给"生我者"的），板线程不是
//!  它的生我者 ⇒ 客人交出来的那一枚落在装配者表里。装配者把它**转授**给板线程——装配者本来
//!  就是设备门闩的第一个持有者与转授者，这里走的是同一条路。转授的是**客人开的那扇门**：
//!  副本共享 `owner` **与记号**（[`communication`](crate::communication) 事实 3），故板那一侧照样念得出"这是哪位的孔、
//!  走的哪条路"。
//!
//! # 一问一答的次序
//!
//! ```text
//!   1  装配者在本域与客人之间装一对孔（`establish::endpoint`：本端交出自己那一枚 —— 答话从它走）
//!   2  认领：**这位客人**交出来的那一枚落进本域表里（客人只认得生我者，故先落这里）
//!   3  板线程（只起一枚）→ 把客人那一枚转授给它 → 板路上递一格「答话的是谁」 → 提示来客人了
//! ```
//!
//! 三步都在 [`bridge::attach`] 里，**次序即契约**。

