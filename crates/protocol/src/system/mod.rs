//! System Protocol — **执行实体的存在、组织与生命周期**。
//!
//! 它不定义资源权限（那是 `env::fid` 的 `PieCall` 与各具体协议的事），也不定义任何
//! 领域语义，只回答一件事：**这个执行实体是否存在、从哪来、什么时候结束。**
//!
//! # 实现面在内核 ABI 上（本模块目前没有代码）
//!
//! 第一版没有 System Server，六个动词全是 envcall——`env::fid` 的 **`UnitCall` 整类**
//! 加 **`RoomCall` 的 `Reap` / `Doom`**（判别号与载荷见那边，本模块不重复）。正文落在
//! 这里是因为这里是协议层的家；它的线格式与门在 `crates/env`。哪天它长成域间协议
//! （System Server），代码才写进本模块。
//!
//! # 生命周期
//!
//! ```text
//!   Build                     装域：Space + Team，无线程
//!     │
//!   Spawn                     往该 Team 产线程（恒产 Held）
//!     ▼
//!   Held ──Hatch──▶ Starved ──上核──▶ Running ⇄ Blocked
//!     │                │                  │
//!     └────────────────┴──── Doom ────────┘
//!                      ▼
//!                   Doomed ──reap（退出钩子）──▶ Reaped ──bury──▶ 回收
//! ```
//!
//! # 词汇（两处撞名在这里说清）
//!
//! - **Unit = `Task | Team` 的合称**。代码里**没有 `Unit` 这个类型**，本文件用它指代
//!   两者。
//! - `runtime::core::unit` 是**另一件事**：本域内产线程跑闭包、把结果取回来。撞的是词
//!   不是事，**不改名**，此处声明区分。
//! - **`Spawn` 只有"产 Held"一个意思**：内核侧曾有一枚同名别名（`TaskBuilder::spawn`
//!   = `hold` + 放行），已删——放行是单独一步（ABI 的 `Hatch`，内核的 `Task::release`）。
//!
//! **六个动词**：`Build` / `Spawn` / `Hatch` / `Join`（class 1）+ `Doom` / `Reap`
//! （class 0）。另有四个只读观察面：`SelfId` / `Sire` / `HeirCount` / `Heir`。调度侧的
//! `Starve` / `Park` / `Wait` / `Wake` **不属于**本协议——它们答"什么时候再跑"，不答
//! "这个执行实体还在不在"。
//!
//! # 五道门，一道都不走 Pie
//!
//! | 操作 | 门 |
//! |---|---|
//! | `Build` | 调用方是 S 态域——**特权级**；能力面不为建域背书 |
//! | `Spawn` | 目标 team ∈ 我 `heir`，或本域（`TeamId(0)`） |
//! | `Hatch` | 同域，或在我 `heir` 里 |
//! | `Doom` | 目标域是我沿 `sire` 链可达的**严格后代**（**传递**，按**域**判） |
//! | `Join` | 同域，或在我 `heir` 里（目标已消失时不核） |
//!
//! `Reap` 没有门：它只能对自己——"我不再续跑，来收我"的自退声明，不带目标参数。
//!
//! # 血缘
//!
//! `Build` 时 `sire` 非空 ⇒ 立即入 `sire.heir`（构造期闭合，`adopt` 是唯一写点）。
//! 父方强 `heir`、子方弱 `sire`，是防环唯一边。`heir` **只增不减**——它记的是"生过
//! 多少个子域"，不是"有几个活着"。
//!
//! # 终止与回收分两段
//!
//! `Doomed` = 已停摆（退出钩子未跑）；`Reaped` = 收尾已完成（唯一置位路径是
//! `messenger::reap` ⇒ `Join` 的判据不含竞态）。回收（栈 / trap 帧 / 空间）留到
//! `bury`。父被回收时，退出钩子沿 `heir` 两阶段扑杀整棵子树：先让全部受害者停摆，
//! 再逐个跑钩子——阶段边界即安全边界。
//!
//! # 顶级 Unit 的收场
//!
//! 顶级 Unit（今天只有 root）由内核直接引入、`sire` 为空 ⇒ `Doom` 的判据恒假 ⇒
//! **没有任何调用者能对它 `Doom`，包括它自己的域**。它的收场只有一条路：**自己 `Reap`
//! 自己**（自退触发级联，把剩下的 `heir` 一起收掉）。唯一的例外是内核的紧急路径。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **`TeamId` 不是存在性坐标**：它只增不减、又被父的 `heir` 强持有 ⇒ 读出来永远
//!   "在"。故 `Doom` / `Join` 只认 `TaskId`；`Build` 之后没 `Spawn` 的空域没有单独
//!   终止的手段，它随父收场（父的 `heir` 一放，`Arc` 归零）。
//! - **判据传递、观察一层**：`Doom` 的授权是传递的，而观察面只有 `Sire`（一层）⇒
//!   调用方无法预知自己能杀谁。今天 `Doom` 零域侧调用者，这条不对称不痛。
//! - **终止有第三个来源**：内核的紧急路径（如不可解析的缺页）不以血缘为门——它直接
//!   置 `EXIT_FAULT` 后 `quit()`，不经任何 ABI 动词。
//! - **名字会撞**：`Team.name` 由装配侧决定，同父下 `@unit-address` 保证唯一，跨父不
//!   保证（实测 `flash@20000000` 有两枚同名）——本协议不解释名字。
//!
//! 策略（该不该杀、该给什么身份）不在这里：**内核只回答"能不能"**。
