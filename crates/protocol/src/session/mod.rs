//! Session Protocol — **会话建立**：两个陌生实体怎么建起一条会话。
//!
//! 它不定义消息格式、不定义负码表、不管收发——那些归各具体协议。它只回答一件事：
//! **两个手里都没有对方门闩的 Task，怎么把会话的两端凑到各自手里。**
//!
//! # 陌生在哪：身份是免费的，地址不是
//!
//! ```text
//!   知道对方是谁        ← 内核免费给：`sire`（谁生了我）、每枚门闩上的"谁授的"
//!   手里有对方的门闩    ← 谁都不给：建起之前，双方都没有
//! ```
//!
//! 所以会话不是"交换地址"，是**一侧先铸一枚交给对方**。两个动作一合就成：
//!
//! ```text
//!   我这一侧                          对方那一侧
//!   Quay::open(对端)                  （它知道我是谁：内核告诉它"生你的是谁"）
//!   seat(名字) ─── 一枚孔 + 名字 ───▶ 落到它的表里（盖上"我授的"）
//!                                     claim(我, 期限)  扫表认领，按名字归位
//!                                              │
//!                                              ▼
//!                                     seat(名字) 也交一枚回来
//!   ◀───────────── 它的孔 ───────────┘
//!   ⇒ 两侧各持两枚孔 ⇒ 数据面 = `Port`（本协议不管收发）
//! ```
//!
//! **认领的判据是"谁授的"，不是名字、不是位置、不是内容**——那三样都能被伪造或乱序；
//! 内核盖在投递那一刻的戳子不能。这是本协议**不发明名字系统**的原因：按名字寻址是
//! 目录的事，不在这一层。
//!
//! # 四对动作，各自管一个范围
//!
//! | 对 | 范围 | 过不过线 |
//! |---|---|---|
//! | [`Quay::open`] ↔ [`Quay::shut`] | 整座码头 | 不过（各自整理） |
//! | [`Quay::seat`] ↔ [`Quay::unseat`] | 一条泊位 | **过**：拆下要告诉对方，否则它会一直往没人收的通道里推 |
//! | [`Quay::claim`] ↔ [`Quay::reclaim`] | 对方送来的那一批 | 不过（改我这边的账） |
//! | [`Quay::pair`] | 一条路（**只读**） | **过**：装 + 亮名字，等对方把回话那一枚交进来 |
//!
//! 前三对里，`claim` 是**双向**那一档（两侧各装一条，凑齐才算通）；`pair` 是它的对偶——
//! **一问一答**：装上、亮名字、等答复，中间没有第二条路要等。要会话用 `claim`，
//! 要一次往返用 `pair`（板协议就建在它上面）。
//!
//! # 两条不变量（照实写，它们是这一层的全部价值）
//!
//! - **不许半条会话**：认领要么整批到手、要么报错（[`Claim::Partial`] / [`Claim::Timeout`]）
//!   ——"建起"是一个整体事件，不是流水。
//! - **失败不留半行**：装上到一半失败，用 [`Quay::shut`] 收干净即可，不必另有一个
//!   "清理"动作（能容忍"没开全"的关张就是清理）。
//!
//! # 六条实测事实（写进代码才发现的，签名看不出来）
//!
//! 1. **对端是"建那个域的那个线程"**，不是被产出来的那一枚线程（`Quay::bind` 的正文）：
//!    子方把孔交给"生我者"，故父方要跟生者打交道。**这一条错了的症状是会话永远认领
//!    不到**——孔明明交出去了。
//! 2. **一次会话是两枚孔**：`seat` 交出去的那一枚是本端**读**的，"认领"进来的那一枚
//!    是本端**写**的。两个方向各一枚，不能混（`Pier::hole` 与 `Pier::at_peer`）。
//! 3. **对端那一枚要按 `owner` 认，不是按 `grantor`**（`call::owner_of`）。内核那两个
//!    戳子回答的是两件不同的事：
//!    - `vestor`（`Collect` 的第三格 / `Reserve` 的第一格）= **谁授的**。`accord` 出来的
//!      副本，它是**授出方**——故"对端授的"这条判据在本端表里**一枚都匹配不上**。
//!    - `owner`（`Reserve` 的第二格）= **谁开的这扇门**。副本共享同一事实，转手不变；
//!      本端 `mint`/`accord` 出来的每一枚都是本端，对端 `ship` 回来的那一枚是对端。
//!
//!    落点读数（本端 3、对端 4）：本端表里 `tok=21 o=3`、`tok=22 o=3`、`tok=28 o=4`
//!    ——要认的是 28。
//! 4. **一副本一个槽**（`HoleMeta.slot`，`accord` 只克隆 `Arc`）——这条决定了"名字牌"
//!    那条路走不通，见下节。牌本身（名字 32 + 号 8）与定长解码面（[`Name::from_bytes`](env::wire::Name::from_bytes)，
//!    尾随 NUL 是填充）留着，但**现在没有生产者**。
//! 5. **"一枚泊位配一枚孔"是一对一**：本端有几条 `seat` 过还没配齐的泊位，就按先后认领
//!    几枚对端来的孔。只给"第一条"配线，多通道时会错位。
//! 6. **扫表不能设上限**：本端表里可能已经有几十枚孔（设备门闩、别人给的副本……），
//!    设一个"最多看几枚"的缓冲会让排在后面的那一枚永远看不见（`call::each` 不攒数组）。
//!
//! # 三条走不通的判据（踩过，别回头）
//!
//! 认"对端放进来的那一枚孔"时，这三条**都试过**，症状与原因一并记下：
//!
//! | 判据 | 为什么不行 |
//! |---|---|
//! | `h.grantor == 对端` | `accord` 副本的 `vestor` 是授出方（本端）⇒ 一枚都匹配不上 |
//! | `h.grantor == 本端` | 选中本端 `seat` 时铸的那一枚 ⇒ **写端指回自己的槽**，对端永远收不到 |
//! | 令牌号最大的一枚 | 令牌号是**全局**分配的，与"表尾"无关 ⇒ 选中过本端自己那份 |
//!
//! 还有一条**次序**上的坑：对端那一枚是**后到**的。认不出就别绑——早绑一次就钉在自己的
//! 孔上，症状是"本端 `post` 返回成功、对端 `pull` 超时"。`claim` 本来就是循环
//! （`POLL_MS` 一转），下一转再扫即可。
//!
//! 顺带记一条**已经拆掉**的设计：曾经往孔里写一张"名字 + 号"的牌想让对端按名字归位。
//! 但交出去的副本与本体**共享同一个槽**，于是本端读就把对端那张也吃掉、本端不读就占着
//! 单槽挡住对端推来的第一条消息——两条路都不通。名字这一层信息由**对端按 `owner` 认领**
//! 替代（`call::card_arrived` / `read_card` 因此闲置）。
//!
//! # 两层
//!
//! ```text
//!   core.rs   码头 / 泊位 / 失败域 / 七个动作 —— 不碰内核（判据可机械检查）
//!   call.rs   铸孔 / 交出 / 认领 / 放下 / 读孔   —— 一个判断都没有
//! ```
//!
//! # 谁用它
//!
//! [`system`](crate::system) 起服务时用它等"它交回了控制孔"；
//! [`principal`](crate::principal) 的两条不可伪造凭证就是这里的两个戳子
//! （"你是谁"内核免费背书，"别人是谁"不免费）。

