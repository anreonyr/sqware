//! Session Protocol — **会话建立**：两个陌生实体怎么建起一条会话。
//!
//! 它不定义消息格式、不定义负码表、不管收发——那些归各具体协议。它只回答一件事：
//! **两个手里都没有对方门闩的 Task，怎么把会话的两端凑到各自手里。**
//!
//! # 陌生在哪：身份是免费的，地址不是
//!
//! ```text
//!   知道对方是谁        ← 内核免费给：`sire`（谁生了我）、每枚门闩上的"谁授的"
//!   手里有对方的门闩    ← 谁都不给：建起之前，双方都没有
//! ```
//!
//! 所以会话不是"交换地址"，是**一侧先铸一枚交给对方**。两个动作一合就成：
//!
//! ```text
//!   我这一侧                            对方那一侧
//!   Quay::open(对端)                    （它知道我是谁：内核告诉它"生你的是谁"）
//!   seat(名字) ── 一枚孔（刻着这个名字）──▶ 落到它的表里（盖上"我授的"）
//!                                       claim(我, 这个名字, 期限)  扫表认领、归位
//!                                                │
//!                                                ▼
//!                                       seat(名字) 也交一枚回来（刻着同一个名字）
//!   ◀─────────────── 它的孔 ─────────────┘
//!   ⇒ 两侧各持两枚孔 ⇒ 数据面 = `Port`（本协议不管收发）
//! ```
//!
//! **认领的判据是两格正判据**：这扇门**谁开的**（`owner`）+ 孔上**刻的记号**（`mark`）。
//! 两格都是内核在开门那一刻盖/刻上去的戳（"谁授的"是另一个戳子，见事实 3），副本共享同一
//! 事实、转手不变；而名字、位置、内容、号码那四样都能被伪造或乱序。
//! **记号 = 铸者那张表里这条路的名字**（`seat` 铸孔那一刻刻上去的，随副本过线）——
//! 有它，**同一位开的多枚孔**才分得开（只有 `owner` 一格时办不到）。
//! 这是本协议**不发明名字系统**的原因：按名字寻址是目录的事，不在这一层——记号只回答
//! "这是哪条路上的那一枚"，不回答"谁在哪儿"。

//! # 三对动作，各自管一个范围
//!
//! | 对 | 范围 | 过不过线 |
//! |---|---|---|
//! | [`Quay::open`] ↔ [`Quay::shut`] | 整座码头 | 不过（各自整理） |
//! | [`Quay::seat`] ↔ [`Quay::unseat`] | 一条泊位 | **过**：拆下要告诉对方，否则它会一直往没人收的通道里推 |
//! | [`Quay::claim`] | 对方按记号交回来的那一枚 | 不过（改我这边的账） |
//!
//! `claim` 是**双向**那一档：两侧各装一条（各刻同一个名字），**凑齐才算通**——它认的是
//! "`of` 那位交来的、**刻着 `mark` 的那一枚**"，认下来就归位到同名的那条路上。
//! **一问一答那一档也建在它上面**：问的那一侧照样 `seat` + `claim`（要一次往返就单开一座
//! 码头），答的那一侧只管把孔交出来（板协议的两半就是这么接的）。
//!
//! # 两条不变量（照实写，它们是这一层的全部价值）
//!
//! - **不许半条会话**：认领要么整批到手、要么报错（[`Claim::Partial`] / [`Claim::Timeout`]）
//!   ——"建起"是一个整体事件，不是流水。
//! - **失败不留半行**：装上到一半失败，用 [`Quay::shut`] 收干净即可，不必另有一个
//!   "清理"动作（能容忍"没开全"的关张就是清理）。
//!
//! # 九条实测事实（写进代码才发现的，签名看不出来）
//!
//! 1. **对端是"建那个域的那个线程"**，不是被产出来的那一枚线程（对端由 `Quay::open` 定
//!    下，那一刻就说清楚）：子方把孔交给"生我者"，故父方要跟生者打交道。**这一条错了的
//!    症状是会话永远认领不到**——孔明明交出去了。
//!    **跨域那一格的推论**：子方**只认得它的生我者**（第三方的号它手里没有）。故"让子方
//!    把孔交给第三方"这件事办不到，只能由生我者**转授**——板那条路就是这么接上的：
//!    客人的答话孔先落在父域表里，父域再 `Ship` 给板线程。
//! 2. **一次会话是两枚孔**：`seat` 交出去的那一枚是本端**读**的，"认领"进来的那一枚
//!    是本端**写**的。两个方向各一枚，不能混（`Pier::hole` 与 `Pier::at_peer`）。
//!    **一次往返也是两枚孔**：孔是单槽，而一个槽只有一个读者——同一枚上"我推了再读"，
//!    读到的就是我刚推的那一句（对端反而一个字都收不到）。故问事的那一方要**借一枚回信
//!    孔**过去（板那条路上，客人就是这么借的）。
//! 3. **对端那一枚要按 `owner` 认，不是按 `grantor`**（`call::reserve` 读回来的那两格）。
//!    内核那两个戳子回答的是两件不同的事：
//!    - `vestor`（`Collect` 的第三格 / `Reserve` 的第一格）= **谁授的**。`accord` 出来的
//!      副本，它是**授出方**——故"对端授的"这条判据在本端表里**一枚都匹配不上**。
//!    - `owner`（`Reserve` 的第二格）= **谁开的这扇门**。副本共享同一事实，转手不变；
//!      本端 `mint`/`accord` 出来的每一枚都是本端，对端 `ship` 回来的那一枚是对端。
//!    - `mark`（`Reserve` 的第三格）= **这扇门上刻的那个名字**（铸者那张表里这条路的
//!      名字）。同样随副本过线、转手不变——故"**同一位的哪一枚**"由 `owner` + `mark`
//!      两格一起答（这一轮加的就是它，见文件头）。
//!
//!    落点读数（本端 3、对端 4）：本端表里 `tok=21 o=3`、`tok=22 o=3`、`tok=28 o=4`
//!    ——要认的是 28。判据的落点因此是 `owner == **本端**`（**不是** `owner == from`）：
//!    父域那一侧把 `from` 传成自己，两者过去**碰巧**等价；真有一个不同的对端时
//!    （板线程对客人），`owner == from` 会把**正好要认的那一枚**跳过去。
//! 4. **一副本一个槽**（`HoleMeta.slot`，`accord` 只克隆 `Arc`）——这条决定了"名字牌"
//!    那条路走不通：牌写进那个槽，本端读就把对端那张一起吃掉、本端不读就占着单槽把对端
//!    推来的第一条消息堵在槽外。**整条路已经拆掉**（`CARD` / `card` / `post_card` /
//!    `take_card` 都没了）。名字的读法（定长解码面，尾随 NUL 是填充）归具体协议用
//!    （`system::board::call::name_of`）。
//! 5. **"一枚泊位配一枚孔"是一对一**：本端有几条还没配齐的泊位，就按先后认领几枚对端
//!    来的孔。只给"第一条"配线，多通道时会错位。
//!    **反过来也成立**：一枚孔只配一条泊位——**已经用掉的那几枚**（我读的那枚 + 我已认下
//!    的写端）不再认，否则第二次认领会把第一条泊位的写端再配给下一条（一座码头两条泊位
//!    时必现）。
//!    **次序不再承担语义**（这一轮改掉的那一层）：认领的判据里带着记号，而 `seat` 挡同名
//!    ⇒ **同一位、同一记号只可能有一枚**，故"哪一枚孔落在哪一条路"由记号说定，`Vec` 顺序
//!    只是把候选贴上去的手序。
//! 6. **扫表不能设上限**：本端表里可能已经有几十枚孔（设备门闩、别人给的副本……），
//!    设一个"最多看几枚"的缓冲会让排在后面的那一枚永远看不见（`call::each` 不攒数组）。
//! 7. **"交得出去"要持 `VEST`**：内核 `Accord` 的六道闸是**在表内 / 存活 / 持 `VEST` /
//!    覆盖子集 / `ONLY` 一致 / 未被关住**（`Need::Grant` 查的就是 `VEST`）。故 `seat`
//!    交出去的子集是 `R|W|**VEST**`——本协议**必须**让对端能再授出：子方交出来的那一枚
//!    先落在生我者表里，而生我者要把它转给第三方（板线程）才接得上（事实 1 的推论）。
//!    **不给 `VEST` 的症状是转授那一步答 `Denied`，而两侧会话已经配好对了**——看上去像
//!    "对面坏了"，实测栽过。
//!    另：**形态位（`ONLY`）不是这里能选的**——它是资源事实，`Accord` 只校验 subset 与
//!    源枚一致。孔都是共享资源（不带 `ONLY`），故本协议这一路既按不上也洗不掉。
//! 8. **一枚号只在"持有它的那张表"里解析得动**：号本身是**全局序列**（内核
//!    `next_pie_token` 自 1 递增），但 `Reserve` / `Push` / `Pull` 都按调用方**自己的表**
//!    找它——别人的号拿到手里＝用不动。**同一个域里两枚线程各有一张表**，故"同一个域"
//!    不等于"同一个号能用"：把一枚孔交给同域的另一枚线程，**照样要走 `Ship`**
//!    （板线程的提示孔、router 的服务入口，都是这么交的）。**症状：拿别人表里的号去
//!    `pull`，一个字都读不到**（拿主线程铸的服务入口去守门的线程，实测就是这么挂住的）。
//!    **这条不是纪律，是类型**：`PieToken` 标着 `!Send + !Sync`（见 `env::wire::handle`）
//!    ——跨线程共享的账（`static`／`Arc`／`SpinLock<T>`）装不进句柄，产线程的闭包也
//!    捕获不进、其结果也交不回（`unit::closure` 要 `F`／`T` 都 `Send`）。**"把号交给
//!    别的线程"是编译期的事**；要绕过它得显式写出 `.get()`（那是 `ship` 的动作）。
//!    实测栽过的那一枚，本来编译就该拦下来。
//! 9. **"认我没开过的那一枚"这条判据已经拆掉**（一问一答那一档原先是它）：它认不出"这一
//!    枚是谁给的"，只能认"不是我开的"——表里若已经躺着别的外来孔（同域线程交回来的副本、
//!    别人借过来的回信孔），它会按登记先后**认错那一枚**。**症状是两边都"配好对了"，
//!    问出去的话石沉大海**（实测栽过：入口副本比板那一枚先到，板那一问被推进了自己的
//!    服务入口）。今天两档都认 `(owner, mark)` 两格正判据，**记号把"同一位的多枚孔"分开**
//!    ⇒ 不必再要求本端表干净。
//!
//! # 三条走不通的判据（踩过，别回头）
//!
//! 认"对端放进来的那一枚孔"时，这三条**都试过**，症状与原因一并记下：
//!
//! | 判据 | 为什么不行 |
//! |---|---|
//! | `h.grantor == 对端` | `accord` 副本的 `vestor` 是授出方（本端）⇒ 一枚都匹配不上 |
//! | `h.grantor == 本端` | 选中本端 `seat` 时铸的那一枚 ⇒ **写端指回自己的槽**，对端永远收不到 |
//! | 令牌号最大的一枚 | 令牌号是**全局**分配的，与"表尾"无关 ⇒ 选中过本端自己那份 |
//!
//! 还有一条**次序**上的坑：对端那一枚是**后到**的。认不出就别绑——早绑一次就钉在自己的
//! 孔上，症状是"本端 `post` 返回成功、对端 `pull` 超时"。`claim` 本来就是循环
//! （`call::fall` 一等），醒来再扫即可。
//!
//! 顺带记一条**已经拆掉**的设计：曾经往孔里写一张"名字 + 号"的牌想让对端按名字归位。
//! 但交出去的副本与本体**共享同一个槽**（见事实 4），于是本端读就把对端那张也吃掉、
//! 本端不读就占着单槽挡住对端推来的第一条消息——两条路都不通。**名字改由孔上的记号承担**
//! （`UnsealHole` 那一刻刻上去，随副本过线）；帧里带名字那一层归**板**（一问一答的正文）。
//!
//! # 两层
//!
//! ```text
//!   core.rs   码头 / 泊位 / 失败域 / 五个动作 —— 不碰内核（判据可机械检查）
//!   call.rs   铸孔 / 交出 / 认领 / 放下 / 读孔   —— 一处裁决都没有（见该文件头）
//! ```
//!
//! **core.rs 的判据跑在哪**：`protocol-case` 的 `quay` 靶——一台**编外宿主靶**，把本层的 `core.rs`
//! **逐字未改**地编进去，运行时那一层（铸孔 / 交出 / 放下 / 扫表 / 等 / 时钟）给一个**桩**
//! （进程内假表 + 假钟）。上面那九条事实里能机械检查的部分，在那一台里成了判据；门口
//! `crates/gate/tests/host.rs`。（照实记：`core.rs` 原先**一条 `#[cfg(test)]` 都没有**，故这一台是
//! **新开**而不是"救活"——规格写在靶子里，核心那份源码一个字没动。）
//!
//! # 谁用它
//!
//! [`system`](crate::system) 起服务时用它等"它交回了控制孔"（按通道名逐条认领）；
//! [`board`](crate::system::board) 的一问一答也建在它上面（两侧都是 `seat` + `claim`，
//! 靠记号对位，谁也不认"我没开过的那一枚"）；
