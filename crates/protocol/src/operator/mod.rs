//! Operator Protocol — **命名寻址**：一棵树，名字 → Pie。
//!
//! 全系统**就一个** Operator，管着所有条目；其他任务只是**操作**它：
//!
//! ```text
//!   part  分   分出一块空窗格（Pane）
//!   land  落   把一枚 Pie 落到一个名字上（贴一枚 Tile）
//!   find  寻   走到头，把那一枚 Pie 交出去
//!   trim  剪   剪掉一条
//!   list  列   看一块 Pane 里有哪些**号**
//!   name  名   这枚号此刻叫什么
//!   seek  译   把一条路**译成号**——名字只到这一格，往下一律按号
//!   opens 开   第 n 格是谁的门牌（**只读**，不上线：持树者判 `Rule::Opens` 时自己问）
//! ```
//!
//! 对外那七条都是 4 个字母；第八条是 5 个字母、只读、不发消息——照实记：这一族的字是**语义
//! 名词/动词**（`part`/`land`/`find`/`trim`/`list`/`seek`/`name`），故 `peek`/`probe`/`look`
//! 那类实现细节词一个都没用上。
//!
//! 两个类型名与两条原语名**不同名**（`part` 建 `Pane`、`land` 落 `Tile`）——这是照实记：名动同形
//! 那一格本来留给 `tile`，最后定的是 `land`（"落位"那个画面），而 `seat` 因为与会话的
//! `Seat` / `Quay::seat` 撞在同一个文件里而被否掉。
//!
//! # 树
//!
//! ```text
//!   slots: Vec<Option<Slot>>      号 i ↔ slots[i]；None = 墓碑（剪掉 / 剔死留下的坑）
//!   Slot  { 名字, 去处 }          名字 = 一段
//!   Node  = Pane(Vec<EntryId>)    窗格：装的是**孩子的号**，还能往里走（可以再分）
//!         | Tile(PieToken)        砖：到头了，就是内核那一枚
//!   根    = 顶层那个 Vec<EntryId> `Where::Root` 就是它（**根没有号**）
//! ```
//!
//! **号就是下标**（照实记：原来是一棵嵌套树，按深度递归 ⇒ 持树者死在第 117 层）。
//!
//! 一条路是**段列表**（`&[Name]`），不是一个字符串：一段就是现成的 `Name`（定长 32 字节、
//! 构造即校验）——于是"名字不合法"在类型上不存在，也没有分隔符 / 转义 / `..` 这些边界。
//! **路只有一处用处**：[`Operator::seek`] 把它译成号（见下一节）。
//!
//! # 名与号分开
//!
//! 机器用**号**（[`EntryId`]），人用**名**（`Name`）。号在 `part` / `land` 时铸、**换绑不动号**、
//! `trim` 与 `find` 剔死则号失效（水位只上不下 ⇒ 号不重用）；**根没有号**，故 0 是第一个真格子。
//!
//! 名字是**间接**的坐标：一条路（段列表）全系统只有一处用处——[`Operator::seek`] 把路**译成号**。
//! 译完就按号走：`find` / `trim` / `name` 收**号**，`land` / `part` / `list` 收**容器坐标**
//! [`Where`]（根，或某一号）——根没有号，故它显式占 [`Where::Root`] 那一格。名字在答话那一侧
//! 也留着一条（[`Operator::name`] 按号答名），于是"人念得出的那半"与"机器认得的那半"各有
//! 一条路，中间只有 `seek` 这一道闸。
//!
//! # 七条原语（对外）+ 一条只读（不上线）
//!
//! | 原语 | 收什么 | 干什么 | 答什么 |
//! |---|---|---|---|
//! | [`Operator::part`] | 容器坐标 + 新名 | 保证那一格是一块 `Pane`（**幂等**：已经在就是成了） | **那一格自己的号** |
//! | [`Operator::land`] | 容器坐标 + 新名 + 一枚 Pie | 贴一枚 `Tile`：空着就落上，占着就是换绑 | **那一格自己的号** |
//! | [`Operator::find`] | 号 | 把那一号后面那一枚 Pie 交出去 | 一格状态 |
//! | [`Operator::trim`] | 号 | 把那一号剪掉 | 一格状态 |
//! | [`Operator::list`] | 容器坐标 | 读那一块 `Pane` 里的**号** | 一串号 |
//! | [`Operator::seek`] | 一条路 | 把路**译成那一枚号**（名字只到这一格） | 一枚号 |
//! | [`Operator::name`] | 号 | 把一枚号翻成名字 | 一枚名字 |
//!
//! **第八条 [`Operator::opens`]（开）不发消息**：它答"第 `n` 格是谁的门牌"，是持树者自己判
//! [`Rule::Opens`] 时问的一句（**没有动作码**）。与 `find` 正相反——`find` 交出句柄，它只答
//! "是谁"，不动树、不交东西。也**不分配**（同 `name` 那一档）。
//!
//! **要动一块 `Pane`，先把它清空**——`land`（换绑）与 `trim` 是同一条规矩：
//! 非空 `Pane` ⇒ [`Fail::NonEmpty`]。
//!
//! # 失败域只有六格
//!
//! [`Fail`]：`Unknown` / `NonEmpty` / `NotATile` / `NotAPane` / `Full` / `Dead`——每格对应一个
//! **不同的下一步**。后两格的"不是谁"跟着两个类型名走：寻到头是**窗格** ⇒ `NotATile`
//! （它不是一枚 `Tile`）；要往里走 / 要列，可那一段是**砖** ⇒ `NotAPane`。
//!
//! **没有"名字已被占"那一格**：同名接手一枚 `Tile`、或一块**空的** `Pane`，都是换绑；而 owner
//! 归 Principal，Operator 分不出"自己 / 别人"，"已占即拒"在这里无处落脚。
//!
//! # 签名里没有"谁"
//!
//! 那八条原语都没有 caller 参数、条目也没有 owner 字段：**谁能动由 Principal 那一层回答**
//! （内核在 Push 时盖的发送者印章是现成的，Principal 拿去用，Operator 不看它）。
//!
//! # 两枚注入的戳子 + 一次注入的动作
//!
//! [`Stamps`]（那一枚 Pie 还答得出吗 / 这扇门是谁开的）与 [`Unship`]（把我这一份放下——剪掉或
//! 换掉一枚 `Tile` 时用它，不加这一格那一枚句柄就漏在树里）。核心因此不 `use` 内核，喂三个假
//! 闭包就能把规矩推理干净。两枚戳子收在**一格具名的组**里：它们同型，摆成位置参数时写反了
//! 编不过（`session` 那一族认 `owner` 还是 `grantor` 实测栽过一次）。
//!
//! # 与 [`system::board`](crate::system::board) 的关系
//!
//! `board` 是**另一件事**：一块公示板 + 一本待客台账（名字可以立着而没有东西、记得"谁挂的"、
//! 有死亡道、摘牌子不流转）。这一份是**一棵命名树**：结构长在它自己里面、不记 owner、
//! 谁问都答。两处并存，去留不在本正文里定。
//!
//! # 落地程度
//!
//! 三层都在：**核心**（[`core`]：树 + 八条原语；用例在**编外宿主台**
//! `crates/operator-case`，门口 `scripts/host.sh`）、**载体**（[`call`] 的帧与转发、
//! 持树者那本客人小账 `desk`）、**服务**（[`server`](/crate::operator::server) 的
//! `serve` / `attach` / 客侧三手，加 `prog-operator` 这个域；装配那一格在
//! `programs/.../service.rs` 的 `Program::operator`）。
//!
//! **七条都在线上**（第八条 `opens` 不上线）：两条一格状态的（`find` / `trim`）与**五条答数据的**
//! （`land` / `part` 各答一枚号、`seek` 答一枚号、`list` 答一串号、`name` 答一枚名字）。
//! **答话那一侧有四种帧形**（一格状态 / 一串号 / 一枚名字 / 一枚号），各有各的上界
//! （见 [`call::REPLY_MAX`] 那一段）；`list` / `name` / `seek` 三家分家，就是"名与号分开"那一条
//! 落地：**名字只到 `seek` 这一格**。
//!
//! **问话那一侧按动作各一条帧形**（`seek` 带路，`land` / `part` 带容器坐标 + 新名，
//! `list` 带容器坐标，`find` / `trim` / `name` 带号）；最长的仍是 `seek` 那一条
//! （[`call::ASK_MAX`]），其余都落在十到五十字节。

// ── 载体：三侧分别住在哪 ───────────────────────────────────
//
// **使用侧** [`client`]（客侧三手）住这里——那是"别的任务怎么找上树"。**今天三位客人**：
// `echo`（自问自答一趟：分 → 落 → 寻 → 收 → 剪）、`router`（门牌挂在 `/device/router`）、
// `guest`（按那条路找上门去跟 `router` 说话）。**实现侧**（持树者）
// 与**装配侧**（把持树者接上客人 / 认下提示之路）住 `programs/src/supervisor/operator/{server,bridge}.rs`。
// 下面这段是那一台的说明——它讲的是"怎么跑"。
//
//!  同一对动作（`seat` + `claim`），靠**孔上的记号**对位。
//!
//!  ```text
//!    装配者（编排域 system）                    客人（某个服务域）        持树者（operator 域，一枚线程）
//!    quay.seat(LINK) + quay.claim(客人, LINK) ▶ open: seat(LINK) + claim(生我者, LINK)
//!    转授：把客人那一枚 Ship 给持树者 ──────────────────────────────────▶  按"谁转授的 + 记号"认答话写端
//!    LINK 上先递一格：持树者的号 ────────────▶  open 收下 ⇒ 此后叫得出它
//!    提示：往提示之路推一个客人号 ─────────────────────────────────────▶  收一位客人（admit）
//!                                             铸问话孔(ask)、Ship 给持树者 ▶  按"谁开的 + 记号"认出 ⇒ arm + attach
//!                                             推(Ask) ───────────────────▶  组唤醒 ⇒ pull ⇒ 交给树
//!                                             读(Reply) ◀────────────────  推(Reply)
//!  ```
//!
//!  # 为什么持树者就一枚线程
//!
//!  树上那几枚是**一枚只在持它的那张表里有意义的句柄**（`PieToken` = "我这张表里的第几个"）。
//!  "查到了要把 Pie 授出去"必须由**持有那一枚的那张表**来做——故所有条目只能住同一张表，
//!  也就是同一枚线程。板那一台栽过这条（每位客人一枚待客线程 ⇒ 甲的条目在甲的表里，乙来查
//!  时判它"已死"、也授不出去，症状是"刚挂上的名字，别人一查就是 `Unknown`"）。
//!
//!  # 与板那一台的差别（照实记）
//!
//!  1. **持树者住在自己的域里**（板线程住编排域）：故它是被 `service::spawn` 产出来的，
//!     装配者从 `rep` 就知道它是谁，不必再起线程；它那一枚提示孔由**它自己**铸、Ship 给
//!     生我者（= 装配者 = 那一枚 `Quay::claim` 的对端）。
//!  2. **没有"客人说走了"那一档**：本正文里没有客人生命周期（谁问都答）。故没有退场的
//!     那一格——只有"看出来"那一档（那一枚答不出 ⇒ 剔格子）。
//!  3. **没有死亡道**：板那是给编排域监督服务用的（一位服务一条 `gone-<名字>`）。树这一侧
//!     不推任何东西给装配者。
//!  4. **帧里带一整条路**（段列表），不是单个名字；入口那一枚仍然经会话交出去，报文里只有
//!     一格状态。
//!
//!  # 入口那一枚不经装配者转授
//!
//!  客人要跟持树者说话，只需两样：**它是谁**（号）与**一条答话路**。号由装配者递一格告诉它
//!  （[`attach`] 的 `tell`），答话路由装配者转授给持树者。**客人递 Pie 给持树者不必先拿到
//!  什么凭证**——`Accord` 的目的地就是一个 `TaskId`，故"把 Pie 交出去"这一步是客人直接对
//!  持树者做的（板那一台也是这么交入口的）。
//!

