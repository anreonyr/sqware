//! Driver Protocol — **设备轴**：一台设备从"交到某个域手里"到"它的线有人领"这一整段里，
//! **只属于驱动之间**的那几句话说在这里。
//!
//! 它**不是**一份驱动框架：没有 `Device` trait、没有驱动注册表、没有设备类模板。它是**跨域
//! 约定**的集合——谁对谁说什么；设备语义（读哪个寄存器、FIFO 怎么排、行怎么编）各驱动自带
//! （`programs/src/driver/<域>/` 里那一片设备模块）。
//!
//! ```text
//!   driver
//!   ├── SVC    /svc —— 驱动族那条路的头一段（与各族共用；[`crate::system::SVC`]）
//!   ├── DIR    /svc/drv —— 驱动族在命名树上的那一段（唯一一处名字约定）
//!   ├── line   线：权威 / 属主 / 登记 / 投递 / 排空 / 收线      【已落：四格都有调用者】
//!   └── hub    设备账：报名 / 列册 / 认领                      【已落：三面 ＋ 客侧三手】
//! ```
//!
//! # 什么能进这一层（三个否证问题）
//!
//! 一件东西进 `protocol::driver`，当且仅当它**描述两个不同域之间、关于设备这件事的约定**，
//! 且**换一台设备也成立**。三问任一答"是"就出局：
//!
//! 1. **只有持有那台设备的人读得到它吗？** ⇒ 是（设备寄存器、设备树解析、FIFO 排法、
//!    门面的帧）：住各驱动自己的目录。
//! 2. **换一台驱动它就变吗？** ⇒ 变（服务面：串口那枚读行孔、实时钟那面报时）：同上。
//! 3. **它只是"好几台都写一遍"的样板吗？** ⇒ 是：进 `programs/src/driver/`，**不进协议**
//!    （"多个驱动都用" ≠ "该进 protocol"）。
//!
//! # 照实记（`supply` 已不在这里）
//!
//! 本层原先有**两半**：物料（`supply`："一张单子换一段记录"）与线（`line`）。实测把
//! `supply` 的消费者列出来之后，它站不住：**`programs/src/driver/` 一处都不用**它——
//! 递单的是**编排域**（`system::bootstrap` 领设备树与载荷区、`system::control::assemble`
//! 领配给），发货的是**引导域**（`root::supply::server`），驱动在这条路上只是**收方**
//! （收下来的记录由 `system::grant` 解、经 `driver::assemble` 归位——那两件**也一起退了**：
//! 设备那一轴今天由 `hub` 在运行期回答，取法是驱动自己跑一趟）。按上面三个问题，
//! 它答的是"不是驱动协议" ⇒ 整个 `supply` 搬到 [`crate::system::supply`]。
//!
//! 于是本层原先只剩一件事：**线**。一个驱动与另一个驱动（线路由者）之间要共享的全部语言，
//! 就是 [`line`] 里那三样：**请求形 · 答码 · 事件记号**（尺寸与失败域的双射表同住
//! `line::frame`）。
//!
//! **照实记（`hub` 是第二件）**：设备那一轴原先只在**装配期**说得出话（需求单 ＋ 按位次收配给），
//! 运行期没有任何一处是"这一台设备归谁"的权威。`hub` 把那一本账立起来，并把"取法"从装配期挪到
//! 运行期：**驱动自己去 `/dev/<类>/<名>` 拿**（[`hub`] 三面：报名 / 列册 / 认领）。它进这一层
//! 的判据与 [`line`] 同一条：**描述两个不同域之间、关于设备的约定，且换一台设备也成立**。
//!
//! # 相邻但不属于本层
//!
//! 驱动要用、但**不是**驱动协议的东西——照实记在这里，免得下次又顺手塞进来：
//!
//! | 驱动要用的东西 | 家 |
//! |---|---|
//! | 递单 / 收配给（驱动在这里是**收方**） | [`crate::system::supply`] |
//! | 配给记录的字节形状（`Pair` 数组解） | [`crate::system::grant`] |
//! | 被按名找到（挂牌） | `system::board` / `system::operator` 的客侧几手 |
//! | 就绪宣布 | `crate::system` 的 `Announce` |
//! | 开设备（门闩 → 视图） | `runtime::core::dock` |
//! | 服务面（读写设备） | 各驱动自己的具体协议（**永不进 protocol**——旧 `uart` 协议的死因） |
//! | 装配样板（会话 + 收配给 + 上板 + 常驻） | `programs/src/driver/`（**不放**：那是程序骨架） |
//!
//! # 两个角色
//!
//! | 角色 | 手里有什么 | 干什么 |
//! |---|---|---|
//! | **设备驱动** | 那台设备的门闩 | 写寄存器、排空设备、开自己的闸门（`IER`） |
//! | **线路由者** | 中断控制器 | 接线、`claim` / `complete`、把线投给登记过的驱动、收线 |
//!
//! 今天 `prog-router` 一台兼着"控制器驱动"与"线路由者"，`prog-uart` 是第一台纯设备驱动。
//! 两个角色分开写，是因为第二台控制器 / 第二台设备驱动出现时这一层不必重写。
//!
//! # 已知边界（照实写，不是待办）
//!
//! - **线那一半已落**：`occupy` / `deliver` / `exhaust` / `vacate` 四个原语 + 一张按线号索引的
//!   账（**账住路由者自己那一侧**：`programs/src/driver/router/core/lines.rs`），**接到机器上**
//!   了（`router` 一枚线程守"铃 + 门 + 排空"三个事件，`uart` 登记自己那条线）；**`exhaust`
//!   今天有真内容**——读口搬到设备持有者之后，客户是真的读走了设备里的字节才说那句话；
//!   **`vacate` 也有调用者了**——路由者每次醒来探活（`alive` 答不出的那几条拆线 + 空出格子）。
//! - **门牌已落（三台驱动）**：驱动的门牌挂 `system::operator` 的 **`/svc/drv`**（[`SVC`] ＋
//!   [`DIR`]）——名字用服务名、那块 Pane 由第一个上树的驱动建、按名找服务走树、板只管生死。
//! - **驱动的特权级已裁（量出来的）**：两台设备驱动都是 **U 态**。
//! - **重活不做**：DMA、共享内存、热插拔、驱动运行期替换、一条设备多条线、中断共享。

pub mod hub;
pub mod line;

use crate::service::operator::path::Path;

/// 驱动族那条路在树上的**头一段**：`/svc`（[`crate::system::SVC`]——一处给）。
///
/// **照实记（`/device` → `/svc/drv` 那一刀）**：驱动那一族原先自占一块顶层的 Pane
/// （`/svc/drv`），而"服务那一层"（`/svc`，含设备账那一台）与它平级。用户裁定的是：
/// **常驻的东西都挂在 `/svc` 底下**（`/svc/{sys/{…},drv,hub}`），而 `/dev` 留给**设备那一轴**
/// （hub 落的那本账）。故这一段从"顶层一格"变成"`/svc` 底下的一段"。
pub const SVC: &Path = crate::system::SVC;

/// 驱动族在命名树上的那一段名：**`drv`**（整条路是 [`ROAD`]）。
///
/// 驱动把自己的**服务入口**落在 `/svc/drv/<服务名>` 上（`router` ⇒ `/svc/drv/router`），名字用
/// **服务名**——与装配表、日志、板上的名字同一个。
///
/// 那块 Pane 归**第一个上树的驱动**建：树上 `part` 落到一块非空 Pane 上答 `NonEmpty`
/// ⇒ 只有一次创建机会，故"已经在了"必须当成**要的结果**（不是错误）。
pub const DIR: &str = "drv";

/// **驱动那一族那块窗格在树上的路**（`/svc/drv`）——**一处说全**。
///
/// **照实记（这一格从前是一手 `road()`）**：四个客人都要把那两段拼进一条路
/// （`guest` / `sleeper` / `lodger` / `probe-owner`），故它从前是一枚返回 `Option<[Name; 2]>`
/// 的函数（"次序 ＋ 两段名字合法"每处都要判一次）。今天那件事由 [`Path`] 说：一条常量路，
/// 客人写 `driver::ROAD.join(ME)`——判据一格都不必再写。
///
/// **路是"容器链"，不含那一枚自己的名字**（`/svc/drv/uart` 那最后一段归客人自己拼）。
pub const ROAD: &Path = Path::new("svc/drv");

/// **域的服务入口那一枚孔的记号**（`"entry"`）。
///
/// **照实记（它从板那一族搬来）**：这一枚原先住 `protocol::system::board`——板按它把客人交来的
/// "入口"与"问话孔"分开认。板那一族整族退场（死信号与那条握手都撤了，见 `programs/src/system/`
/// 那几笔照实记）之后，它在这里落户：**生产者是各域自己**（`driver::{uart,rtc}` 与
/// `router::adapt::boot` 各有一处 `mail::unseal_hole(ENTRY_MARK)`：那是本域"服务入口"那一枚孔），
/// 而"通用入口"这件事不属于任何一族 ⇒ 住驱动那一层。
pub const ENTRY_MARK: env::Mark = env::Mark::of("entry");
