//! 一台设备从"交到某个域手里"到"它的线有人领"这一整段里，
//! 它**不是**一份驱动框架：没有 `Device` trait、没有驱动注册表、没有设备类模板。它是**跨域
//! 约定**的集合——谁对谁说什么；设备语义（读哪个寄存器、FIFO 怎么排、行怎么编）各驱动自带
//! （`programs/src/driver/<域>/` 里那一片设备模块）。
//! # 什么能进这一层（三个否证问题）
//! 一件东西进 protocol::driver，当且仅当它**描述两个不同域之间、关于设备这件事的约定**，
//! 且**换一台设备也成立**。三问任一答"是"就出局：
//! 1. **只有持有那台设备的人读得到它吗？** ⇒ 是（设备寄存器、设备树解析、FIFO 排法、
//!    门面的帧）：住各驱动自己的目录。
//! 2. **换一台驱动它就变吗？** ⇒ 变（服务面：串口那枚读行孔、实时钟那面报时）：同上。
//! 3. **它只是"好几台都写一遍"的样板吗？** ⇒ 是：进 `programs/src/driver/`，**不进协议**
//!    （"多个驱动都用" ≠ "该进 protocol"）。

pub mod line;

use crate::common::path::Path;

/// 驱动族那条路在树上的**头一段**：`/svc`（crate::common::svc::SVC——一处给）
pub const SVC: &Path = crate::common::svc::SVC;

/// 驱动族在命名树上的那一段名：**`drv`**（整条路是 ROAD）
/// 驱动把自己的**服务入口**落在 `/svc/drv/<服务名>` 上（`router` ⇒ `/svc/drv/router`），名字用
/// **服务名**——与装配表、日志、板上的名字同一个
/// 那块 Pane 归**第一个上树的驱动**建：树上 `part` 落到一块非空 Pane 上答 `NonEmpty`
/// ⇒ 只有一次创建机会，故"已经在了"必须当成**要的结果**（不是错误）
pub const DIR: &str = "drv";

/// **驱动那一族那块窗格在树上的路**（`/svc/drv`）——**一处说全**
pub const ROAD: &Path = Path::new("svc/drv");

/// **域的服务入口那一枚孔的记号**（`"entry"`）
pub const ENTRY_MARK: env::Mark = env::Mark::of("entry");
