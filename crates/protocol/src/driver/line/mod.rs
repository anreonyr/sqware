//! line — **线**：一条中断线从"归了某个域"到"这一条处理完了"这一整段。
//!
//! 它是 [`crate::driver`] 的另一半（那一半是 [`super::supply`]：物料到手）。线上两个角色：
//! **设备驱动**（持有那台设备的寄存器页——只有它能排空）与**线路由者**（持有中断控制器——
//! 只有它 `claim` 得动，那是 per-context 的）。
//!
//! ```text
//!   reserve  保留这一格 + 接线   设备驱动 → 线路由者：「这台设备的线归我」
//!   deliver  推一帧   + 置忙     线路由者 → 设备驱动：「哪一条响了」
//!   exhaust  排空     + 置闲     设备驱动 → 线路由者：「哪一条我处理完了」
//!   release  释放这一格 + 拆线   （主人没了）
//! ```
//!
//! 两对：`reserve` / `release`（保留 / 释放）、`deliver` / `exhaust`（投递 / 排空）。
//!
//! # 账
//!
//! ```text
//!   格 = 空（这条线没主） | 有主 { 泊位, 忙 }
//!   线号 = 下标（容量按 ndev 校验 ⇒ 越界不可表达）
//! ```
//!
//! "忙"只可能是"有主"里的一个字段（"没人要的线正在等排空"写不出来）。**客户手里没有"线"**：
//! 它那条泊位就是坐标，故"线"这个类型只活在路由者那一侧。
//!
//! # 权威与属主
//!
//! **线 = 名字的函数**：线号只有一个来源——设备树里那个节点的 `interrupts` 第一格；客户永远不说
//! 线号，只报它持有那台设备的**名字**。解树只发生一处（线路由者，它手里有设备树）。
//!
//! **属主验不动**：内核交完设备就零设备账，句柄号又不跨表 ⇒ 抢线如实记为代价；真护栏在装配期
//! （谁拿到那台设备的 `ONLY` 门闩）。
//!
//! # 两层
//!
//! ```text
//!   core.rs    账 + 四个原语 + 失败域   —— 不碰内核（不出现 runtime::）
//!   call.rs    帧形与记号
//!   client.rs  客侧几手（装泊位 / 说登记 / 收投递 / 说排空）
//!   （不在协议里）接线 / 静音 / 拆线 / claim / complete —— programs/src/driver/router/plic.rs
//! ```
//!
//! 核心只记账：**"登记了就接线、放回了就接着、释放了就拆"**那三手紧随其后，由适配层做
//! （它要动硬件）。门牌：驱动挂在 [`crate::operator`] 的 **`/device`**（[`super::DIR`]）之下，
//! 名字用服务名。
//!
//! # 未决（照实写）
//!
//! - **排空今天没有真内容**：读口在内核的调试面手里 ⇒ 客户端说不出有内容的 `exhaust`，
//!   路由者仍靠那一拍放回（`IRQ_WAIT_MS`）。**那一拍就是排空的替身**；要真排空，得先把读口
//!   搬到驱动（控制台那一刀）。
//! - **探活时机**：`release` 谁在什么时候做（路由者闲时在等铃，今天没有逐客的时机）。
//! - **静音还是压着不结**：`deliver` 之后到排空之前，那条线怎么处置（今天按静音）。

