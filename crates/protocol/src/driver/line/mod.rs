//! line — **线**：一条中断线从"归了某个域"到"这一条处理完了"这一整段。
//!
//! 它是 [`crate::driver`] 的另一半（那一半是 [`super::supply`]：物料到手）。**这一份今天只有
//! 功能模型**——把操作列全、列准；结构与签名未走门，未决照实记在文末。
//!
//! # 线上是两个角色
//!
//! | 角色 | 手里有什么 | 在这条链上能做什么 |
//! |---|---|---|
//! | **设备驱动** | 那台设备的寄存器页（`ONLY`） | 排空设备——电平源不排空就再报 |
//! | **线路由者** | 中断控制器 | `claim` / `complete`——**只有它领得动**（per-context） |
//!
//! 今天两台：`prog-router` 是线路由者，`prog-uart` 是第一台设备驱动。**线的客户永远是持有
//! 那台设备的人**，不是服务的用户——想读串口的域不碰线，只跟设备驱动说话。
//!
//! # 内核在这条链上只知道一件事
//!
//! 「有外部中断」——一枚 Nole 门铃、一位（`kernel/src/platform/devices.rs`）。线号它不知道，
//! 故 `claim` 只能由域做：内核一领就进了数据面。
//!
//! ```text
//!   设备驱动          设备            控制器                 内核          线路由者
//!   置 IER.RX ─▶ 有字节 ⇒ 拉线 ─▶ 源 enable ⇒ 拉本 hart ─▶ 摇铃 ⇒ 唤醒 ─▶ claim
//!                                                                        │
//!                          领到非 0 ⇒ 静音(priority=0) ⇒ complete ◀──────┘
//!                          20 ms 后把静音的放回去
//! ```
//!
//! 三个断点（都是机械的，不是风格问题）：
//!
//! | 断点 | 事实 |
//! |---|---|
//! | **没有「线 → 谁」的表** | 线路由者遍历树只留下线号；节点的**名字**在手边没收 |
//! | **线路由者手里没有客户的孔** | 它领到线，却不知道往哪儿说"你那条响了"（孔 = 哪张表里的第几个） |
//! | **「我抽干了」没有载体** | 于是退回 20 ms 节拍（`router/main.rs` 自己写着"这个数没有依据"）+ 替所有线静音，包括没人认领的那几条 |
//!
//! # 四个操作
//!
//! 每一个都是某一条断点的补丁——不是并列的功能，是**缺了它那条链就走不通**：
//!
//! | 操作 | 谁 → 谁 | 一笔语义 | 补哪个断点 |
//! |---|---|---|---|
//! | **登记** | 设备驱动 → 线路由者 | 「这台设备的线归我，有事往这枚孔说」 | 前两个 |
//! | **投递** | 线路由者 → 设备驱动 | 「这条线响了」（一次，不攒） | 第二个 |
//! | **抽干** | 设备驱动 → 线路由者 | 「这一条我处理完了」 | 第三个 |
//! | **收线** | （状态，未必是一个动作） | 「这条线没主了」 | 主人没了那一格 |
//!
//! **接线 / 静音不是协议里的操作**：那是线路由者对控制器做的事（设备语义各带各的，
//! `programs/src/driver/router/plic.rs`），只由「登记 / 收线」触发。今天同一个杠杆
//! （`priority = 0`）一身兼两职——**短暂静音**（这一轮领到、还没排空）与**拆线**（主人没了）；
//! 「抽干」一落地，前者的触发源从节拍换成事件，20 ms 那条节拍照理消失。
//!
//! # 两格判定
//!
//! - **权威：线 = 名字的函数**。线号只有一个来源——设备树里那个节点的 `interrupts` 第一格，
//!   而节点名就在设备名里。故客户**永不说线号**；解树只发生**一处**（线路由者，它手里有设备树）。
//! - **属主：名字唯一 + 先到先得**。线路由者**验不动**"你真是那台设备的持有者"——内核交完
//!   设备就零设备账，而句柄号不跨表。故**抢线**如实记为代价：进得到线路由者门里的域，就能
//!   认领一条未被占用的线；真正的护栏在装配期（谁拿到那台设备的 `ONLY` 门闩）。
//!
//! # 门牌（已裁，见 `programs/src/driver/mod.rs`）
//!
//! 驱动的门牌挂 [`crate::operator`] 的 **`/device`**，名字用**服务名**；那块 Pane 由**装配侧**
//! 建一次（`land` 在父段不存在时答 `Unknown`、`part` 到非空 Pane 上答 `NonEmpty` ⇒ 只有一次
//! 创建机会）；按名找服务走树，板管生死（编排域监督的唯一事件源是板那条死亡道）。
//!
//! # 明确不做（照实写，不是待办）
//!
//! - **服务面**（读写设备字节）：各驱动自己的具体协议——旧 `uart` 协议的死因就是这一格。
//! - **一条设备多条线、中断共享、多控制器（多 context）**：今天 virt 上只有一台控制器、
//!   一个 S 态 context。
//! - **热插拔、驱动运行期替换**；`#interrupt-cells > 2` 与 `interrupt-map` 不解析
//!   （`plic.rs` 已记账）。
//! - **属主的强校验**：见上，代价照实记。
//!
//! # 未决（第 2 关进门先裁）
//!
//! 1. **载体**：客户 ↔ 线路由者那条路怎么走——①靠门牌（`/device/router`）拿到入口、按入口的
//!    `owner` 把一枚常驻孔交过去；②经装配侧转授（板 / 树那条路的形状）；③逐次借回信孔
//!    （只够一问一答，装不下异步投递）。
//! 2. **登记帧里说什么**：客户的门牌名（服务名）与**设备名**是两回事——线由设备名解出，
//!    故帧里要带设备名（它本来就在客户那张需求单上）。
//! 3. **投递的形状**：≥1 字节的孔（能带线号 / 设备名）还是 Nole——**空推送不成立**（孔的前置
//!    是 `msg.len() ≥ 1`），而 Nole 的铸权只查 S 态 ⇒ 这一格与驱动的 S/U 绑在一起。
//! 4. **投递与抽干是一条路的两个方向还是两条**（会话一条泊位正好给两枚孔，天然是前者）。
//! 5. **静音还是压着不结**（领了不 `complete`，硬件自己不再送这条线）。
//! 6. **没有客户端时接不接线**：接线是不是登记的直接后果（今天是把树里指到本域的每一条线
//!    全接上，连没人认领的一起吞）。
//! 7. **收线的探活时机**：线路由者闲时在等铃，今天没有逐客的时机。
//! 8. 名待批：`抽干` / `结清`（命名在签名关由用户批）。
//!
//! # 各有各的家（本层只引用，不复述）
//!
