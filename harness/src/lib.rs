#![no_std]
//! harness — **测具**那一档：探针（只读数）与压测台（整台替换引导镜像）。
//!
//! # 这一档与产品那一档的界线
//!
//! **产品**（隔壁那个 crate `programs`）：内核起的那套服务 + 真客人。
//! **测具**（本 crate）：**只为了量**而存在的程序——
//!
//! - **探针**（`probe-*.rs`，6 份）：进**验收镜像**当客人跑。`soak` / `examine` / `fair` 的判据
//!   就是它们打出来的那几行；故它们**必须**在验收镜像的清单里（这是"测具出产品镜像"这件事
//!   唯一做不到的一格）。
//! - **压测台**（`rig` / `load` / `beat` / `again` / `group`，与它们的受害者 `churn` / `hang` /
//!   `park` / `busy` / `waiter`，10 份）：**整台替换引导镜像**，与验收场景没有交集。
//!
//! 本 crate 只借产品那一件共享入口：每个程序一声 `extern crate programs;` ⇒ `programs::entry`
//! 的 `_start`（`global_asm!`）与 panic 处理被拉进链接；链接脚本也是同一张
//! （`programs/link.ld`，镜像都链在 `IMAGE_BASE = 0x10000`）。
//!
//! **特权级与"哪几台进哪张镜像"只在 `kernel/build.rs` 声明**（与产品同一条规矩），而且是
//! **按场景分表**的：验收那张列 15 份产品 + 6 份探针；台子那张只列台主与它要的受害者。
//!
//! # 照实记（为什么搬家）
//!
//! 这两族原先与 15 份产品同住 `programs/`：同一个 crate、同一张 `[[bin]]` 表、同一张**并集**
//! 那张清单（并集）⇒ 跑默认（验收）镜像也把 10 台压测台装进去，而那 10 台在那张镜像里
//! **永远不会被起**（≈1.6 MB / 5.6 MB）。用户的话是
//! **"为什么 programs 里面的测试和程序混在一起？我不希望这样"** ⇒ 测具整体搬到这里，
//! 清单同时拆成按场景的几张表。
//!
//! **照实记（先验的那一格）**：`extern crate programs;` 把 `entry.rs` 的 `_start` 带过 **rlib
//! 边界**这件事，是这一刀成立的前提——先拿一份探针试过（`nm` 里 `T _start` 在、ELF 正常），
//! 才动的其余的。验不过的退路是"同 crate 分目录"。

