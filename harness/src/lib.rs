#![no_std]
//! harness — **测具**那一档：**不进产品镜像的一切**——探针（只读数）· 试客（量服务）·
//! 压测台（整台替换引导镜像）。
//!
//! # 这一档与产品那一档的界线
//!
//! **产品**（隔壁那个 crate `programs`）：内核起的那套服务 + 真客人。
//! **测具**（本 crate）：**只为了量**而存在的程序——
//!
//! 本 crate 只借产品那一件共享入口：每个程序一声 `extern crate programs;` ⇒ `programs::entry`
//! 的 `_start`（`global_asm!`）与 panic 处理被拉进链接；链接脚本也是同一张
//! （`programs/link.ld`，镜像都链在 `IMAGE_BASE = 0x10000`）。
//!
//! **特权级与"哪几台进哪张镜像"只在 `programs::unit::PROGRAMS` 声明**（与产品同一条规矩）：前者是
//! 每行的 `kind`，后者是每行的 `wanted_by`。验收那张列 **6** 份产品 + **6** 份探针 + **6** 位试客
//! （共 18 条）；
//! 台子那张只列台主与它要的受害者。

