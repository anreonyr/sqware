#![no_std]
#![no_main]

//! passer — **过客**：起来、挂一个名字、**直接死**（不说再见）。
//!
//! 它是板上那两本账的"死"判据（**"那一枚入口还答得出吗"**，`VestedBy` = `Reserve` 那一格）的
//! **读数程序**：与 `guest` 的区别只有一处——**它不说 `EVICT`**。故板上那枚牌子与板侧那一格
//! 只能由"看出来的"那一档（`sweep`）收掉。
//!
//! ```text
//!   1  板那条路：seat(板) + claim(生我者, 板) —— 本端那一枚孔交给生我者（装答话路）
//!   2  问话孔：本端铸、给板读（问话从它走，答话走上面那条板路）
//!   3  服务入口：本端铸（记号 entry）、经会话交给板 ⇒ 板上挂着"passer 在哪"
//!   4  REGISTER "passer" —— 报一行读数
//!   5  **直接死**（出口那一手带上那句话）：不退场、不交回、无门闩、通道为空
//! ```
//!
//! # 为什么不退场
//!
//! 退场（`EVICT`）是**客人自己说的**那一档：板当场撤格。那样就验不到"看出来的"那一档了
//! ——本程序的全部价值就在**少说那一句**：它一死，它开的那些门随之封印（退出钩子），板侧那
//! 一格与板上那枚牌子都成了死实例，而 `Reserve` 对已封印的门答 `Err` ⇒ **板问得出来**。
//!
//! # 特权级由清单定
//!
//! 本域是 **U 态**（`programs::program::PROGRAMS` 里这一行的 `kind`，与 `guest` 同档）：铸孔、交出、一问一答
//! 都不需要 S 态。

extern crate alloc;
extern crate programs;

use programs::Report;

// 板：本域是**客侧**（挂一个名字）。

/// 本域挂在板上的名字 —— 本域知道的全部。
const ME: &str = "passer";

/// 等板 / 等答的总上限（毫秒）。**必须有界**：对面死在头几步时本域不能陪着挂死。
const MS: usize = 1000;

/// 两种退场：挂上了 / 没挂上（都**不是 panic**；kernel 会把那一行连同域号打出来）。
const E_OK: usize = 0;
const E_TRIP: usize = 1;

#[programs::entry]
fn main() -> Report<'static> {
    // **照实记（"上板 ＋ 报到"那一步退场：撤板那一刀）**：本域从前先开一条 `board::BERTH` 会话并
    // `enroll`——它的全部意义是"挂上自己、然后**不说退场就死**"，量的是板那一侧看得见看不见。
    // 板那一族的死信号已整片退场（监督那一趟改读**内核那一格**认死）⇒ 那一步连同它的读数
    // （`reg` / `entry`）与 assert 一起退场；本域今天只剩"**直接死**"这一件事。

    // 一、**直接死**：不说退场那一句、不交回、不留门闩。
    return Report::note(E_OK, "passer: gone");
}

/// 哪里算不下去就报哪一句（kernel 收场时把这一句连同域号打出来）。
fn bail<'a>(note: &'a str) -> Report<'a> {
    return Report::note(E_TRIP, note);
}
