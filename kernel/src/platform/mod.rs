//! platform — boot 交给内核的三样东西：**这台机器是什么**、**引导镜像**、**有哪些设备**。
//!
//! 三件来路不同、读者也不同，各自一个文件：
//!   `machine.rs` — 设备树里的机器信息（核数 / 时基 / 内存 / 保留区），注入一次、纯值
//!   `initrd.rs`  — 从引导期清单区里切出 root 镜像（**临时机制**，见该文件头）
//!   `devices.rs` — 设备供给：一次设备树扫描，每台设备一枚门闩，写进配对块
//!
//! 共同点只有一条：**内核在这三样上各出现一次**——`main` 注入机器信息、`boot` 取
//! root 镜像并扫设备——此后零设备概念。
//!
//! 不在这里的两样：**每核的运行时上下文**是 `crate::hart`（tp 指向的那块，不是机器
//! 属性）；**栈与镜像锚点**是 `crate::layout`（VA/物理布局的单一事实源）。

pub mod devices;
pub mod initrd;
pub mod machine;
