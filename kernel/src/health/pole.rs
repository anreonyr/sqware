use alloc::sync::Arc;
use alloc::vec;
use crate::memory::PAGE_SIZE;
use crate::memory::manager::{Frame, addr::VirtAddr, asid, entry::PteFlags, table::TABLE_LIVE};
use crate::runtime::switcher::envcall::pie::{create_pole, fail_pole_at};
use crate::work::mail::pole;
use crate::work::unit::{gate::{self, Permission}, space::{RegionId, SpaceBuilder}, team::TeamBuilder};

pub fn lifecycle() {
    let before = TABLE_LIVE.load(core::sync::atomic::Ordering::Relaxed);
    let space = SpaceBuilder::user().build().unwrap();
    let team = TeamBuilder::new(space).spawn().unwrap();
    let caller = team.task().hold().unwrap();
    let peer = TeamBuilder::new(SpaceBuilder::user().build().unwrap()).spawn().unwrap();
    let recipient = peer.task().hold().unwrap();
    let rw = PteFlags::R | PteFlags::W;
    let reservation = team.space.allocate_low(RegionId::Normal, PAGE_SIZE).unwrap();
    let frame = Frame::allocate().unwrap();
    let weak = Arc::downgrade(&frame);
    let prepared = caller.gate.creations.prepare().unwrap();
    let input = team.space.map_frames(reservation, vec![frame], rw | PteFlags::X, rw | PteFlags::A | PteFlags::D).unwrap();
    prepared.commit(&input.map);
    let start = input.reservation.start();
    let original = input.map.ranges().unwrap()[0].current.bits();
    let kernel = crate::work::unit::team::kernel().unwrap().space.clone();
    let tables = TABLE_LIVE.load(core::sync::atomic::Ordering::Relaxed);
    for stage in 1..=3 {
        fail_pole_at(stage);
        assert_eq!(create_pole(&caller, start, PAGE_SIZE, true), Err(env::PieFail::OoM));
        assert!(caller.gate.pies.lock().is_empty());
        assert!(Arc::ptr_eq(&team.space.tree.find(start).unwrap(), &input.map));
        assert_eq!(input.map.ranges().unwrap()[0].current.bits(), original);
        let _lease = caller.gate.creations.claim(&input.map).unwrap();
        assert_eq!(TABLE_LIVE.load(core::sync::atomic::Ordering::Relaxed), tables);
    }
    asid::fail_next_shootdown(kernel.tree.asid());
    assert_eq!(create_pole(&caller, start, PAGE_SIZE, true), Err(env::PieFail::Busy));
    assert!(caller.gate.pies.lock().is_empty());
    kernel.retry_invalidation().unwrap();
    assert_eq!(TABLE_LIVE.load(core::sync::atomic::Ordering::Relaxed), tables);
    assert_eq!(input.map.ranges().unwrap()[0].current.bits(), original);
    let token = create_pole(&caller, start, PAGE_SIZE, true).unwrap();
    assert_eq!(create_pole(&caller, start, PAGE_SIZE, true), Err(env::PieFail::Denied));
    let snapshot = gate::locate(&caller, token).unwrap();
    let meta = snapshot.pole().unwrap();
    let first = pole::open(&meta, token, &team.space, rw).unwrap();
    assert_eq!(pole::open(&meta, token, &team.space, rw).unwrap(), first);
    assert_eq!(first.0, start.as_usize());
    assert!(meta.opened(&input.map));
    let child = env::PieToken::mint(gate::accord(&caller, token, &Arc::downgrade(&recipient), Permission::FETCH | Permission::STORE, env::Mark::NONE).unwrap());
    let (shared, _) = pole::open(&meta, child, &peer.space, rw).unwrap();
    let peer_map = peer.space.tree.find(VirtAddr::wrap(shared)).unwrap();
    assert!(meta.opened(&peer_map));
    assert_eq!(peer.space.tree.translate(VirtAddr::wrap(shared)).unwrap().0, team.space.tree.translate(start).unwrap().0);
    assert_eq!(create_pole(&recipient, VirtAddr::wrap(shared), PAGE_SIZE, true), Err(env::PieFail::Denied));
    gate::reduce(&caller, token, Permission::FETCH | Permission::VEST).unwrap();
    assert!(!snapshot.permission().contains(Permission::STORE));
    assert!(!team.space.tree.translate(start).unwrap().1.contains(PteFlags::W));
    assert!(!meta.readonly());
    assert!(!meta.exclusive());
    gate::revoke(&caller, &Arc::downgrade(&recipient), child).unwrap();
    assert!(meta.readonly());
    assert!(meta.exclusive());
    assert!(peer.space.tree.translate(VirtAddr::wrap(shared)).is_none());
    pole::shut(&meta, token).unwrap();
    assert!(weak.upgrade().is_some());
    assert!(team.space.tree.translate(start).is_none());
    let (reopened, _) = pole::open(&meta, token, &team.space, PteFlags::R).unwrap();
    assert!(team.space.validate_read(reopened, PAGE_SIZE));
    assert!(!team.space.validate_write(reopened, PAGE_SIZE));
    assert_eq!(create_pole(&caller, VirtAddr::wrap(reopened), PAGE_SIZE, true), Err(env::PieFail::Denied));
    gate::release(&caller, token).unwrap();
    assert!(!snapshot.alive());
    drop(snapshot); drop(meta);
    assert!(weak.upgrade().is_none());
    assert!(peer.release_held(&recipient));
    drop(recipient); drop(peer);
    assert!(team.release_held(&caller));
    drop(caller); drop(team);
    drop(kernel);
    assert_eq!(TABLE_LIVE.load(core::sync::atomic::Ordering::Relaxed), before);
}
