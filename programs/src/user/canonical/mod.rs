//! canonical::实现侧 — **控制台那一台**：把控制台当 UNIX 那一套 stdin / stdout，并在本域里扮
//! **终端那一侧的行规程**（**U 态**）。
//!
//! ```text
//!   main.rs              入口（bin）：只剩流程
//!   core/discipline.rs   **纯功能**：行规程（canonical mode 的最小一份）
//!   adapt/               适配（bin）：找控制台 `/device/uart/{rx,tx}` ＋ 轮转那一圈
//! ```
//!
//! **本域就是一台终端**：ECHO 负责把敲的字显出来、行规程负责行编辑，而**交付的行不再写出去**
//! ——没有下游程序，写一遍只会把每一行在屏幕上显示两次。故本域没有命令行、没有过滤器、没有管道；
//! 本质功能只有一件：**字节流 → 终端认的行**。
//!
//! # 纯功能与适配的分界
//!
//! 行规程的每一条规矩（ICRNL / ECHO / ECHOCTL / ERASE / KILL / EOF、行满截断、收场词）都在
//! `core/discipline.rs` 的 `Discipline::feed` 那一手；`adapt/terminal.rs` 只做"收、喂、写"的轮转
//! （碰孔、碰轮转那一圈），连"攒完清零"都不必记得（账在 `feed` 里清）。故那一圈的壳里**一条行
//! 语义也没有**。
//!
//! **照实记（本域没有 lib 侧的东西）**：这一份 `mod.rs` 只是一枚**空锚**（一行代码也没有）——
//! 本域没有客人、也不被谁 `use`，故 `core/` 与 `adapt/` 全由 bin 自己 `mod`。它留下是因为它是
//! **这条路的锚**（`crate::user::canonical` 那一类链接指着它），与 `driver/uart/mod.rs` 同一条判据。
//!
//! # 这一台在机器上的位置（判据）
//!
//! - **一台设备只有一个读者**：控制台那两枚门牌（`rx` / `tx`）只有本域取用，故它进 `root` /
//!   `product` 两景，且是那两景**最后一条**（`order: 18`）——编排域等它退场才收场，它一退 ⇒
//!   引导域退 ⇒ 级联扑杀 ⇒ 停机。
//! - **板上看得见它的死**（`board: true`）：上板那一挂只为这一件事（挂不上照旧干活）。
//! - **收场两条路**：收场词 `exit`（机器的约定，`scripts/boot.nu` / `qtest.nu` 喂的就是它）与
//!   `^D`（EOF，tty 的约定）——本机没有真正的 EOF。
//!
//! # 三条照实记（这一台栽过的那几栽）
//!
//! **第一栽：`\r` 被丢掉 ⇒ 敲什么都没反应。** 第一版只认 `\n` 当行尾、把 `\r` 抹掉；而交互时敲的
//! 回车正是 `\r` ⇒ 一行都攒不成（屏幕上连回显也没有）。行规程那一格（ICRNL）就是为它立的。
//!
//! **第二栽：写口与读口互相等死。** 控制台服务那一手（uart 排空之后把一批推给读口）是**阻塞**的，
//! 而本域这一手（推给写口）在写口满时也阻塞 ⇒ "本域正写着、uart 正把下一批推给我们"这一格死锁。
//! 实测：喂 12 字节，机器稳定停在第 8 字节（uart 每 8 字节左右排一批）。故 `adapt/terminal.rs`
//! 改成**轮转**——**先把读口收干净（POLL），写口就绪才推；写口满就短等一拍、再回去收读口**。
//!
//! **第三栽：名字与本事对不上。** 它原先叫 `pipe`、肚子里揣着一条 `cat | grep` 的过滤器链；而这一台
//! 真正的本事是**行规程**（终端那一侧），管道只是搭在它身上的一件外挂。用户裁定：**名字改回本质**
//! （`canonical`），**那条过滤器链整条剔除**——于是交付的行只认收场词，别的什么都不做。
//!
//! **照实记（旧回显那台的退场）**：这一档原先住的是调试回显 `echo`（上板、上树两趟、`core/line.rs`
//! 那一整套行语义、回显那一圈，四份文件）。用户裁定"只要最小的功能，不要残留"，那一刀把它们整块
//! 删掉，只留这一台：**位置不变**（两景最后一条、板上看得见它的死），换掉的是"回显"那一件事本身
//! ——今天**回显是终端的事**（ECHO），不再是程序的事。
//!
//! # 明说的差异与不做的
//!
//! - **管道（非 tty）输入也回显**：控制台就是终端，"stdin 是不是 tty"检测不出（真实的 tty 只在
//!   输入是终端时才 ECHO）。
//! - **`^D` 收场时补一个换行**：有意的可读性偏差（免得最后一行与下一个输出黏住），不是 termios
//!   的行为。
//! - **不做**：ISIG（`^C` 不当信号）、IXON、原始模式、`INLCR`、IEXTEN、输出侧 `ONLCR`（输出的
//!   `\n` 由终端那一侧落到行首——本机实测就是如此）、光标移动 / 历史 / 按行宽折行。
