//! ```
//!
//! 本域的本职只有这一件：**把一条字节流按终端约定切成行**。碰内核的那几手（板、树、孔、
//! 那一声 `debug!`）住 `adapt/`（见 `user/echo/mod.rs` 的分界那一节）。
//!
//! **不立 `frame.rs`、也不立会话核**：本域的客人那一侧是"一台终端"，不是另一份协议——没有
//! 报文要解、没有一问一答要记（与 `driver/uart/core/` 只有一条纪律同一条判据）。

