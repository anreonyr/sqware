//! echo::实现侧 — **调试回显**：把**控制台服务**读到的一行原样写回去（**U 态**）。
//!
//! ```text
//!   main.rs     入口（bin）：只剩流程
//!   core/       **纯功能**：字节流 → 终端认的行（`Line`）
//!   adapt/      适配（bin）：找控制台 / 上树两趟 / 回显那一圈
//! ```
//!
//! **照实记（本域没有 lib 侧的东西）**：`rtc` 的 `core/` 住 lib，是因为它的客人 `sleeper` 要读
//! **同一份源码**；本域没有客人、也不被谁 `use` ⇒ `core/` 与 `adapt/` 全由 bin 自己 `mod`。
//! 本模块留下是因为它是**这条路的锚**（`crate::user::echo` 那一类链接指着它），**今天一行代码
//! 也没有**——与 `driver/uart/mod.rs` 同一条判据。
//!
//! **两端都在控制台服务上**（`/device/uart` 那块 Pane，两枚门牌）：**读**走 `rx`（uart 域排空
//! 设备得来的一批），**写**走 `tx`（本域推"一条完整的字"，uart 域写进 `THR`）——那台串口**只有
//! 一个持有者**，字节由它取、也由它写（见 `driver/uart/mod.rs` 的头注）。
//!
//! **照实记（写这一路换过来之前的样子）**：从前写走调试面（`DebugCall::Put`，class 8），理由是
//! "域能说一句话不依赖任何别的域"；读则早就不能走调试面（固件代读 `RBR` 会把字节先取走，见
//! `driver/uart/mod.rs` 的实测）。今天写也收进服务：代价是"说话"要等服务起来、且 uart 一死本域
//! 就说不出话（那正是收场）；换来的是**同一台设备只有一个写者**。调试面今天只留给**起手那几行**
//! （`echo: ready` / `reg=`——那些发生在拿到 uart 之前）与故障读数。
//!
//! **照实记（"上板"与"登记"是两件事）**：这一格原写的是"`REGISTER`：板据此看得见本域的死"。
//! 乙那一刀把它们分开了：**死**由装配者在**提示那一格**递来的名字看见（板在 `admit` 那一刻
//! 就把"谁 → 死亡道"记下），**登记**只管把"名字 → 入口"挂上板。故这一趟对"本域死得有没有
//! 读数"**没有影响**——有影响的是装配表上本域那一格的 `board: true`。
//!
//! # 纯功能与适配的分界
//!
//! 语义规则在 `core/line.rs`——**行尾是哪两个字节、CRLF 算几次断行、收场词是哪一个、非 UTF-8
//! 怎么折**，加起来就是本域的本质功能"**字节流 → 终端认的行**"；`adapt/` 那四份只做"等、取、
//! 喂、写"（碰内核 / 板 / 树 / 孔），`main.rs` 只剩次序。故回显那一圈的壳里**一条规则也没有**
//! ——判定与记账都在 `core/line.rs` 的 `Line::feed` 那一手（连"攒完清零"也是）。
//!
//! # 为什么按**行**回显，而不是读到几个字节就写几个
//!
//! 写的那一侧是行语义（控制台那条**写口**）：**一条消息就是一条完整的字**。按字节回显会得到
//! `h\ne\nl\nl\no\n`——不是这台机器的怪癖，是"一次写必须是一条完整的字"这条红线在地板上的
//! 形态。读的那一侧是**字节流**（服务一次排空交一批），故本域攒够一行再推
//! （攒行那一手在 `core/line.rs`：一个字节一个字节地攒，行尾那一格交出去；**换行由本域补**）。
//!
//! # 为什么先找控制台、后落自己那块牌子
//!
//! 树上那两趟都是"查回来一枚"，而**认哪一枚从前靠次序**：`operator::take` 取本端表里最后
//! 一份由持树者授进来的孔 ⇒ 先查的先认；先落牌子再找控制台，那一份就会把控制台那一枚盖过去
//! （实测栽过：认错了孔，之后一个字节都读不到）。
//!
//! **照实记（这条次序契约不再是契约）**：甲′ 之后那一枚号**随答话回来**（`operator::find`
//! 的第二格），每一趟认得的就是它自己那一枚 ⇒ "最后一份"那件事不存在了。`main.rs` 里那个次序
//! 照旧保留（它本来也是"先有门路、再挂自己的牌子"这条更自然的读法），但它今天**不承担正确性**。
//!
//! # 两条边界（设计红线）
//!
//! 1. **一台设备只有一个读者、也只有一个写者**：读口与写口从前都在内核的调试面手里（固件代读
//!    `RBR`、`Dbcn::ConsoleWrite` 代写），今天都在设备持有者手里——本域只是它的客人。调试面的
//!    读入（`DebugCall::Get`）留着，但**今天没有用家**。
//! 2. **一次写必须是一条完整的字**：写同一个设备的域不止一个时，混着写就会互相插字
//!    （旧树里 root 的设备直连写与服务的写就是这么插花的：`root: conssoll: coole nsole…`）。
//!    今天这条做在**服务口径**里：一条消息 = 一条完整的字，而写的人只有持设备者。
//!
//! # 为什么它也上板（`board: true`）
//!
//! **本域要让人看得出它死了**。本域退场时开的那几枚孔随退出钩子封印 ⇒ 板当场看出"客人没了"
//! ⇒ 往死亡通知那条路推一格 ⇒ 装配者（编排域）据此记账并放下本域那个死域。本域是**最后一条**，
//! 故这一格同时就是"会话结束"的信号。挂不上板照旧回显——只是那条信号缺席。
//!
//! 非 UTF-8 的一行折成 `<non-utf8>` 再写——**照实记（这条折法今天的来路）**：它原先是因为内核
//! 那一格要过 `str`（[`env::fid::DebugCall`] 的 `Put`），而今天写口是**裸字节**，故它今天的身份
//! 只是**终端那一侧的显示约定**（`core/line.rs` 的 `Line::feed` 交出来之前那一折）。
//! 要"原样回显原始字节"，把 `Line` 交出的那一格从 `&str` 改成 `&[u8]` 就够——那一刀没搭这一趟。
//! 调试回显面对的是一台终端，够用——不为它动冻结面。
