#![no_std]
#![no_main]

//! busy — 忙机台（`load`）的**占核者**：纯自旋，永不落核。
//!
//! # 为什么非要有"永不落核"的任务
//!
//! 「到点兑现」这条债的成立条件比原先想的窄：`redeem`/`drain` 是**全局**的，而**任何一颗
//! 空闲核**都会按 `due()` 武装、在到点那一刻醒来兑现**全部**到点 ⇒ 只要机器上还剩一颗核
//! 空闲，旧口径（四处写死 `beat(100ms)`）也不迟到。树内 workload 全都满足"总有核空闲"
//! （`soak`：全员 1 millis 轮询睡眠；`rig`：只有一枚 `hang`）⇒ 这条债在树内**量不出来**。
//!
//! 要把它量出来，就得让它要量的那颗核**一刻不闲**：本程序不 `sleep`、不让出、不做任何
//! env 调用，由 `load` 按枚数铺几枚（**单核隔离档**一枚就够；多核档是**对照**、故意留
//! 空闲核——见 `load.rs` 头注与 `HOGS` 那一格）。特权级由清单定（U 态）：占核与特权级无关，
//! 给最小特权那一档。

extern crate programs;

use programs::stress::tick;

/// 一次自旋的块大小：够大以摊掉循环开销，够小以不至于让"被抢占点"太粗。
const CHUNK: usize = 65_536;

#[unsafe(no_mangle)]
extern "C" fn main() -> ! {
    loop {
        tick::spin(CHUNK);
    }
}
