//! driver — **驱动这一族**：设备面的持有者，与它们共用的装配件。
//!
//! 判据是**角色**，不是特权级（与 `harness`（测具那一个 crate） 同款）：本目录下的成员各自在
//! `plan::assembly::ALL` 里这一行的 `kind` 声明自己是哪一档——今天三台都是 **`User`**：这一格是量出来
//! 的，不是判据看特权级（读寄存器、`claim`/`complete`、持门闩都不需要 S 态；见 [`uart`] 头注）。
//!
//! ```text
//!   router   线路由者（中断面域）：持有中断控制器，接 / claim / complete 每一条线
//!   uart     串口驱动：持有 serial@10000000，把"收到字节就拉线"打开；门牌上挂读行那枚孔
//!   rtc      实时钟驱动：持有 rtc@101000，兼**报时服务**（门牌 `/device/rtc`）——第二台真设备
//! ```
//!
//! **线的权威 / 属主 / 登记 / 投递 / 排空 / 收线**那一层在 `crates/protocol/src/driver::line`
//! （四格原语 + 一张按线号索引的账 + 客侧几手），**已接到机器上**：`router` 一枚线程守
//! "铃 + 门 + 排空"三个事件、每醒一次先逐客，`uart` 是第一位客户（占线 / 收投递 / 排空），
//! 房客 `lodger` 专门喂那两格读数（占线就死、失败那趟也走一遍）。
//!
//! # 门牌（三块都落）
//!
//! 驱动的门牌挂 `protocol::system::operator` 的 **`/device`**（`protocol::driver::DIR`）：名字用
//! **服务名**（`router` / `uart` / `rtc`，与装配单、日志同一个名），**按名找服务走树**；板留着
//! 管生死（编排域监督的唯一事件源是板那条死亡道）。
//!
//! **那块 Pane 由第一个上树的驱动建**：树上 `part` 落到一块非空 Pane 上答 `NonEmpty`
//! ⇒ 只有一次创建机会，故"已经在了"必须当成**要的结果**（不是错误）。`router` 今天读到的是
//! `part=0`（它建的）；后两台上来读到 2。
//!
//! **代价照实记**：树上撞名是**换绑**（旧的一枚放下，`operator` 不做 owner 判断）⇒ 拿得到树路
//! 的域能顶掉别人的门牌；板那边撞名是 `Taken`——门槛从"撞名即拒"降成"撞名即顶"。
//!
//! **三块都挂上了**：`router` 是 `/device/router`，`uart` 是 `/device/uart`、`rtc` 是 `/device/rtc`
//! （`part` 是**幂等**的：那台先上来就建、后上来的拿到同一枚号 ⇒ 三台都读成 `part=0`）——
//! 后两块各挂**一扇服务门**。
//!
//! # 服务面（两台都有客人了）
//!
//! 服务面 = **各驱动自己的具体协议**，故住各驱动自己的目录、**不进 `crates/protocol`**
//! （旧 `uart` 协议的死因就是把它放进了协议层）；客人与驱动 `use` 的是同一份源码
//! （`driver/rtc/{call,core,client}.rs` 那一份，客人是 `harness/src/sleeper.rs`）。
//!
//! 两个实例的形状**不一样**——这正是"抽象等第二个实例"要证的那件事：
//!
//! ```text
//!   uart  单向：排空读到什么就交什么（一条字节流；"一行"是终端那侧的约定，客人 `echo`）
//!   rtc   双向：客人问（问时间 / 定闹钟，一问一答、每趟自带一枚回信孔）
//!              + 设备叫（到点把"那一声"推回客人手里，客人 `sleeper`）
//! ```
//!
//! # 两条家族纪律
//!
//! - **设备语义各带各的**：谁的设备谁在自己目录里放设备模块（[`router`] 的 `plic.rs`、
//!   [`uart`] 的 `uart.rs`、[`rtc`] 的 `rtc.rs`）——本仓不用一份"驱动框架"去包它们。
//! - **需求单归收方**：三台各在 [`plan::assembly`] 里开自己那张单（`ROUTER_WANTS` /
//!   `UART_WANTS` / `RTC_WANTS`），装配者与收方**读同一张**（见 [`crate::service::Program`]）。
//!   单子必须住那一层——装配单本就要把那一格摆出来。**照实记**：各域原先是 `needs.rs` 一行
//!   转发到那里，那一刀删掉转发、直接取（见 `driver/uart/mod.rs`）。
//!
//! 本级的 [`assemble`] 是各驱动**都要写一遍**的那一段客侧装配（会话 + 收配给 + 归位）。

pub mod assemble;
pub mod router;
pub mod rtc;
pub mod uart;
