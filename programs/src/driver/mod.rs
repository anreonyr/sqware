//! driver — **驱动这一族**：设备面的持有者，与它们共用的装配件。
//!
//! 判据是**角色**，不是特权级（与 `harness`（测具那一个 crate） 同款）：本目录下的成员各自在
//! `programs::program::PROGRAMS` 里这一行的 `kind` 声明自己是哪一档——今天三台都是 **`User`**：这一格是量出来
//! 的，不是判据看特权级（读寄存器、`claim`/`complete`、持门闩都不需要 S 态；见 [`uart`] 头注）。
//!
//! ```text
//!   router   线路由者（中断面域）：持有中断控制器，接 / claim / complete 每一条线
//!   uart     串口驱动：持有 serial@10000000，把"收到字节就拉线"打开；门牌下挂两枚孔（读口 / 写口）
//!   rtc      实时钟驱动：持有 rtc@101000，兼**报时服务**（门牌 `/svc/drv/rtc`）——第二台真设备
//! ```
//!
//! **线的语言**那一层在 `crates/protocol/src/driver::line`（`frame` 形与码 ＋ 客侧四手）；
//! **账与四原语（占住 / 投递 / 排空 / 收线）在持有者那一侧**——`router/core/lines.rs`。
//! 两层都**已接到机器上**：`router` 一枚线程守
//! "铃 + 门 + 排空"三个事件、每醒一次先逐客，`uart` 是第一位客户（占线 / 收投递 / 排空），
//! 房客 `lodger` 专门喂那两格读数（占线就死、失败那趟也走一遍）。
//!
//! # 门牌（三块都落）
//!
//! 驱动的门牌挂 `protocol::system::operator` 的 **`/svc/drv`**（[`protocol::driver::ROAD`]）：名字用
//! **服务名**（`router` / `uart` / `rtc`，与装配表、日志同一个名），**按名找服务走树**；板留着
//! 管生死（编排域监督的唯一事件源是板那条死亡道）。
//!
//! **那块 Pane 由第一个上树的驱动建**：树上 `part` 落到一块非空 Pane 上答 `NonEmpty`
//! ⇒ 只有一次创建机会，故"已经在了"必须当成**要的结果**（不是错误）。`router` 今天读到的是
//! `part=0`（它建的）；后两台上来读到 2。
//!
//! **照实记（`uart` 那一格是 Pane，不是砖）**：控制台是**双向**的（读口 / 写口），故那一台
//! 在 `/svc/drv/uart` 下再分一块 Pane、落两枚砖 `rx` / `tx`（用户裁定 `/svc/drv/uart/{rx,tx}`，
//! 那一趟在 `driver/uart/desk.rs`）；`router` / `rtc` 仍是一枚砖（`/svc/drv/router`、
//! `/svc/drv/rtc`）。"归属"声明在砖上，故 `probe-owner` 顶的是 `/svc/drv/uart/rx` 那一枚。
//!
//! **代价照实记**：树上撞名是**换绑**（旧的一枚放下，`operator` 不做 owner 判断）⇒ 拿得到树路
//! 的域能顶掉别人的门牌；板那边撞名是 `Taken`——门槛从"撞名即拒"降成"撞名即顶"。
//!
//! **三块都挂上了**：`router` 是 `/svc/drv/router`，`uart` 是 `/svc/drv/uart/{rx,tx}`、`rtc` 是
//! `/svc/drv/rtc`（`part` 是**幂等**的：那台先上来就建、后上来的拿到同一枚号 ⇒ 三台都读成
//! `part=0`）——后两块各挂服务门（`uart` 两面：读口 `rx` / 写口 `tx`）。
//!
//! # 族一级共用的三件（＋一枚死法）
//!
//! 起手那几步里**每台都要走一遍、而几台逐字同构**的，住本级这几个模块：
//!
//! - [`device`]：**设备账那一趟的客侧**（认领一台：报名 → 列册 → 找门 → 认领 → 开图）；
//! - [`context`]：**上板 ＋ 上树 ＋ 一条会话**（开会话 → 要问话孔 → 名字译成号 → 按号取入口）；
//! - [`fail`]：**一枚扁平死法**（一个号 ＋ 那一句话），号取自装配表。
//!
//! 号那一格的理由与内件三枚并成 `system::Start` 那一刀同一条（见
//! `programs/src/system/{operator,principal,coalition}/program.rs` 那几格）：装配表说"这一台死了"
//! 是一个号，而各域自己那几格从前又写了 `4..=8`——**同一件事两套号**。治法是把号收进那张表，
//! "死在第几步"留在那一句话里。
//!
//! 判据与 [`device`] 同一条：**同构才收**——收的是"几台都要写一遍的那一段"，不是"驱动框架"：
//! 设备语义、门面那一句话、常驻那一只组仍各带各的（见下面两条家族纪律）。
//!
//! **照实记（两刀都落在这条判据上）**：先是 `tree` / `register` 两份（加 `harness/lodger.rs` 的
//! `find_router`）抄的同一趟路 ⇒ 并进 [`context`]；后来三台各留的那份 `adapt/fail.rs` 薄壳
//! （`DIED` / `ASSEMBLE` / `type Fail`，正文三行）也删掉 ⇒ 号回**它自己的名字**、那句话回
//! **调用点**，`uart/adapt/` 随之整个消失。`Fail::assemble` 与 [`fail::Fail::at`] 原本函数体
//! 逐字相同，故一并收掉。
//!
//! # 三台按同一条线切开（但**不同形**）
//!
//! 三台驱动（`router` / `uart` / `rtc`）都按同一条线切开——**纯功能与适配分开**：
//!
//! ```text
//!   core/     纯：数据 + 决定（不碰内核、不碰设备）
//!   adapt/    适配：等、取、喂、执行——碰内核 / 板 / 树 / 设备 / Exit（**没有就不设**）
//!   设备面     各域根上那一份（`plic.rs` / `uart.rs` / `rtc.rs`）：谁的设备谁自己带
//!   main.rs   入口：三段流程
//! ```
//!
//! **两半的边界不总落在 lib/bin 上**：`rtc` 的客人（`sleeper`）要读同一份源码 ⇒ 它的
//! `core/` ＋ `client.rs` 住 lib；`uart` / `router` 的客人不读它们的源码 ⇒ 整块由 bin 自己
//! `mod`（见各域 `mod.rs` 那条照实记）。判据不是"住哪一侧"，而是**那些数据与决定碰不碰内核**。
//!
//! **"等事件"留在适配层**：组（`Pile`）与铃（`Bell`）是内核的，而纯核不出现 `runtime::`
//! ⇒ 常驻那一圈的**壳**在 `adapt/`，而它的每一格判定在 `core/`——壳里因此没有语义 `if`。
//!
//! ## 裁（用户）：三台不同形是**结果**，不是欠收
//!
//! **核心那一圈住哪**，按"那一圈有没有自己的状态与等法"定，不按"三台要长得一样"定：
//!
//! ```text
//!   uart    一个源（那条线）⇒ 那一圈住 main.rs 的"核心"段，`adapt/` 因此整个不设
//!   rtc     两个源（门 ＋ 线：一只组、两枚孔、一页缓冲）⇒ 住 adapt/resident.rs
//!   router  三个源（铃 ＋ 门 ＋ 排空：账 / 门铃 / 入口 / 缓冲）⇒ 住 adapt/resident.rs ＋ Up
//! ```
//!
//! "同构才收"收的是**逐字同构的那几段**（[`device`] / [`context`] / [`fail`]），
//! 不是"三台长得一样"——没有哪一条判据要求各域的形状相同。**成功那几行读数**（`uart: …` /
//! `rtc: …` / `router: …`）同理：它们本就各说各的。
//!
//! **`router` 的 `Up`（7 格）照留**：那七格是**同一条命**（控制器寄存器面 / 树那侧的事实 / 账 /
//! 门铃 / 那只组 / 门外那页缓冲 / 本域入口），常驻那一圈每醒一次全都用得上。杀掉它就是把
//! 七个裸参数穿过常驻与四手——"高参数助手"正是前面几刀删掉的那类形状（`tree::plate` 7 参）。
//!
//! # 服务面（两台都有客人了）
//!
//! 服务面 = **各驱动自己的具体协议**，故住各驱动自己的目录、**不进 `crates/protocol`**
//! （旧 `uart` 协议的死因就是把它放进了协议层）；客人与驱动 `use` 的是同一份源码
//! （`driver/rtc/{core,client}.rs` 那一份，客人是 `harness/src/sleeper.rs`）。
//!
//! 两个实例的形状**不一样**——这正是"抽象等第二个实例"要证的那件事：
//!
//! ```text
//!   uart  单向：排空读到什么就交什么（一条字节流；"一行"是终端那侧的约定，客人 `canonical`）
//!   rtc   双向：客人问（问时间 / 定闹钟，一问一答、每趟自带一枚回信孔）
//!              + 设备叫（到点把"那一声"推回客人手里，客人 `sleeper`）
//! ```
//!
//! # 两条家族纪律
//!
//! - **设备语义各带各的**：谁的设备谁在自己目录里放设备模块（[`router`] 的 `plic.rs`、
//!   [`uart`] 的 `uart.rs`、[`rtc`] 的 `rtc.rs`）——本仓不用一份"驱动框架"去包它们。
//! - **需求单归收方**（照实记：这一条改过口径）：三台各在自己那一域里写一条
//!   [`Ask`](device::Ask)（`UART_ASK` / `RTC_ASK` / `PLIC_ASK`…），**装配者不再读它**——
//!   设备由本域自己走一趟设备账认领（见 [`device`]），故那张单子不再是"装配表的一格"。
//!   从前它住 [`programs::program`] 是为了让装配者按同一张单发货；那条路退了，单子回本域。
//!
//! # 这一级给驱动作者什么（四个名词）
//!
//! ```text
//!   Device          一台设备：向设备账认领 → 开图 → 交出坐标与视图
//!   Context         本域在系统里的位置：一块牌子 + 上板 + 一条会话（上树 / 占线 / 交件）
//!   Context::join   起手那一趟（接上板与树那两条路 / 铸牌子 / 拿占线那一柄）
//!   Fail            一台驱动的死法：一个号 + 那一句话（**步名**）
//!   Line            本域那条线（客手来自 protocol::driver::line::client）
//! ```
//!
//! **入库判据**：一个 API 进 `driver::` **当且仅当两台以上逐字同构**（今天最宽的一件是
//! [`context::Context`]：`uart` / `rtc` 走，`router` 起手不同形）。设备长什么样、服务协议
//! 长什么样，永远在域里。**照实记（`tree` / `register` 两份已并进 `context`）**：那两份
//! 加 `harness/lodger.rs` 的 `find_router` 抄的是同一趟路（开会话 → 要问话孔 → 名字译成号 →
//! 按号取入口），参数表 7 / 4 / 0 参而只要同一条会话 ⇒ 并成一条 `Session`。
//!
//! **照实记（那条 `Session` 一路搬到了 protocol）**："开会话"那一半的用户里一半不是驱动
//! （房客 `lodger`、客人 `canonical`、内件 `coalition`）⇒ 它先抬出本目录，再按用户裁定回到
//! **它自己那一层**：[`protocol::communication::session`]（**地板**：只认孔与路）。树上那几手
//! （名字 → 号 → 入口）回 `operator` 的客手（[`protocol::system::operator::client`]）。
//!
//! **照实记（"落门牌"那一手反倒回来了，task-2 那一刀）**：同一趟里的**上树组合**
//! （`plate`：分目录 → 落门牌 → 查回来 → 按号问名）已从协议层**下移到这里**
//! （[`context::Context::plate`]）——它是**驱动族那一段路的装配 recipe**（`dir` 恒为
//! [`protocol::driver::ROAD`]），而唯一的实现消费者是 [`context::Context::join`]（`router`
//! 的起手经 `Context` 走同一手）。故本目录不再只留"设备面那一半"：设备面 ＋ 这一段装配
//! recipe 同住 `context`，协议层只剩它调的四手。

