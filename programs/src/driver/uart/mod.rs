//! uart::实现侧 — **串口驱动域**：`serial@10000000` 的持有者，兼**控制台服务**。
//!
//! ```text
//!   main.rs     入口（bin）：只剩流程
//!   core/       **纯功能**：交出去的那一批（非空不可表达）
//!   uart.rs     设备面（bin 自己 `mod`——同一份源码不编两遍）
//! ```
//!
//! **照实记（`adapt/` 整个消失）**：起手 / 上树那几趟并进 [`programs::driver::{Device, Context}`]、
//! 常驻那一圈并回 `main.rs` 的"核心"段、那一份死法薄壳也删了（本域直接用装配表里的号）
//! ⇒ 本域今天只有 `main.rs` ＋ `core/` ＋ `uart.rs`。
//!
//! **照实记（本域没有 lib 侧的服务面）**：`rtc` 那一侧 `core/` 与 `client.rs` 住 lib，是因为
//! 客人 `sleeper` 要读**同一份源码**；本域的客人（`canonical`）只经树拿到那枚孔，**不读本域任何
//! 一份源码** ⇒ 连 `core/` 也由 bin 自己 `mod`。本模块留下是因为它是**这条路的锚**
//! （`[`crate::driver::uart`]` 那类链接指着它）。
//!
//! # 读口归设备持有者
//!
//! 从前读口在**内核的调试面**（客人从前走 `DebugCall` → SBI DBCN → 固件的 `uart8250_getc` 读
//! `RBR`）：那一段由固件代读，设备里的字节**先被它取走**——实测：20 字节喂进去，本域每次被
//! 投递叫醒去看，FIFO 已经空了（本域排空读到 0，调试面读到 20）。今天读口搬到本域：`IER.RX`
//! 由本域开、`RBR` 也由本域读——**一台设备只有一个读者**，这是"持设备者才有资格动它"的直接后果。
//!
//! # 服务面：交出去的是什么
//!
//! `/device/uart` 是一块 **Pane**，两枚门牌（用户裁定 `/device/uart/{rx,tx}`）：
//!
//! - **`rx`（读口）**：**一次排空读到的字节，原样交出去**。客人（`canonical`）经树上拿到的副本就是
//!   "从本域读"的那一份。**一条消息 = 一次排空，而边界无意义**——它是一条字节流；"一行"是
//!   **终端**的约定（按行显示在客人那侧，见 `programs/src/user/canonical/main.rs`），不是设备的事。
//!   不另立帧形：孔是单槽、一次推就是一个消息单元，再写一层长度前缀只是把同一件事说两遍。
//! - **`tx`（写口）**：**一条消息 = 一条完整的字**。客人把"要写出去的全部字节"推上来（换行由
//!   客人补），本域取走、原样塞进 `THR`（`uart.rs::put`）。**写也只有本域**——与"一台设备只有
//!   一个读者"同一条判据的写侧。写口立起来之前，域要说话只能借内核的调试面
//!   （`DebugCall::Put`）；那条路今天留给**起手与故障**读数。
//!
//! **照实记**：排空读到 0 字节时**不推**（内核 `Push` 那一格不收 0 字节的报文）——这不是丢字节，
//! 一批 0 字节本来就没有内容可交。这条纪律今天做进了类型：`core/batch.rs` 的 `Batch`
//! （"交 0 字节"写不出来）。
//!
//! **照实记之二（`rx` 那枚孔的权限）**：树授出去的副本是 `R|W|VEST`（`port::ship` 那一手的统一
//! 口径），故客人**也推得动** `rx`；"客人在读、不在写"是约定、不是判据——与线路由者那边"抢线
//! 没有属主验证"同一类代价。写的那一路不靠这条约定：`tx` 是**专门的一枚**（`pull` 它的是本域、
//! 推它的才是客人）。
//!
//! **照实记之三（TX 上从此有两个写者）**：内核与各域的 `debug!` 仍经 SBI 的 DBCN 往**同一台**
//! `uart8250` 写（引导期与故障读数要靠它），而本域今天也开始写 `THR` ⇒ "两颗核同时写同一台
//! UART"从"无证据"变成**结构性存在**。粒度是"一次写 = 一条字"：本域一条写一次、内核一条读数行
//! 一次 ecall——**字级**插花今天无证据，**行级**仍可能（与 `kernel/src/console.rs` 那条照实记
//! 同一档）。
//!
//! # 为什么它不退场
//!
//! **资源寿命 = 能力寿命**：那枚门闩在本域表里 ⇒ 本域一退，设备就没人持有了（而 `IER`
//! 那一位是**硬件状态**，会留在原地）；门牌那枚孔也是本域铸的 ⇒ 本域一退，读行的人当场
//! 看出来（那枚孔径死）。故它的收场只有两条路：被编排域收掉（`doom`）或随级联走。
//!
//! # 特权级：量出来的 U 态
//!
//! 今天是 **U 态**。旧树这一格写 S 态、理由是"要读写寄存器"——那不是理由：banner 里串口与
//! PLIC 的 PMP 都是 **S/U (R,W)**，U 态读得动。这一格现在**有读数**了：清单里两台驱动都写成
//! `User` 之后，两道门（examine 3/3、soak 10/10）照旧全过——写 `IER`、读 `RBR`、`claim`/`complete`、
//! 持门闩、铸孔、挂组都不需要 S 态。**唯一收在 S 态的一格是铸铃**，而路由者那枚铃是**内核给的**
//! （它只 `hush`，不铸）。
