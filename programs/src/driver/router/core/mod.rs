//!   sources.rs   这台控制器自己的事实（线数 / context）＋ 它那几条线（区 ↔ 线号）＋ 五笔没进来的账
//! ```
//!
//! 它只吃**设备树那段字节**（适配层把借映进来的视图切好交给它），故可独立推理；
//! 寄存器那一半住 `../plic.rs`（设备面）。**账与四原语**（登记 / 投递 / 排空 / 收线）不在这里
//! ——那一条线的权威住 `contract::driver::line::core`（两侧共用一份）。

