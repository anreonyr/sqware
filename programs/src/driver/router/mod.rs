//! router::实现侧 — **线路由者（中断面域）**：外部中断的收与结（**U 态**，**一枚线程**）。
//! ```text
//!   main.rs        入口（bin）：只剩流程
//!   core/sources.rs **纯功能**：树那侧的事实（线数 / context）＋ 区 ↔ 线号 ＋ 五笔没进来的账
//!   plic.rs        设备面：寄存器（接线 / 静音 / 拆线 / claim / complete）
//!   adapt/         住持面（bin）：起手 / 门面 / 逐客 / 排空 / 铃 / 常驻壳
//! ```
//! **账与四原语在这里**：登记 / 投递 / 排空 / 收线那条权威住
//! 本域 [`core::lines`]——**路由者的内部管理表**；协议那一侧只留**形与码**与**客侧几手**。
//! **它为什么叫 router**：它管的是**线**（哪条线、谁领走、领完怎么结），不是某一台设备。
//! 要认的那三样在 `adapt/boot.rs` 的三条 `Ask` 里。
//! **起域时一条线都不接**：接线是登记的直接后果——没登记的线根本不进本 context，本域不再
//! 替所有人刹车（今天树里那 10 条里 9 条没主，全接上就是替它们吞中断）。
