//! router — **线路由者（中断面域）**：外部中断的收与结（**U 态**，**一枚线程**）。
//!
//! ```text
//! 收配给（父域按同一张需求单推来记录，**按位次归位**：控制器 / 自描述 / 门铃）
//!   → 读树：本域该用哪个 context、树里指到本控制器的线有哪几条（**名字只为日志**；顺带报"没进来的账"）
//!   → 板上一趟（装上板路、交上问话孔——**只为让板看得见本域的死**，不挂牌子）
//!   → 树上一趟（分出 `/device`、把本域的服务入口落成 `/device/router`、再查回来验一遍）
//!   → 等三个源（一只组）：**铃**（外部中断）、**门上有人**（登记）、**客人的排空**
//!       门上   登记：解树（区 → 线号）→ 占住那一格 → **接上线** → 把排空那条路挂进组
//!       铃     领到一条：**往主人手里投一帧** → 投到了才静音 + complete → 应铃
//!       排空   客人说"我排空了"：那一格回闲 → **把线放回去**
//!   → 每醒一次先**逐客**（`sweep`）：主人没了的那些线——拆线 + 空出格子（探活）
//! ```
//!
//! **本文件只剩流程**：起手在 `adapt/boot.rs`；醒来的四手各一份
//! （`adapt/{sweep,exhaust,desk,bell}.rs`），那一圈的**壳**在 `adapt/resident.rs`；
//! 树那侧的事实与线集合在 `core/sources.rs`（纯），寄存器面在 `plic.rs`（设备）。
//! 判据、裁法与那一张读数表在 `driver/router/mod.rs`。

extern crate alloc;
// 本包 lib 提供 `_start` + panic_handler；必须真的链接它，`use` 只带符号不算。
extern crate programs;

/// 住持面（适配）：起手 / 门面 / 逐客 / 排空 / 铃 / 常驻 / 死法——由 bin 自己 `mod`。
mod adapt;

/// 纯功能：树那侧的事实与线集合（区 ↔ 线号）。
mod core;

/// 设备面（本域私有，同 `lib.rs` 的纪律：谁的设备谁自己带）。
mod plic;

/// 本域那一台：**返回类型就是它的死法**——编号与那句话都在 [`adapt::fail::Fail`] 里
/// （装配那几步 `1`–`3` 由 [`programs::driver::assemble`] 那一族共用，本域自己那几格从 4 起）。
#[programs::entry]
fn main() -> Result<(), adapt::fail::Fail> {
    // 起手：领配给 → 开两图 → 读树 → 建账 → 铸入口 → 上板 ＋ 上树 → 挂组。
    let mut up = adapt::boot::up()?;
    // 常驻：等三源 → 逐客 / 排空 / 登记 / 铃。
    adapt::resident::run(&mut up)
}
