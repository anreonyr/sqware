//! rtc::实现侧 — **实时钟驱动域**：`rtc@101000` 的持有者，兼**报时服务**（门牌 `/svc/drv/rtc`）。
//! ```text
//!   main.rs     入口（bin）：只剩五步流程
//!   core/       **纯功能**：会话核（事件 → 决定）＋ 那一格 ＋ 形与记号 ＋ 失败域
//!   client.rs   客侧两手（碰内核；与客人 `harness/src/sleeper.rs` 同一份源码）
//!   dev/rtc.rs  设备模块（bin 自己 `mod`——同一份源码不编两遍）
//!   adapt/      住持面（bin）：门面 / 常驻——**只剩这一台自己的形状**
//! ```
//! **两半的分界**：客人够得着的那一半（[`core`] ＋ [`client`]）住本模块（lib）；只属于这一台
//! 的那一半（`adapt/` ＋ `dev/rtc.rs`）由 bin 自己 `mod`——`PieToken` 只在铸它的那张表里念得出来，
//! 而客人不在这张表里。
//! # 纯与适配的分界
//! ```text
//!   core/    数据 + 决定：那一格、会话核（一问怎么答 / 到点做什么）、形与记号、失败域
//!   adapt/   等、取、喂、执行：组与泊位（内核）、读表与清那一格（设备）
//! ```
//! **"等事件"移不进纯核**：组（`Pile`）是内核的，而纯核的纪律是不出现 `runtime::` ⇒ 常驻
//! 那一圈的**壳**留在 `adapt/resident.rs`；但它的**每一格判定**都在 [`core::Host`]——壳里因此
//! 没有语义 `if`（核吐什么，它就执行什么）。
//! **两份失败域**也由这条分界分开：[`core::Fail`] 是**上线**那一格（讲客人那一问，折成答码），
//! [`programs::driver::shared::fail::Fail`](programs::driver::shared::fail) 是**下线**那一格（讲这一域死在
//! 起手/常驻的哪一步，报给内核出口）。
//! # 服务面：两个方向放进同一面

