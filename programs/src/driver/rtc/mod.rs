//! rtc::实现侧 — **实时钟驱动域**：`rtc@101000` 的持有者，兼**报时服务**（门牌 `/device/rtc`）。
//!
//! ```text
//!   main.rs     入口（bin）：只剩五步流程
//!   core/       **纯功能**：会话核（事件 → 决定）＋ 那一格 ＋ 形与记号 ＋ 失败域
//!   client.rs   客侧两手（碰内核；与客人 `harness/src/sleeper.rs` 同一份源码）
//!   rtc.rs      设备模块（bin 自己 `mod`——同一份源码不编两遍）
//!   adapt/      住持面（bin）：起手 / 上树 / 门面 / 常驻 / 死法
//! ```
//!
//! **两半的分界**：客人够得着的那一半（[`core`] ＋ [`client`]）住本模块（lib）；只属于这一台
//! 的那一半（`adapt/` ＋ `rtc.rs`）由 bin 自己 `mod`——`PieToken` 只在铸它的那张表里念得出来，
//! 而客人不在这张表里。
//!
//! # 纯与适配的分界
//!
//! ```text
//!   core/    数据 + 决定：那一格、会话核（一问怎么答 / 到点做什么）、形与记号、失败域
//!   adapt/   等、取、喂、执行：组与泊位（内核）、读表与清那一格（设备）、死法（程序出口）
//! ```
//!
//! **"等事件"移不进纯核**：组（`Pile`）是内核的，而纯核的纪律是不出现 `runtime::` ⇒ 常驻
//! 那一圈的**壳**留在 `adapt/resident.rs`；但它的**每一格判定**都在 [`core::Host`]——壳里因此
//! 没有语义 `if`（核吐什么，它就执行什么）。
//!
//! **两份失败域**也由这条分界分开：[`core::Fail`] 是**上线**那一格（讲客人那一问，折成答码），
//! `adapt::fail::Fail` 是**下线**那一格（讲这一域死在起手/常驻的哪一步，报给内核出口）。
//!
//! # 服务面：两个方向放进同一面
//!
//! 那是**本驱动自己的具体协议**（协议层不放服务面：旧 `uart` 协议的死因就是把它放了进去），
//! 故它住本目录：帧形与记号、那一格与失败域在 [`core`]、客侧两手在 [`client`]
//! ——客人与驱动 `use` 的是同一份源码。
//!
//! 两个实例的形状**不一样**——这正是"抽象等第二个实例"要证的那件事：
//!
//! ```text
//!   uart  单向：排空读到什么就交什么（一条字节流；"一行"是终端那侧的约定，客人 `echo`）
//!   rtc   双向：客人问（问时间 / 定闹钟，一问一答、每趟自带一枚回信孔）
//!              + 设备叫（到点把"那一声"推回客人手里，客人 `sleeper`）
//! ```
//!
//! # 为什么是"借一枚回信孔"而不是"从门牌孔原地回话"
//!
//! 门牌那一枚孔是**本域自己开的**：客人没了它不死（寿命边那一句反过来说就是"开者是甲方、
//! 用者是乙方，乙方死了资源不死"，见 `kernel` 的 `gate::cull`）⇒ 闹钟响的时候本域会往一枚
//! 没人取的槽里推、**永远堵在那儿**，而那台设备从此没人排空。客人自己铸一枚孔借过来，
//! "客人还在不在"就由**那一枚孔自己**答（开者退场 ⇒ 它开的资源一起封印），本域既不必探活、
//! 也不必记"客人是谁"——那一格里只有"到点时刻 + 往哪回"。
//!
//! # 照实记：三处想当然被读数打回来
//!
//! 这一台在这个仓里以前没人量过，故本域起手先报一行自证读数（那对纳秒格子读两次），
//! 再靠一行行读数把设备语义坐实。第一版写了三处**想当然**，全被打回来（细节见 `rtc.rs`）：
//!
//! 1. **读时间**：真语义是**低半格那次读把高半格锁存起来** ⇒ 正确读法是**先低后高**。
//! 2. **报警状态**：`ALARM_STATUS` **在到点那一瞬是 0**（它是 `alarm_running`），故本域改用
//!    `IRQ_ENABLED` 与两头的时间读数说话。
//! 3. **写闹钟**：低半格那次写会**当场比较一次** ⇒ 必须先高后低（实测：按旧序写，第一次
//!    武装在目标之前约 99 ms 就报了一次）。
//!
//! 另量到一条：**这一格是电平源**——把 `CLEAR_INTERRUPT` 那一手临时去掉，同一段运行里投递
//! 从 5 次变成 **3093** 次（线一直挂着）。故"清掉那一格"不是客气。
//!
//! # 照实记：自走那一圈撤了
//!
//! 从前本域**每次排空之后立刻再武装一次**（10 Hz 自走）：那时没有客人，那一圈是"这台设备
//! 自己会拉线"的唯一读数。服务面落下之后，**那条读数改由客人的真请求产生**，自走就成了没人
//! 要的机制（"没有读数的机制不落"的反面）——故 `PERIOD_NS` 与启动时那一次武装整条撤掉，
//! 闹钟从此只由客人定。**读数照旧**（`router: line=11` / `rtc: rang n=` 还是由真闹钟产生），
//! 变的是它的**因果**：那一声是客人约来的。
//!
//! # 特权级
//!
//! **U 态**（`plan::assembly::ALL` 里这一行的 `kind`）：读那页寄存器、`claim` / `complete`、持门闩、
//! 铸孔挂组都不需要 S 态——驱动那一档是量出来的（见 `programs/src/driver/uart/mod.rs`）。

