#![no_main]

//! rtc — **第二台设备驱动**：`rtc@101000` 的持有者（设备树里那条 11 号线），兼**报时服务**。
//!
//! 它存在的理由原来是一条**判据**（线那四格、配给、门牌、设备面这一整套，只有 `uart` 一台
//! 真设备走过——**抽象等第二个实例**）。那一刀落完之后，它是**第二个实例走进服务面**的那一台：
//! `uart` 那一面只有一个方向（把排空读到的字节交出去），本面**两个方向都有**（客人问、设备叫）。
//!
//! ```text
//!   1  领配给：`rtc@101000` 那页寄存器（`ONLY`）
//!   2  开图 + **自证**：读两次它的纳秒计数器（两次不同 ⇒ 它真的在走）
//!   3  上板（板看得见本域的死）+ 开树那条会话
//!   4  上树一趟：落门牌 `/device/rtc`（报时服务的入口）+ 登记那条线（11 号线归本域）
//!   5  常驻：**一只组等两个源**
//!        门上有请求（客人借来一枚回信孔）  问时间 → 就地答；定闹钟 → 占住那一格 + 武装设备
//!        线上有投递（设备自己拉的线）      清掉那一格 ⇒ 那一格到点 ⇒ 从那枚孔推"那一声"
//! ```
//!
//! **本文件只剩流程**：每一步的身子住 `adapt/` 那几份（含死法），服务面的判据与照实记在
//! `driver/rtc/mod.rs`；上树那一趟与登记那一趟是**其他驱动也要走的**
//! （`programs::driver::{tree, register}`），故那两段不在这里。
//!
//! 树上的名字只多一处：本域的门牌（`/device/rtc`）。**板只管生死**（不挂牌子），
//! 与 `router` / `uart` 同一条分家。

extern crate alloc;
extern crate programs;

/// 住持面（适配）：起手 / 上树 / 门面 / 常驻 / 死法——**只属于这一台**，故由 bin 自己 `mod`。
mod adapt;

/// 设备面（本域私有：谁的设备谁自己带）。
mod rtc;

use programs::driver::rtc::core::Host;
use runtime::env::debug;

/// 本域那一台：**返回类型就是它的死法**——编号与那句话都在 [`adapt::fail::Fail`] 里
/// （装配那三步 `1`–`3` 由 [`programs::driver::assemble`] 那一族共用，本域自己那几格从 4 起）。
#[programs::entry]
fn main() -> Result<(), adapt::fail::Fail> {
    // 1–3：领配给（按位次归位）→ 开图自证 → 上板 + 开会话。
    let up = adapt::boot::up()?;
    // 4：上树那一趟 + 登记本域那一条线。
    let held = adapt::tree::plate(&up)?;
    // 5：常驻——**会话核**（纯）持那一格与每一格判定，这里只是壳。
    adapt::resident::run(&up, held, &mut Host::new())
}

/// 打一行。调试面是"服务还没起来的嘴"：本域没有控制台，只有它。
fn say(msg: &str) {
    let _ = debug::put(msg);
}
