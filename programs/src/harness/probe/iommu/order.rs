//! 设备与内存之间的次序：本域写下的**数据**（表页 / 描述符 / 命令）与**门铃**之间，
//! 以及**看到完成**与**读回载荷**之间那两次显式栅栏。
//!
//! RISC-V 把访问分成 R/W 与 I/O 两条通道，只写 `fence rw, rw` 管不住设备那一侧，
//! 故这里一律用 `fence iorw, iorw`：本仓第一次真把设备拉进同一条序里。
//! QEMU 单线程 + BQL 下不给栅栏也成立，但那是仿真的事实，不是硬件保证。
//!
//! 栅栏是对称的（前驱 ↔ 后继都在同一条通道上），故只有这一枚：发布前与观察前各来一次。

/// 把本域刚写下的那批字节推到设备与 IOMMU 看得见的地方，并把设备刚写下的那批字节
/// 收进本域的读序。两个方向共用这一枚。
pub fn sync() {
    // SAFETY: 只发一条栅栏，不碰内存、不读写寄存器。
    unsafe { core::arch::asm!("fence iorw, iorw", options(nostack)) }
}
