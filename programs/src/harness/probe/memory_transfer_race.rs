//! 真实多 Hart 确定性交错：管理端驻留在**真在途窗口**里，对端在另一颗 hart 上真登记一次冷缺页。
//!
//! 前面几景（`memory_transfer`／`memory_transfer_tlb`／`memory_transfer_fresh`）
//! 证的都是“同一颗 hart 上的先后”或“某一段窗口真的开着”；本景要证的是另一件事：
//! 一次真移交占槽之后、撤 PTE 之前那一段**内核在途窗口**里，调用者的 `pend` 还持着、
//! `SIE` 是关的、那颗 hart 出不去——就在这一段里，**另一个 Team／另一个 Space**
//! 里的对端能在**另一颗 hart** 上进内核、在自己的空间里真登记一次冷缺页，
//! 而这一次登记被**内核那一侧**真看到（不是程序自己举的牌子）。
//!
//! # 两台与三份来源
//!
//! - **管理端**：引导镜像那一台，Team 0／Space L。它备迁移来源（一份私有分配，
//!   两页：第 0 页是要搬的那一页，第 1 页是目标空槽）与共享控制页（另一份私有分配），
//!   两页各自铸成**共享根**（`UnsealArgs::Pole { shared: true }`），再各授一枚子分支给对端。
//! - **对端**：由管理端经 `Loader` 装载进**另一个 Team**（Space P）的那一台。
//!   它在自己空间里把两条子分支各 `open` 成一条关系：来源那条盖两页，控制页那条盖一页。
//! - **共享控制页**：与迁移范围**分开**的一份来源，两侧映射的是同一张物理页，
//!   寿命到本景收尾；线格式在 [`handshake`]（内核夹具 include 同一份文件）。
//!
//! # 程序序（每一步都只有一种走法）
//!
//! 1. 管理端把第 0 页物化并填上花纹，把共享控制页挂在自己空间里、铸根、授子；
//!    把两枚子分支的号经一道孔递给对端，再 `embark` 它。
//! 2. 对端把两条关系 `open` 出来，先读一次第 0 页（真物化、真发布一条 PTE），
//!    把 `READY` 与它那两个 VA、那一页的和写回控制页，然后等在 `START` 上。
//! 3. 管理端等到 `READY`，把 `TAG`／`MODE`／`STATE=PREPARED` 摆好，发起**真移交**
//!    （第 0 页 → 第 1 页，两端都是同一份根上的窗口）。
//! 4. 占槽之后、撤 PTE 之前，内核夹具（见 `kernel/tests/health/race_scene.rs`）：
//!    按调用者空间读出控制页，核出压着第 0 页的两条关系（自己那条 ＋ **别人空间**那条），
//!    把 `START` 放开，再等**那条别人空间的关系上真的排上了一个等待者**
//!    （`messenger::queued`，有界自旋）；等到了才写 `STATE=ARMED` 返回。
//! 5. 对端看见 `START`，去读第 1 页：那一页此刻是移交留的空位（`Reserved`、
//!    **没有 PTE**），于是那一次读是一次真冷缺页，按这段关系整段等一次。
//! 6. 移交接着撤下两条关系上第 0 页的 PTE（含别人空间那一条）、结算，
//!    再按“这次真动过的关系”放开等待者——对端就是被这一手放开的。
//! 7. 对端重试那一次读：第 1 页现在握着**同一个承载**，于是它读到的是第 0 页那份花纹
//!    （新清零页只会读到 0），把读数写回控制页就正常收工。
//! 8. 管理端核夹具那一步是 `ARMED`、核对端读到的和与第 0 页那份一样，再 join 对端。
//!
//! # 这不是“同刻竞争”的另一种写法
//!
//! 本景**不靠** `with_running` 换调用者冒充并发，也不靠 sleep 或边界上的 spawn-exit：
//! 管理端那一段驻留就在真入口、真事务、真在途窗口里；对端那一手走的是真页错误、
//! 真等待位、真 `Reap`。多 Hart 只有一颗时（`QEMU_SMP=1`）那一手不可能进展：
//! 夹具的有界自旋会超时，`STATE=TIMEOUT`，本景当场红——那正是它该有的样子。

