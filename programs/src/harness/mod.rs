//! 不进产品镜像的一切——探针（只读数）· 试客（量服务）·
//! 压测台（整台替换引导镜像）。
//! # 这一档与产品那一档的界线
//! **产品**（`driver/` / `service/` / `system/` / `user/`）：内核起的那套服务 + 真客人。
//! **测具**（本目录）：**只为了量**而存在的程序。两档同住这一个 crate、同一张链接脚本
//! （`programs/link.ld`，镜像都链在 `IMAGE_BASE = 0x10000`）、同一手 programs::entry。
//! **特权级与"哪几台进哪张镜像"只在 programs::unit 声明**（与产品同一条规矩）：前者是每行的
//! `space`，后者是每行的 `wanted_by`。验收那张列 **6** 份产品 + **6** 份探针 + **6** 位试客（共 18 条）；
//! 台子那张只列台主与它要的受害者。

/// 压测台共用的**测时与空转**（各台互不依赖，共享的只有这一份"怎么量时间"）
/// 它也是本档唯一的共享件：各台都是独立 bin，共用物住本目录顶层、由各 bin 各自
/// `use programs::harness::tick` 取一次。三档各一目录：`probe/`（探针：只读数）· `guest/`（试客
/// 量服务）· `bench/`（压测台：整台替换引导镜像；每台与它的受害者同目录）
pub mod tick;

/// 探针那一档（`probe/`）各台共用的量具：**数一块窗格底下到齐没有**（各族"该有几枚"由
/// 各自的 `Grant::ALL.len()` 说）。各台仍是独立 bin，身子在 `probe/<名>/main.rs`；
/// 共享件住本目录顶层，由各 bin 各自 `use programs::harness::probe::count` 取一次。
pub mod probe;

/// 独立压测镜像共用的执行主体。
pub mod bench;
