//! 链路一步的结果。

/// 链路一步的结果。
///
/// 「完成」与「硬失败」是两件事，而「还没确认」一律是 `Waiting`：无论它是「在期限内
/// 再等一帧」还是「期限到头了」——两种都**保留**这一枚引用，只是后者的凭据得写成
/// 不可用（不冒充已停）。
pub(super) enum Step {
    /// 这一步完成了，接着走下一步。
    Continue,
    /// 这一步要等硬件；没到期限就留到下一帧。
    Waiting,
    /// 硬件没按协议回答 = 这一步没走完，拿不到凭据。
    Failed,
    /// 整条链走完了。
    Done,
}
