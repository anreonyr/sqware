//! 起手走到哪一步。

/// 起手走到哪一步。
///
/// 除了 `Fresh` 与装配，后面每一格都是“要等硬件”的一步：每帧只推一格，
/// 一个帧推完就往下走，要等就留在这一格里。
pub(super) enum Start {
    /// 还没起手。
    Fresh,
    /// 装配完了，等硬件武装：先抬故障队列。
    Faults,
    /// 等命令队列立起来。
    Commands,
    /// 提交 `IOTINVAL` 与一条 `IOFENCE.C`，等本次完成记录。
    Fence,
    /// 编程 `DDTP` 到 1LVL 并回读确认。
    Ddtp,
    /// 置上 bus-master 并回读确认。
    Master,
    /// 武装完了，等交付坐标、放开服务。
    Armed,
    /// 服务已放开，这一轮在跑。
    Running,
    /// 本机没有这台设备（普通产品保持行为）。
    Absent,
    /// 起手失败过：封口不重试（只把子任务收干净）。
    Failed,
}
