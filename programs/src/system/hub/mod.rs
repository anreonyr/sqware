//! hub — **设备账那一族的实现侧**（`prog-hub` 那一台域）。
//!
//! ```text
//!   core    纯：册（Entry / Cell / League）＋ 四格判定 ＋ 取窗        【已落】
//!   server  适配：收整机物料 → 立账 → 上树 → 立盟 → 落 /svc/hub 与 /dev → 三面待客 ＋ 探活
//!   main    入口：起手（`server::serve`）
//! ```
//!
//! **它是服务，不是驱动**：读寄存器、排 FIFO、开除能都不在这里；它只办"这一台归谁"。
//! 设备语义永远在持有那台设备的那一域（`programs/src/driver/…`）。
//!
//! **核心与适配的边界**（与 operator / coalition 同一条）：核心不出现 `runtime::`、不出现
//! `View`、不叫盟册；"主人还答得出吗"是喂进去的一个闭包（`mail::reserve` 那一手在适配层）。
//!
//! **照实记（这一台为什么叫 hub 而它落的是设备账）**：`hub` 是它在树上的那一段名字
//! （`/svc/hub`），协议那一族同住 `protocol::driver::hub`；设备那一轴是它**落的账**
//! （`/dev/<类>/<名>`），不是它的门牌。
//!
//! # 起手那一段是**这台机器上最慢的一件**（实测，真机读数）
//!
//! 它要：读一遍设备树 → 逐类立一枚盟（每类两趟盟册）→ 铸三枚面 ＋ 落 `/svc/hub` →
//! **逐类逐台落 `/dev/<类>/<名>`，每格查回来验一遍**。量出来的两个数：
//!
//! ```text
//!   收物料            system: enrolled 17 supplies for hub      （17 = 15 台设备 ＋ 树 ＋ 门铃）
//!   落格              hub: 17 devices, 9 classes                （9 类各一块 /dev/<类> 窗格）
//!   起手总时长        debug 档约 2.5 s；release 档是它的几分之一
//! ```
//!
//! 于是装配那条线**要等它**（`Setup::Machine` 的第二条通道：它铸那枚孔之前别的台都还没起）
//! ——那不只是一条读数：**先起的先就绪**这条判据在它身上第一次真的花掉了时间。
//!
//! # 三条已知边界（照实写，不是待办）
//!
//! 1. **18 段设备区里它只认 15 段**（内核配对块读数 `handed to root 21 entries`：
//!    18 段 ＋ 树 ＋ 门铃 ＋ 载荷区）：少的那 3 段是 `mmode_resv0/1@80000000`（保留内存：
//!    **没有 `compatible`** ⇒ 不是"某一类设备"）与 `flash@20000000` 的第二段 `reg`
//!    （**一台多段只认首段**：内核按段发门闩，故那一段没有主人）。要收它们得给那两条判据
//!    开口子（"没有 `compatible` 也认" / "多段各认一段"）——**那一天要先有客人**。
//! 2. **debug 档那条时间线更长**：这一台把装配期拉长之后，几位**迟到的测具**在 debug 档下
//!    会把它们那 `MS = 1000` 的额度走满（`sleeper` / `subject` / `member` /
//!    `probe-{denied,lease,owner,control}` 报"没等到"）。**release 档一切照旧**（`scene`
//!    两景全绿）；那条额度是按旧机器定的，要 debug 档读数把它抬到 5 s 即可（实测全绿）。
//! 3. **本域死了以后**：已经认领过的驱动手里有副本、照跑（`presence: false`）；未认领的
//!    没人发得出——`/dev` 那几格的门闩还在树上，但没人答认领。

