//! system::实现侧 — **编排域那一侧**：起一条、看/判、放下、收场。
//!
//! 系统协议的**规范与接口**（正文、判定、服务表、内核 ABI 的帧、子域怎么收配给）住
//! `crates/protocol/src/system/`；**实现方**（编排域怎么把一条服务起起来、怎么监督与收场）
//! 住这里。装配单与"这台机器有哪些服务"住在本域那一份（[`assemble`]）与
//! [`crate::service`]（两个装配者共用的那台机器）。
//!
//! **板那一台也住这里**（[`board`]）：板线程是**编排域里的一枚线程**（不是另一个域）——
//! `root` 那张单上没有 `board` 那一格，起板的只有本域。
//!
//! **三枚内件也住这里**（[`operator`] 持树者 / [`principal`] 名册 / [`coalition`] 盟册；
//! 它们那张**表**在 [`assemble::inner`]）：同一条判据——**谁住编排域，谁住 `system/` 之下**。iii 之后
//! 它们与编排者**共用一份字节**（`prog-system`）、在本域里各占一枚线程，靠 `Spawn` 那一格
//! `args` 分派（[`Role`](crate::service::Role)）；从前它们各是一个程序、各住
//! 本 crate 顶层，这一刀把它们收进来——读者看目录就知道"这三枚与板是同一种
//! 东西"。
//!
//! **机器自述也住这里**（[`machine`]）：单子上那一格写的是类，翻成"哪一台"要读设备树，
//! 而造单子的就是本域（理由见该模块头注）。
//!
//! **内核那一侧也住这里**（照实记：独立那份 `call.rs` 已收掉）：建域 / 产线程 / 塞门闩 /
//! 放行 / 收域 / 判收尾那七手原先另立一份 `call.rs`，而它们的**唯一读者就是 [`server`]** ⇒
//! 并进那个文件（判据与本模块同一条：**谁在说话**——那几手是"适配"这句话的孩子）。
//!
//! **监督相单独一份**（照实记：原先住在 [`server`] 里）：[`server`] 全是**装配期**的事
//! （建域 / 放行 / 等就绪 / 收一枚 / 等它退场），而 [`supervise`] 是**起完之后一直看**——
//! 一个做到"名册最后一条没了"为止，另一个从那一刻开始。两半之间只有两处来往：表里那几格
//! 状态，与 `stop` / `until` 两枚原语。

pub mod assemble;
