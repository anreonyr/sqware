#![no_std]
//! programs — 镜像里装载的程序集合（每个 `src/bin/` 一个）。
//!
//! 本 lib 有两件共享物：
//!   - `entry` —— `_start` + panic 处理，各程序共用；
//!   - `needs` —— **装配契约**（谁要哪几枚门闩、多少权、以什么形态出去）。装配者与收方
//!     共用一份，故"要什么"与"给什么"不可能各抄一遍。
//!
//! **设备侧不回这里**：谁要读设备，谁的目录里放自己的设备模块（`bin/supervisor/plic/`
//! 下的 `plic.rs` / `uart.rs`）——**设备语义各带各的，装配契约才共享**：前者是设备知识，
//! 后者只是两端必须对上的那份约定。
//!
//! 其余驱动侧（名字→线号 / 终端渲染）随旧树一起清了（tag `proto-v1-baseline`），
//! 需要时按新形状写——**不从那一套搬**。
//!
//! `bin/` 里有三个：`prog-root`（装配者）、`prog-plic`（中断面域）、`prog-echo`（调试回显）。

pub mod entry;
pub mod needs;
