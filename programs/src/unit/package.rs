//! Executable image inventory, independent of deployment selection.

#[derive(Clone, Copy)]
pub struct Package {
    pub name: &'static str,
    pub binary: &'static str,
}

macro_rules! package {
    ($name:literal) => {
        Package {
            name: $name,
            binary: concat!("prog-", $name),
        }
    };
}

